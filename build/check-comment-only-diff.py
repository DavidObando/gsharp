#!/usr/bin/env python3
"""Check that a Git diff changes only comments.

For each file that the diff changes, the check removes the comments from the
base version and from the head version, and then compares the code that
remains. The file passes only if that code is identical. A change inside a
string literal is a code change, so it fails.

The comparison ignores only these differences, and only outside string
literals:

  - spaces and tabs at the end of a line;
  - a line that contained only a comment (the check deletes it);
  - a run of blank lines that contained a deleted comment line (the check
    keeps one blank line), and blank lines at the start or end of the file.
    A run of blank lines with no comment stays as it is, because it can be
    data (a multi-line YAML plain scalar);
  - the spaces next to a comment inside a line. The check removes a comment
    and the spaces next to it. Between two characters that could join into
    one token, it leaves one space, so `a/**/b` does not become `ab`.

A comment that spans lines leaves one line break, because the line break can
end a statement. A line that ends in a backslash continues on the next line,
so the check never deletes or merges the line after it.

Supported files: .gs (G#), .cs (C#), .py (Python, through the standard
tokenize module), .sh and .bash (shell), .yml and .yaml (YAML). The check
fails closed: it reports a failure for an unsupported file type, for an added,
deleted, renamed or copied file, for a mode change, for a file that is not
UTF-8 text, and for source that it cannot tokenize with confidence.

Some grammar is out of scope, so the check also fails closed on it:

  - C#: a comment or string that spans a preprocessor line, and U+0085,
    U+2028 or U+2029;
  - shell: `case` inside `$(...)`, a backslash-newline that does not follow a
    space or a tab, a `$` or a backtick in a heredoc delimiter, a backslash
    inside a double-quoted heredoc delimiter, a body line that ends in a
    backslash in a heredoc with an unquoted delimiter, and any carriage
    return;
  - YAML: a comment after an open quote that the scanner read as plain text,
    a block scalar with only blank lines, and an explicit indentation
    indicator;
  - all: a carriage return without a line feed, and a byte-order mark (at the
    start of a Python file, or anywhere in a shell or YAML file).

A change of line ending (CRLF and LF) is a code change.

Some comments are instructions to a tool: `<auto-generated`, `ReSharper
disable`, `shellcheck`, `noqa`, `type: ignore`, `pylint:`, `pyright:`,
`mypy:`, `isort:`, `fmt: on/off/skip`, `pragma:` and `yaml-language-server:`
(see DIRECTIVE). The check treats them as code, so a change to one fails. A
shebang line and a Python encoding line are code too. A Python docstring is a
string literal, so a change to one fails. In YAML, the body of a block scalar
(`run: |`) is string content, so a change to a shell comment inside it fails.

Usage: check-comment-only-diff.py --base REV [--head REV] [PATH ...]

The base is compared through its merge base with the head, like
`git diff BASE...HEAD`. PATH limits the check to those paths.

Exit status: 0 if every changed file changes only comments, 1 if a file fails,
2 for a usage or Git error.
"""

from __future__ import annotations

import argparse
import io
import re
import subprocess
import sys
import tokenize
from dataclasses import dataclass, field
from pathlib import Path

CODE = 0
STRING = 1
COMMENT = 2


class ScanError(Exception):
    """The scanner cannot tokenize the input with confidence."""

    def __init__(self, text: str, pos: int, message: str) -> None:
        line = text.count("\n", 0, min(pos, len(text))) + 1
        super().__init__(f"line {line}: {message}")


# Comments that a tool reads. The check keeps them as code, so a change fails.
DIRECTIVE = re.compile(
    r"<auto-generated"
    r"|\bReSharper\s+(disable|restore)\b"
    r"|\bshellcheck\s"
    r"|\bnoqa\b"
    r"|\btype:\s*ignore\b"
    r"|\b(pylint|pyright|mypy|isort):"
    r"|\bfmt:\s*(on|off|skip)\b"
    r"|\bpragma:"
    r"|\byaml-language-server:",
    re.IGNORECASE,
)
PY_CODING = re.compile(r"^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+")

_EOL = re.compile(r"[\r\n]")


def _eol(text: str, pos: int) -> int:
    """Return the index of the next line break at or after pos, or len(text)."""
    m = _EOL.search(text, pos)
    return m.start() if m else len(text)


def _mark(mask: bytearray, start: int, end: int, cls: int) -> None:
    mask[start:end] = bytes([cls]) * (end - start)


# --------------------------------------------------------------------------
# G#. This follows src/Core/CodeAnalysis/Syntax/Lexer.gs: `//` and `///` run
# to the end of the line; `/* */` does not nest; "..." has backslash escapes,
# `$$`, `$name` and `${...}` holes; a backtick string is raw and can span
# lines; '...' is one character or one escape. A hole is scanned like
# ScanInterpolationHoleCore: it tracks ()[]{}, skips nested "..." and '...'
# literals (recursively) and `//` and `/* */` comments, and ends at the first
# unmatched `}`. The whole string token, holes included, is STRING.
# --------------------------------------------------------------------------

_GS_CODE_SPECIAL = re.compile(r"[/\"`']")
_GS_STRING_SPECIAL = re.compile(r"[\"\\$\r\n]")
_GS_MAX_HOLE_DEPTH = 32  # Lexer.MaxInterpolationNestingDepth


def classify_gs(text: str) -> bytearray:
    mask = bytearray(len(text))
    pos = 0
    while True:
        m = _GS_CODE_SPECIAL.search(text, pos)
        if m is None:
            return mask
        pos = m.start()
        c = text[pos]
        if c == "/":
            nxt = text[pos + 1 : pos + 2]
            if nxt == "/":
                end = _eol(text, pos)
                _mark(mask, pos, end, COMMENT)
                pos = end
            elif nxt == "*":
                end = text.find("*/", pos + 2)
                if end < 0:
                    raise ScanError(text, pos, "unterminated /* comment")
                _mark(mask, pos, end + 2, COMMENT)
                pos = end + 2
            else:
                pos += 1
        elif c == '"':
            end = _gs_string_end(text, pos)
            _mark(mask, pos, end, STRING)
            pos = end
        elif c == "`":
            end = text.find("`", pos + 1)
            if end < 0:
                raise ScanError(text, pos, "unterminated raw string")
            _mark(mask, pos, end + 1, STRING)
            pos = end + 1
        else:
            end = _gs_char_end(text, pos)
            _mark(mask, pos, end, STRING)
            pos = end


def _gs_string_end(text: str, start: int) -> int:
    """Return the index after the closing quote of the string at start."""
    n = len(text)
    pos = start + 1
    while True:
        m = _GS_STRING_SPECIAL.search(text, pos)
        if m is None or text[m.start()] in "\r\n":
            raise ScanError(text, start, "unterminated string")
        pos = m.start()
        c = text[pos]
        if c == '"':
            return pos + 1
        if c == "\\":
            if pos + 1 >= n or text[pos + 1] in "\r\n":
                raise ScanError(text, pos, "backslash at the end of a string line")
            pos += 2
        elif text.startswith("$$", pos):
            pos += 2
        elif text.startswith("${", pos):
            pos = _gs_hole_end(text, pos + 2, 1) + 1
        else:
            pos += 1


def _gs_hole_end(text: str, pos: int, depth: int) -> int:
    """Return the index of the `}` that closes the hole whose body starts at pos."""
    if depth > _GS_MAX_HOLE_DEPTH:
        raise ScanError(text, pos, "interpolation nested too deeply")
    n = len(text)
    hole = pos
    stack: list[str] = []
    while pos < n:
        c = text[pos]
        if c in "\"'":
            pos = _gs_hole_literal_end(text, pos, depth)
            continue
        if c == "/" and text.startswith("//", pos):
            pos = _eol(text, pos)
            continue
        if c == "/" and text.startswith("/*", pos):
            end = text.find("*/", pos + 2)
            if end < 0:
                break
            pos = end + 2
            continue
        if c in "([{":
            stack.append(c)
        elif c == ")":
            if stack and stack[-1] == "(":
                stack.pop()
        elif c == "]":
            if stack and stack[-1] == "[":
                stack.pop()
        elif c == "}":
            if not stack:
                return pos
            if stack[-1] == "{":
                stack.pop()
        pos += 1
    raise ScanError(text, hole, "unterminated interpolation hole")


def _gs_hole_literal_end(text: str, start: int, depth: int) -> int:
    """Skip a "..." or '...' literal inside a hole, like SkipInterpolationNestedLiteral."""
    n = len(text)
    quote = text[start]
    pos = start + 1
    while pos < n and text[pos] not in "\r\n":
        c = text[pos]
        if c == "\\" and pos + 1 < n:
            pos += 2
            continue
        if c == quote:
            return pos + 1
        if quote == '"' and text.startswith("${", pos):
            pos = _gs_hole_end(text, pos + 2, depth + 1) + 1
            continue
        pos += 1
    raise ScanError(text, start, "unterminated literal inside an interpolation hole")


_HEX = set("0123456789abcdefABCDEF")


def _gs_char_end(text: str, start: int) -> int:
    """Return the index after the closing quote of the char literal at start."""
    n = len(text)
    pos = start + 1
    if pos >= n or text[pos] in "\r\n'":
        raise ScanError(text, start, "empty or unterminated char literal")
    if text[pos] == "\\":
        pos += 1
        if pos >= n or text[pos] in "\r\n":
            raise ScanError(text, start, "unterminated char literal")
        digits = {"x": 4, "u": 4, "U": 8}.get(text[pos], 0)
        pos += 1
        while digits and pos < n and text[pos] in _HEX:
            pos += 1
            digits -= 1
    else:
        pos += 1
    if pos >= n or text[pos] != "'":
        raise ScanError(text, start, "char literal with more than one character")
    return pos + 1


# --------------------------------------------------------------------------
# C#. Handles `//`, `/* */`, preprocessor lines (code), "..." with escapes,
# @"..." verbatim, $"..." and $@"..." interpolation with {{ and }} escapes,
# """raw""" strings with $$ interpolation, and char literals.
# --------------------------------------------------------------------------

_CS_CODE_SPECIAL = re.compile(r"[/\"'@$#]")
_CS_STRING_PREFIX = re.compile(r"(\$+@?|@\$+|@)?(\"+)")


def classify_cs(text: str) -> bytearray:
    mask = bytearray(len(text))
    pos = 0
    while True:
        m = _CS_CODE_SPECIAL.search(text, pos)
        if m is None:
            _cs_check_directives(text, mask)
            return mask
        pos = m.start()
        c = text[pos]
        if c == "/":
            pos = _cs_comment(text, pos, mask)
        elif c == "#":
            line_start = text.rfind("\n", 0, pos) + 1
            if text[line_start:pos].strip():
                raise ScanError(text, pos, "unexpected '#' outside a string")
            pos = _eol(text, pos)  # a preprocessor line is code
        else:
            end = _cs_literal_end(text, pos)
            if end is None:
                pos += 1  # @identifier or a lone $
            else:
                _mark(mask, pos, end, STRING)
                pos = end


_CS_DIRECTIVE_LINE = re.compile(r"\n[^\S\n]*#")  # any whitespace but a line break


def _cs_check_directives(text: str, mask: bytearray) -> None:
    """Fail if a comment or string spans a preprocessor line.

    The scanner does not evaluate #if. In a disabled region, C# ignores a `/*`
    or a quote, so a comment or string that crosses a directive line can hide
    active code. The check does not try to model that.
    """
    for cls in (COMMENT, STRING):
        for start, end in _runs(mask, cls):
            m = _CS_DIRECTIVE_LINE.search(text, start, end)
            if m:
                raise ScanError(text, m.start() + 1, "a comment or string spans a preprocessor line")


def _cs_comment(text: str, pos: int, mask: bytearray | None) -> int:
    nxt = text[pos + 1 : pos + 2]
    if nxt == "/":
        end = _eol(text, pos)
    elif nxt == "*":
        close = text.find("*/", pos + 2)
        if close < 0:
            raise ScanError(text, pos, "unterminated /* comment")
        end = close + 2
    else:
        return pos + 1
    if mask is not None:
        _mark(mask, pos, end, COMMENT)
    return end


def _cs_literal_end(text: str, start: int) -> int | None:
    """Return the index after the string or char literal at start, or None."""
    if text[start] == "'":
        return _cs_char_end(text, start)
    m = _CS_STRING_PREFIX.match(text, start)
    if m is None:
        return None
    prefix = m.group(1) or ""
    dollars = prefix.count("$")
    verbatim = "@" in prefix
    quotes = len(m.group(2))
    body = m.start(2)
    if quotes >= 3 and not verbatim:
        return _cs_raw_end(text, start, body + quotes, quotes, dollars)
    if verbatim:
        return _cs_verbatim_end(text, start, body + 1, dollars > 0)
    return _cs_regular_end(text, start, body + 1, dollars > 0)


def _cs_char_end(text: str, start: int) -> int:
    pos = start + 1
    if text.startswith("\\", pos):
        close = text.find("'", pos + 2)
        if close < 0 or close - start > 11 or _EOL.search(text, start, close):
            raise ScanError(text, start, "bad char literal")
        return close + 1
    if text[pos + 1 : pos + 2] != "'" or text[pos : pos + 1] in ("", "\r", "\n", "'"):
        raise ScanError(text, start, "bad char literal")
    return pos + 2


def _cs_regular_end(text: str, start: int, pos: int, interpolated: bool) -> int:
    n = len(text)
    while pos < n:
        c = text[pos]
        if c in "\r\n":
            break
        if c == "\\":
            pos += 2
            continue
        if c == '"':
            return pos + 1
        if interpolated and c in "{}":
            if text.startswith(c * 2, pos):
                pos += 2
                continue
            if c == "{":
                pos = _cs_hole_end(text, pos + 1, 1) + 1
                continue
        pos += 1
    raise ScanError(text, start, "unterminated string")


def _cs_verbatim_end(text: str, start: int, pos: int, interpolated: bool) -> int:
    n = len(text)
    while pos < n:
        c = text[pos]
        if c == '"':
            if text.startswith('""', pos):
                pos += 2
                continue
            return pos + 1
        if interpolated and c in "{}":
            if text.startswith(c * 2, pos):
                pos += 2
                continue
            if c == "{":
                pos = _cs_hole_end(text, pos + 1, 1) + 1
                continue
        pos += 1
    raise ScanError(text, start, "unterminated verbatim string")


def _run_length(text: str, pos: int, ch: str) -> int:
    end = pos
    while end < len(text) and text[end] == ch:
        end += 1
    return end - pos


def _cs_raw_end(text: str, start: int, pos: int, quotes: int, dollars: int) -> int:
    n = len(text)
    while pos < n:
        c = text[pos]
        if c == '"':
            run = _run_length(text, pos, '"')
            if run > quotes:
                raise ScanError(text, pos, "quote run longer than the raw string delimiter")
            if run == quotes:
                return pos + run
            pos += run
            continue
        if dollars and c == "{":
            run = _run_length(text, pos, "{")
            if run >= 2 * dollars:
                raise ScanError(text, pos, "too many braces in a raw interpolated string")
            pos += run
            if run >= dollars:
                pos = _cs_hole_end(text, pos, dollars) + dollars
            continue
        pos += 1
    raise ScanError(text, start, "unterminated raw string")


def _cs_hole_end(text: str, pos: int, close: int) -> int:
    """Return the index of the closing brace run of the hole whose body starts at pos."""
    n = len(text)
    hole = pos
    stack: list[str] = []
    while pos < n:
        c = text[pos]
        if c == "/" and text[pos + 1 : pos + 2] in ("/", "*"):
            pos = _cs_comment(text, pos, None)
            continue
        if c in "\"'@$":
            end = _cs_literal_end(text, pos)
            pos = pos + 1 if end is None else end
            continue
        if c in "([{":
            stack.append(c)
        elif c == ")":
            if not stack or stack.pop() != "(":
                raise ScanError(text, pos, "unbalanced ')' in an interpolation hole")
        elif c == "]":
            if not stack or stack.pop() != "[":
                raise ScanError(text, pos, "unbalanced ']' in an interpolation hole")
        elif c == "}":
            if not stack:
                if not text.startswith("}" * close, pos):
                    raise ScanError(text, pos, "bad closing brace in an interpolation hole")
                return pos
            if stack.pop() != "{":
                raise ScanError(text, pos, "unbalanced '}' in an interpolation hole")
        elif c == ":" and not stack:
            if text.startswith("::", pos):
                pos += 2
                continue
            # A format clause runs to the closing brace.
            end = text.find("}", pos)
            if end < 0 or _EOL.search(text, pos, end):
                raise ScanError(text, pos, "unterminated format clause")
            pos = end
            continue
        pos += 1
    raise ScanError(text, hole, "unterminated interpolation hole")


# --------------------------------------------------------------------------
# Python, through the standard tokenize module.
# --------------------------------------------------------------------------

_FSTRING_STARTS = {getattr(tokenize, n) for n in ("FSTRING_START", "TSTRING_START") if hasattr(tokenize, n)}
_FSTRING_ENDS = {getattr(tokenize, n) for n in ("FSTRING_END", "TSTRING_END") if hasattr(tokenize, n)}


def classify_py(text: str) -> bytearray:
    mask = bytearray(len(text))
    line_starts = [0]
    for m in re.finditer("\n", text):
        line_starts.append(m.end())

    def offset(row_col: tuple[int, int]) -> int:
        row, col = row_col
        if row - 1 >= len(line_starts):
            return len(text)
        return line_starts[row - 1] + col

    open_fstrings: list[int] = []
    try:
        for tok in tokenize.generate_tokens(io.StringIO(text).readline):
            start, end = offset(tok.start), offset(tok.end)
            if tok.type in _FSTRING_STARTS:
                open_fstrings.append(start)
            elif tok.type in _FSTRING_ENDS:
                _mark(mask, open_fstrings.pop(), end, STRING)
            elif tok.type == tokenize.STRING:
                _mark(mask, start, end, STRING)
            elif tok.type == tokenize.COMMENT and not open_fstrings:
                row = tok.start[0]
                if row == 1 and tok.string.startswith("#!"):
                    continue  # shebang
                if row <= 2 and PY_CODING.match(tok.line):
                    continue  # encoding declaration
                _mark(mask, start, end, COMMENT)
    except (tokenize.TokenError, SyntaxError) as error:
        raise ScanError(text, len(text), f"Python tokenize failed: {error}") from error
    return mask


# --------------------------------------------------------------------------
# Shell. `#` starts a comment only at the start of a word. Quotes, $'...',
# ${...}, $(...), backticks and heredoc bodies are handled; heredoc bodies and
# quoted strings are STRING. The first line's `#!` is code.
# --------------------------------------------------------------------------

_SH_WORD_BREAK = set(" \t\n;&|()<>")


def classify_sh(text: str) -> bytearray:
    mask = bytearray(len(text))
    _sh_scan(text, 0, mask, nested=False)
    return mask


def _sh_scan(text: str, pos: int, mask: bytearray, nested: bool) -> int:
    """Scan code from pos. If nested, stop after the `)` that closes $( and return its end.

    A word starts after an unescaped space, tab, line break or one of
    `;&|()<>`. A backslash-newline is removed before words are split, so it
    does not start a word. An escaped character, a quoted string, `${...}` and
    a backtick substitution are STRING, so normalization cannot change them.
    """
    n = len(text)
    start = pos
    depth = 0
    word_start = True
    brackets = 0  # unclosed `[` on this line, as in an array subscript
    pending: list[tuple[str, bool, bool]] = []
    while pos < n:
        c = text[pos]
        if c == "\\":
            if text.startswith("\\\n", pos):
                pos += 2  # a line continuation: the word goes on
                continue
            _mark(mask, pos, min(pos + 2, n), STRING)
            pos += 2
            word_start = False
            continue
        if c == "\n":
            pos += 1
            word_start = True
            brackets = 0
            if pending:
                pos = _sh_heredocs(text, pos, mask, pending)
                pending = []
            continue
        if c == "#":
            # A `#` after `;`, `|`, `(` and the like is a comment to Bash, but
            # the same text is pattern data in `@(a|#b)` and `case` patterns.
            # The check keeps it as code, so a change to it fails.
            if word_start and (pos == 0 or text[pos - 1] in " \t\n"):
                if brackets:
                    # Bash allows spaces and `#` in a subscript: a[ #k]=v.
                    raise ScanError(text, pos, "a `#` after an unclosed `[`")
                end = _eol(text, pos)
                if not (pos == 0 and text.startswith("#!")):
                    _mark(mask, pos, end, COMMENT)
                pos = end
            else:
                pos += 1
            continue
        at_word = word_start
        word_start = c in _SH_WORD_BREAK
        if c == "[":
            brackets += 1
        elif c == "]":
            brackets = max(0, brackets - 1)
        if c == "'":
            end = text.find("'", pos + 1)
            if end < 0:
                raise ScanError(text, pos, "unterminated single-quoted string")
            _mark(mask, pos, end + 1, STRING)
            pos = end + 1
            continue
        if c == "$":
            nxt = text[pos + 1 : pos + 2]
            if nxt == "'":
                end = _sh_ansi_c_end(text, pos + 1)
                _mark(mask, pos, end, STRING)
                pos = end
            elif nxt == '"':
                end = _sh_dquote_end(text, pos + 1, mask)
                _mark(mask, pos, end, STRING)
                pos = end
            elif nxt == "(":
                pos = _sh_scan(text, pos + 2, mask, nested=True)
            elif nxt == "{":
                end = _sh_param_end(text, pos + 2, mask)
                _mark(mask, pos, end, STRING)
                pos = end
            else:
                # A `$` that starts no expansion is a literal character. The
                # next character is scanned on its own; after `$` it never
                # starts a word, so `$#` is not a comment.
                pos += 1
            continue
        if c == "`":
            end = _sh_backtick_end(text, pos + 1)
            _mark(mask, pos, end, STRING)
            pos = end
            continue
        if c == '"':
            end = _sh_dquote_end(text, pos, mask)
            _mark(mask, pos, end, STRING)
            pos = end
            continue
        if c == "<" and text.startswith("<<<", pos):
            pos += 3  # a here-string, not a heredoc
            word_start = False
            continue
        if c == "<" and text.startswith("<<", pos):
            pos, heredoc = _sh_heredoc_word(text, pos + 2)
            pending.append(heredoc)
            word_start = False
            continue
        # _check_line_breaks rejects a continuation inside a word, so the
        # raw text here is the word that Bash reads.
        if nested and at_word and re.match(r"case\b", text[pos : pos + 5]):
            # A case pattern ends in an unmatched `)`, which would end $( early.
            raise ScanError(text, pos, "case inside $(...)")
        if nested:
            if c == "(":
                depth += 1
            elif c == ")":
                if depth == 0:
                    if pending:
                        raise ScanError(text, pos, "heredoc inside $(...) on one line")
                    return pos + 1
                depth -= 1
        pos += 1
    if nested:
        raise ScanError(text, start, "unterminated $(")
    if pending:
        raise ScanError(text, pos, "heredoc without a body")
    return pos


def _sh_ansi_c_end(text: str, quote: int) -> int:
    pos = quote + 1
    while pos < len(text):
        if text[pos] == "\\":
            pos += 2
            continue
        if text[pos] == "'":
            return pos + 1
        pos += 1
    raise ScanError(text, quote, "unterminated $'...' string")


def _sh_dquote_end(text: str, quote: int, mask: bytearray) -> int:
    pos = quote + 1
    while pos < len(text):
        c = text[pos]
        if c == "\\":
            pos += 2
            continue
        if c == '"':
            return pos + 1
        if c == "$" and text.startswith("$(", pos):
            pos = _sh_scan(text, pos + 2, mask, nested=True)
            continue
        if c == "$" and text.startswith("${", pos):
            pos = _sh_param_end(text, pos + 2, mask)
            continue
        if c == "`":
            pos = _sh_backtick_end(text, pos + 1)
            continue
        pos += 1
    raise ScanError(text, quote, "unterminated double-quoted string")


def _sh_param_end(text: str, pos: int, mask: bytearray) -> int:
    start = pos
    depth = 1
    while pos < len(text):
        c = text[pos]
        if c == "\\":
            pos += 2
            continue
        if c == "$" and text.startswith("$'", pos):
            pos = _sh_ansi_c_end(text, pos + 1)
            continue
        if c == "'":
            end = text.find("'", pos + 1)
            if end < 0:
                break
            pos = end + 1
            continue
        if c == '"':
            pos = _sh_dquote_end(text, pos, mask)
            continue
        if c == "`":
            pos = _sh_backtick_end(text, pos + 1)
            continue
        if c == "$" and text.startswith("$(", pos):
            pos = _sh_scan(text, pos + 2, mask, nested=True)
            continue
        if c == "$" and text.startswith("${", pos):
            depth += 1
            pos += 2
            continue
        if c == "}":
            depth -= 1
            if depth == 0:
                return pos + 1
        pos += 1
    raise ScanError(text, start, "unterminated ${")


def _sh_backtick_end(text: str, pos: int) -> int:
    start = pos
    while pos < len(text):
        if text[pos] == "\\":
            pos += 2
            continue
        if text[pos] == "`":
            return pos + 1
        pos += 1
    raise ScanError(text, start, "unterminated backtick")


def _sh_heredoc_word(text: str, pos: int) -> tuple[int, tuple[str, bool, bool]]:
    """Read the delimiter after `<<`. Return the end and (delimiter, strip_tabs, quoted)."""
    strip_tabs = text.startswith("-", pos)
    if strip_tabs:
        pos += 1
    while pos < len(text) and text[pos] in " \t":
        pos += 1
    word = []
    quoted = False
    while pos < len(text) and text[pos] not in _SH_WORD_BREAK:
        c = text[pos]
        quoted = quoted or c in "'\"\\"
        if c in "$`":
            # $(...), `...`, $'...' and $"..." need parsing that the scanner
            # does not do.
            raise ScanError(text, pos, "a $ or backtick in a heredoc delimiter")
        if c in "'\"":
            end = text.find(c, pos + 1)
            if end < 0:
                raise ScanError(text, pos, "unterminated heredoc delimiter")
            if c == '"' and "\\" in text[pos + 1 : end]:
                raise ScanError(text, pos, "a backslash in a double-quoted heredoc delimiter")
            word.append(text[pos + 1 : end])
            pos = end + 1
        elif c == "\\":
            word.append(text[pos + 1 : pos + 2])
            pos += 2
        else:
            word.append(c)
            pos += 1
    delimiter = "".join(word)
    if not delimiter:
        raise ScanError(text, pos, "heredoc without a delimiter")
    return pos, (delimiter, strip_tabs, quoted)


def _sh_heredocs(text: str, pos: int, mask: bytearray, pending: list[tuple[str, bool, bool]]) -> int:
    for delimiter, strip_tabs, quoted in pending:
        body = pos
        while True:
            if pos >= len(text):
                raise ScanError(text, body, f"heredoc not closed by {delimiter!r}")
            end = text.find("\n", pos)
            line_end = len(text) if end < 0 else end
            line = text[pos:line_end].rstrip("\r")
            if (line.lstrip("\t") if strip_tabs else line) == delimiter:
                _mark(mask, body, pos, STRING)
                pos = line_end + 1 if end >= 0 else line_end
                break
            if not quoted and line.endswith("\\"):
                # Bash joins this line with the next one before it looks for
                # the delimiter. The scanner does not model that.
                raise ScanError(text, pos, "backslash at the end of an unquoted heredoc line")
            pos = line_end + 1
    return pos


# --------------------------------------------------------------------------
# YAML. `#` starts a comment at the start of a line or after whitespace,
# outside quoted scalars. A quote starts a quoted scalar only where a scalar
# can start. Block scalar (| and >) bodies are STRING.
# --------------------------------------------------------------------------

_YAML_BLOCK = re.compile(r"[|>]([+-]?)([0-9]?)([+-]?)[ \t]*(#.*)?$")


def classify_yaml(text: str) -> bytearray:
    mask = bytearray(len(text))
    lines = re.findall(r"[^\n]*\n|[^\n]+$", text)
    starts = []
    offset = 0
    for line in lines:
        starts.append(offset)
        offset += len(line)
    i = 0
    quote: str | None = None  # an open quoted scalar that spans lines
    flow = 0  # the depth of [ and { flow collections, which can span lines
    while i < len(lines):
        line = lines[i]
        base = starts[i]
        body = line.rstrip("\r\n")
        indent = len(body) - len(body.lstrip(" "))
        pos = 0 if quote else indent
        at_scalar_start = quote is None
        if quote:
            pos = _yaml_quoted_end(text, base, body, 0, quote, mask)
            if pos < 0:
                _mark(mask, base, base + len(line), STRING)
                i += 1
                continue
            quote = None
        block: re.Match[str] | None = None
        if pos == 0 and re.match(r"(---|\.\.\.)([ \t]|$)", body):
            pos = 3  # a document marker; a root scalar can follow it
            at_scalar_start = True
        plain_quote: str | None = None  # an open quote that the scanner read as plain text
        while pos < len(body):
            c = body[pos]
            if c == "#" and (pos == 0 or body[pos - 1] in " \t"):
                if plain_quote:
                    # The open quote may start a scalar in a form that the
                    # scanner does not know, and then this `#` is data.
                    raise ScanError(text, base + pos, "a quote before a comment on a plain line")
                comment = body[pos:]
                if not DIRECTIVE.search(comment):
                    _mark(mask, base + pos, base + len(body), COMMENT)
                break
            if c in "'\"" and at_scalar_start:
                end = _yaml_quoted_end(text, base, body, pos + 1, c, mask, opened=pos)
                if end < 0:
                    quote = c
                    _mark(mask, base + pos, base + len(line), STRING)
                    break
                pos = end
                at_scalar_start = False
                continue
            if c in "|>" and at_scalar_start:
                block = _YAML_BLOCK.match(body, pos)
                if block is None:
                    raise ScanError(text, base + pos, "unrecognized block scalar header")
                comment = block.group(4)
                if comment and not DIRECTIVE.search(comment):
                    _mark(mask, base + block.start(4), base + len(body), COMMENT)
                break
            if c in " \t":
                pos += 1
                continue
            if c in "'\"" and not (c == "'" and body[pos - 1 : pos].isalnum() and body[pos + 1 : pos + 2].isalnum()):
                # Not at a scalar start, and not an apostrophe in a word.
                plain_quote = None if plain_quote == c else plain_quote or c
            if c in "!&" and at_scalar_start:
                # A tag or an anchor comes before the scalar that it names.
                while pos < len(body) and body[pos] not in " \t":
                    pos += 1
                continue
            after = body[pos + 1 : pos + 2]
            if c in "[{,":
                flow += c != ","
                at_scalar_start = True
            elif c in "]}":
                flow = max(0, flow - 1)
                at_scalar_start = False
            elif c in "-?" and after in ("", " ", "\t") and at_scalar_start:
                at_scalar_start = True
            elif c == ":" and (after in ("", " ", "\t", "'", '"') or flow):
                # In a flow collection, and before a quote, a value can follow
                # the colon with no space: {"k":"v"}.
                at_scalar_start = True
            else:
                at_scalar_start = False
            pos += 1
        i += 1
        if block is not None:
            if block.group(2):
                raise ScanError(text, base, "explicit block indentation indicator")
            i = _yaml_block_body(text, lines, starts, i, indent, mask)
    if quote:
        raise ScanError(text, len(text), "unterminated quoted scalar")
    return mask


def _yaml_quoted_end(
    text: str, base: int, body: str, pos: int, quote: str, mask: bytearray, opened: int = 0
) -> int:
    """Mark a quoted scalar on this line. Return the index after it, or -1 if it continues."""
    while pos < len(body):
        c = body[pos]
        if quote == '"' and c == "\\":
            pos += 2
            continue
        if c == quote:
            if quote == "'" and body.startswith("''", pos):
                pos += 2
                continue
            _mark(mask, base + opened, base + pos + 1, STRING)
            return pos + 1
        pos += 1
    return -1


def _yaml_block_body(
    text: str, lines: list[str], starts: list[int], i: int, parent: int, mask: bytearray
) -> int:
    """Mark the body of a block scalar that starts at line i. Return the next line index."""
    content: int | None = None
    j = i
    while j < len(lines):
        body = lines[j].rstrip("\r\n")
        if body.strip() == "":
            j += 1
            continue
        indent = len(body) - len(body.lstrip(" "))
        if content is None:
            if indent <= parent:
                break
            content = indent
        if indent < content:
            break
        j += 1
    if content is None and j > i:
        # The value is only line breaks, and the line break before the next
        # node may be part of it. The scanner does not model that.
        raise ScanError(text, starts[i], "a block scalar with only blank lines")
    # Every body line is STRING, the trailing whitespace-only lines too: a line
    # with more spaces than the body indentation is data, even with clipping.
    if j > i:
        # The line break after the last body line stays code if another node
        # follows, so that node is a line of its own. At the end of the file,
        # that line break is the final character of the value, so it is STRING.
        last_line = lines[j - 1]
        end = starts[j - 1] + len(last_line)
        if j < len(lines):
            end -= len(last_line) - len(last_line.rstrip("\r\n"))
        _mark(mask, starts[i], end, STRING)
    return j


