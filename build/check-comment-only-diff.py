#!/usr/bin/env python3
"""Check that a Git diff changes only comments.

For each file that the diff changes, the check reads the base version and the
head version with a real lexer or parser for the language, and compares what
remains when the comments are removed. The file passes only if that is
identical. A change inside a string literal is a code change, so it fails.

Supported files:

  .gs           The compiler's own lexer, through build/gstokens. The check
                compares every token that is not whitespace or a comment (kind
                and text), and whether a line break comes before it.
  .py           The standard tokenize module. The check compares every token
                except comments and blank-line (NL) tokens. A docstring is a
                string literal, so a change to one fails with "docstring
                changed: review manually".
  .yml, .yaml   PyYAML. The check compares the parse events of the two
                versions (each scalar's value, style, tag and anchor, and the
                structure). If PyYAML is not installed, the check fails.

Every other file type fails with "unsupported: review manually". That
includes shell scripts and C#: their grammar needs a real parser, and the
repository has none that the check can call.

The check also fails for an added, deleted, renamed or copied file, for a mode
change, for a file that is not UTF-8 text, for a change to a byte-order mark,
and for source that the lexer or parser rejects.

Some comments are instructions to a tool (see DIRECTIVE), for example
`// <auto-generated/>`, `# noqa` and `# type: ignore`. The check treats them
as code, so a change to one fails. A shebang line and a Python encoding line
are code too.

Usage: check-comment-only-diff.py --base REV [--head REV] [--repo DIR]
                                  [--gstokens DLL | --no-build] [PATH ...]

The base is compared through its merge base with the head, like
`git diff BASE...HEAD`. PATH limits the check to those paths. The check builds
build/gstokens/GsTokens.gsproj (Release) before it reads a .gs file, unless
--gstokens names a built gstokens.dll or --no-build is given.

Exit status: 0 if every changed file changes only comments, 1 if a file fails,
2 for a usage or Git error.
"""

from __future__ import annotations

import argparse
import ast
import io
import json
import re
import subprocess
import sys
import tempfile
import tokenize
from dataclasses import dataclass
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GSTOKENS_PROJECT = REPO / "build" / "gstokens" / "GsTokens.gsproj"
GSTOKENS_DLL = REPO / "out" / "bin" / "Release" / "GsTokens" / "gstokens.dll"

UNSUPPORTED = "unsupported: review manually"

# Comments that a tool reads. The check keeps them as code, so a change fails.
DIRECTIVE = re.compile(
    r"<auto-generated"
    r"|\bReSharper\s+(disable|restore)\b"
    r"|\bshellcheck\s"
    r"|\bnoqa\b"
    r"|\btype:\s*ignore\b"
    r"|\b(pylint|pyright|mypy|isort):"
    r"|\bfmt:\s*(on|off|skip)\b"
    r"|\bpragma:"
    r"|\byaml-language-server:",
    re.IGNORECASE,
)
PY_CODING = re.compile(r"^[ \t\f]*#.*?coding[:=][ \t]*[-\w.]+")


class CheckError(Exception):
    """The check cannot compare the file, so the file fails."""


@dataclass(frozen=True)
class Token:
    kind: str
    text: str
    line: int
    line_break_before: bool = False

    def key(self) -> tuple[str, str, bool]:
        return (self.kind, self.text, self.line_break_before)

    def show(self) -> str:
        text = self.text if len(self.text) <= 80 else self.text[:77] + "..."
        return f"{self.kind} {text!r}" + (" (after a line break)" if self.line_break_before else "")


def first_difference(base: list[Token], head: list[Token]) -> int | None:
    """Return the index of the first token that differs, or None."""
    for k in range(max(len(base), len(head))):
        if k >= len(base) or k >= len(head) or base[k].key() != head[k].key():
            return k
    return None


def describe(base: list[Token], head: list[Token], k: int) -> str:
    b = base[k] if k < len(base) else None
    h = head[k] if k < len(head) else None
    shown_b = b.show() if b else "(no token)"
    shown_h = h.show() if h else "(no token)"
    line_b = b.line if b else None
    line_h = h.line if h else None
    if b and h and b.kind == h.kind and b.text != h.text:
        # A token can be long and span lines (a raw string), so show the part
        # around the first character that differs, and the line that holds it.
        at = next((i for i in range(min(len(b.text), len(h.text))) if b.text[i] != h.text[i]), min(len(b.text), len(h.text)))
        first = max(0, at - 40)
        prefix = "..." if first else ""
        shown_b = f"{b.kind} {prefix}{b.text[first : at + 40]!r}"
        shown_h = f"{h.kind} {prefix}{h.text[first : at + 40]!r}"
        line_b = b.line + b.text.count("\n", 0, at)
        line_h = h.line + h.text.count("\n", 0, at)
    where_b = f"base line {line_b}" if b else "end of base"
    where_h = f"head line {line_h}" if h else "end of head"
    return f"code differs at {where_b} / {where_h}:\n      base: {shown_b}\n      head: {shown_h}"


# --------------------------------------------------------------------------
# G#, through the compiler's lexer.
# --------------------------------------------------------------------------

GS_TRIVIA = {"WhitespaceToken", "CommentToken", "DocumentationCommentToken"}


class GsLexer:
    """Runs build/gstokens, which prints the tokens that the G# lexer reads."""

    def __init__(self, dll: Path) -> None:
        self.dll = dll

    @staticmethod
    def build() -> GsLexer:
        result = subprocess.run(
            ["dotnet", "build", str(GSTOKENS_PROJECT), "--configuration", "Release", "--nologo", "-v:q"],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )
        if result.returncode != 0:
            tail = "\n".join(result.stdout.strip().splitlines()[-5:])
            raise CheckError(f"cannot build {GSTOKENS_PROJECT.relative_to(REPO)}:\n{tail}")
        return GsLexer(GSTOKENS_DLL)

    def lex(self, texts: list[str]) -> list[list[Token]]:
        """Return the significant tokens of each text, in order."""
        if not self.dll.is_file():
            raise CheckError(f"{self.dll} does not exist; build {GSTOKENS_PROJECT.relative_to(REPO)}")
        with tempfile.TemporaryDirectory(prefix="comment-only-") as scratch:
            paths = []
            for k, text in enumerate(texts):
                path = Path(scratch) / f"{k}.gs"
                path.write_bytes(text.encode("utf-8"))
                paths.append(str(path))
            try:
                result = subprocess.run(
                    ["dotnet", str(self.dll), *paths], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True
                )
            except OSError as error:
                raise CheckError(f"cannot run dotnet: {error}") from error
        if result.returncode != 0:
            raise CheckError(f"the G# token tool failed: {result.stderr.strip()[-500:]}")
        out = []
        for entry in json.loads(result.stdout):
            if entry["errors"]:
                raise CheckError(f"the G# lexer reports: {entry['errors'][0]}")
            out.append(gs_significant(entry["tokens"]))
        return out


def gs_significant(raw: list[list]) -> list[Token]:
    """Drop whitespace and comments, and record where a line break came before a token."""
    tokens = []
    line_break = False
    for kind, line, text in raw:
        directive = kind != "WhitespaceToken" and DIRECTIVE.search(text)
        if kind in GS_TRIVIA and not directive:
            line_break = line_break or "\n" in text or "\r" in text
            continue
        tokens.append(Token(kind, text, line, line_break))
        line_break = False
    return tokens


# --------------------------------------------------------------------------
# Python, through the standard tokenize module.
# --------------------------------------------------------------------------

_FSTRING_STARTS = {getattr(tokenize, n) for n in ("FSTRING_START", "TSTRING_START") if hasattr(tokenize, n)}
_FSTRING_ENDS = {getattr(tokenize, n) for n in ("FSTRING_END", "TSTRING_END") if hasattr(tokenize, n)}


def py_tokens(text: str) -> list[Token]:
    tokens = []
    depth = 0  # f-string nesting; a comment inside one is part of the string
    try:
        for tok in tokenize.generate_tokens(io.StringIO(text).readline):
            if tok.type in _FSTRING_STARTS:
                depth += 1
            elif tok.type in _FSTRING_ENDS:
                depth -= 1
            elif tok.type == tokenize.NL:
                continue
            elif tok.type == tokenize.COMMENT and depth == 0:
                row = tok.start[0]
                keep = (
                    (row == 1 and tok.string.startswith("#!"))
                    or (row <= 2 and PY_CODING.match(tok.line))
                    or DIRECTIVE.search(tok.string)
                )
                if not keep:
                    continue
            tokens.append(Token(tokenize.tok_name[tok.type], tok.string, tok.start[0]))
    except (tokenize.TokenError, SyntaxError) as error:
        raise CheckError(f"Python tokenize failed: {error}") from error
    return tokens


def py_docstring_lines(text: str) -> set[int]:
    """Return the first line of each docstring, or an empty set if ast fails."""
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return set()
    lines = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
                lines.add(first.lineno)
    return lines


def compare_py(base_text: str, head_text: str) -> str | None:
    base, head = py_tokens(base_text), py_tokens(head_text)
    k = first_difference(base, head)
    if k is None:
        return None
    if k < len(base) and k < len(head) and base[k].kind == head[k].kind == "STRING":
        if base[k].line in py_docstring_lines(base_text) or head[k].line in py_docstring_lines(head_text):
            return f"docstring changed: review manually (base line {base[k].line} / head line {head[k].line})"
    return describe(base, head, k)


# --------------------------------------------------------------------------
# YAML, through PyYAML.
# --------------------------------------------------------------------------

_YAML_FIELDS = ("anchor", "tag", "implicit", "value", "style", "explicit", "version", "tags", "flow_style")


def yaml_events(text: str) -> list[Token]:
    try:
        import yaml
    except ImportError as error:
        raise CheckError("PyYAML is not installed, so the check cannot parse YAML: review manually") from error
    try:
        events = list(yaml.parse(text, Loader=yaml.SafeLoader))
    except yaml.YAMLError as error:
        raise CheckError(f"YAML parse failed: {error}") from error
    out = []
    for event in events:
        fields = repr(tuple(getattr(event, name, None) for name in _YAML_FIELDS))
        line = event.start_mark.line + 1 if event.start_mark else 0
        out.append(Token(type(event).__name__, fields, line))
    return out


# --------------------------------------------------------------------------
# Comparison.
# --------------------------------------------------------------------------

SUPPORTED = {".gs", ".py", ".yml", ".yaml"}


def compare(path: str, base: str, head: str, lexer: GsLexer | None = None) -> str | None:
    """Return None if base and head differ only in comments, else the reason."""
    suffix = Path(path).suffix.lower()
    if suffix not in SUPPORTED:
        return UNSUPPORTED
    if base.startswith("\ufeff") != head.startswith("\ufeff"):
        return "the byte-order mark changed"
    try:
        if suffix == ".gs":
            if lexer is None:
                raise CheckError("no G# lexer is available")
            base_tokens, head_tokens = lexer.lex([base, head])
        elif suffix == ".py":
            return compare_py(base, head)
        else:
            base_tokens, head_tokens = yaml_events(base), yaml_events(head)
    except CheckError as error:
        return f"cannot compare: {error}"
    k = first_difference(base_tokens, head_tokens)
    return None if k is None else describe(base_tokens, head_tokens, k)


# --------------------------------------------------------------------------
# Git.
# --------------------------------------------------------------------------


def _git(repo: Path, *args: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE
    ).stdout


@dataclass
class Change:
    status: str
    old_mode: str
    new_mode: str
    old_blob: str
    new_blob: str
    path: str


def changed_files(repo: Path, base: str, head: str, paths: list[str]) -> list[Change]:
    merge_base = _git(repo, "merge-base", base, head).decode().strip()
    raw = _git(repo, "diff", "--raw", "-z", "--no-renames", "--no-abbrev", merge_base, head, "--", *paths)
    fields = raw.decode("utf-8", "surrogateescape").split("\0")
    changes = []
    k = 0
    while k + 1 < len(fields) and fields[k]:
        meta = fields[k].lstrip(":").split()
        changes.append(Change(meta[4], meta[0], meta[1], meta[2], meta[3], fields[k + 1]))
        k += 2
    return changes


def precheck(change: Change) -> str | None:
    """Return the reason that a change cannot be checked, or None."""
    if change.status != "M":
        kind = {"A": "added", "D": "deleted", "T": "type changed"}.get(change.status, change.status)
        return f"file is {kind}; only modified files can be checked"
    if change.old_mode != change.new_mode:
        return f"mode changed from {change.old_mode} to {change.new_mode}"
    if change.new_mode not in ("100644", "100755"):
        return f"not a regular file (mode {change.new_mode})"
    if Path(change.path).suffix.lower() not in SUPPORTED:
        return UNSUPPORTED
    return None


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base", required=True, help="base revision, for example origin/main")
    parser.add_argument("--head", default="HEAD", help="head revision (default: HEAD)")
    parser.add_argument("--repo", type=Path, default=Path.cwd(), help="Git repository (default: current directory)")
    parser.add_argument("--gstokens", type=Path, help="a built gstokens.dll (default: build it)")
    parser.add_argument("--no-build", action="store_true", help="use the built gstokens.dll without building it")
    parser.add_argument("paths", nargs="*", help="limit the check to these paths")
    args = parser.parse_args(argv)
    try:
        changes = changed_files(args.repo, args.base, args.head, args.paths)
    except (OSError, subprocess.CalledProcessError) as error:
        detail = getattr(error, "stderr", b"") or b""
        print(f"git failed: {error} {detail.decode(errors='replace').strip()}")
        return 2
    if not changes:
        print("No changed files.")
        return 0

    lexer: GsLexer | None = None
    lexer_error: str | None = None
    if any(Path(c.path).suffix.lower() == ".gs" and precheck(c) is None for c in changes):
        if args.gstokens:
            lexer = GsLexer(args.gstokens)
        elif args.no_build:
            lexer = GsLexer(GSTOKENS_DLL)
        else:
            try:
                lexer = GsLexer.build()
            except (OSError, CheckError) as error:
                lexer_error = f"cannot compare: {error}"

    failed = 0
    for change in changes:
        reason = precheck(change)
        if reason is None:
            try:
                base = _git(args.repo, "cat-file", "blob", change.old_blob).decode("utf-8")
                head = _git(args.repo, "cat-file", "blob", change.new_blob).decode("utf-8")
            except UnicodeDecodeError:
                reason = "not UTF-8 text"
            except subprocess.CalledProcessError as error:
                reason = f"git failed: {error}"
            else:
                is_gs = Path(change.path).suffix.lower() == ".gs"
                reason = lexer_error if is_gs and lexer_error else compare(change.path, base, head, lexer)
        if reason is None:
            print(f"PASS {change.path}")
        else:
            failed += 1
            print(f"FAIL {change.path}: {reason}")
    passed = len(changes) - failed
    print(f"{passed} of {len(changes)} changed files change only comments; {failed} failed.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
