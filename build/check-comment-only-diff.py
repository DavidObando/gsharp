CLASSIFIERS = {
    ".gs": classify_gs,
    ".cs": classify_cs,
    ".py": classify_py,
    ".sh": classify_sh,
    ".bash": classify_sh,
    ".yml": classify_yaml,
    ".yaml": classify_yaml,
}

# Comments that a tool reads, for the languages whose scanner does not check
# them itself. YAML checks them in classify_yaml.
_DIRECTIVE_LANGUAGES = {".gs", ".cs", ".py", ".sh", ".bash"}


# Line breaks that the scanners do not model. C# also ends a line at U+0085,
# U+2028 and U+2029. Bash treats a carriage return as data, not as part of a
# line break. Every scanner splits lines at LF, so a CR without an LF fails.
_BARE_CR = re.compile(r"\r(?!\n)")
# Bash removes a backslash-newline before it reads tokens, so one inside a word
# (`$\<newline>#x`, `<\<newline><EOF`) hides the token from the scanner. Only a
# continuation after a space or a tab is supported.
_SH_WORD_SPLIT = re.compile(r"(?<![ \t])\\\n")
_CS_LINE_BREAKS = re.compile("[\u0085\u2028\u2029]")


def _check_line_breaks(suffix: str, text: str) -> None:
    if text.startswith("\ufeff") and suffix == ".py":
        raise ScanError(text, 0, "a byte-order mark")
    if suffix in (".sh", ".bash", ".yml", ".yaml") and "\ufeff" in text:
        # YAML allows a mark before each document.
        raise ScanError(text, text.index("\ufeff"), "a byte-order mark")
    m = _SH_WORD_SPLIT.search(text) if suffix in (".sh", ".bash") else None
    if m:
        raise ScanError(text, m.start(), "a line continuation inside a word")
    m = _BARE_CR.search(text)
    if m:
        raise ScanError(text, m.start(), "a carriage return without a line feed")
    if suffix in (".sh", ".bash") and "\r" in text:
        raise ScanError(text, text.index("\r"), "a carriage return in a shell script")
    m = _CS_LINE_BREAKS.search(text) if suffix == ".cs" else None
    if m:
        raise ScanError(text, m.start(), f"line break U+{ord(m.group()):04X}")


def classify(path: str, text: str) -> bytearray:
    """Classify each character of text as CODE, STRING or COMMENT."""
    suffix = Path(path).suffix.lower()
    classifier = CLASSIFIERS.get(suffix)
    if classifier is None:
        raise KeyError(suffix)
    _check_line_breaks(suffix, text)
    mask = classifier(text)
    if suffix in _DIRECTIVE_LANGUAGES:
        for start, end in _runs(mask, COMMENT):
            if DIRECTIVE.search(text, start, end):
                _mark(mask, start, end, CODE)
    return mask


def _runs(mask: bytearray, cls: int) -> list[tuple[int, int]]:
    runs = []
    pos = mask.find(cls)
    while pos >= 0:
        end = pos
        while end < len(mask) and mask[end] == cls:
            end += 1
        runs.append((pos, end))
        pos = mask.find(cls, end)
    return runs


@dataclass
class Line:
    number: int
    text: str = ""
    had_comment: bool = False
    ends_in_string: bool = False
    pieces: list[tuple[str, str]] = field(default_factory=list)


# Whitespace that the check strips at the end of a line. A carriage return, a
# form feed and a vertical tab are not in the set: Bash treats them as data, so
# a change to one fails. _finish removes the CR before a line break and keeps a
# mark, so a line-ending change fails too.
_SPACE = " \t"


# A removed comment between two characters becomes one space, so `a/**/b`
# stays two tokens. No space is needed after an opening bracket or before a
# closing bracket, a comma or a semicolon: no G#, C# or Python token joins
# them to a neighbor. Other characters can join (G# reads `?[` as one token).
_OPENERS = set("([{")
_CLOSERS = set(")]},;")


def _finish(line: Line) -> Line:
    out: list[tuple[str, str]] = []
    site = False  # a comment was removed and no code has followed it yet
    for kind, piece in line.pieces:
        if kind == "x":
            line.had_comment = True
            if not site and any(k == "s" or p.strip(_SPACE) for k, p in out):
                while out and out[-1][0] == "c" and not out[-1][1].rstrip(_SPACE):
                    out.pop()
                if out and out[-1][0] == "c":
                    out[-1] = ("c", out[-1][1].rstrip(_SPACE))
            site = True
            continue
        if site and kind == "c":
            piece = piece.lstrip(_SPACE)
            if not piece:
                continue
        if site:
            left = out[-1][1][-1:] if out else ""
            if left and left not in _SPACE and left not in _OPENERS and piece[0] not in _CLOSERS:
                out.append(("c", " "))
            site = False
        out.append((kind, piece))
    carriage_return = bool(out) and out[-1][0] == "c" and out[-1][1].endswith("\r")
    if carriage_return:
        out[-1] = ("c", out[-1][1][:-1])
    while out and out[-1][0] == "c":
        stripped = out[-1][1].rstrip(_SPACE)
        if stripped:
            out[-1] = ("c", stripped)
            break
        out.pop()
    line.ends_in_string = bool(out) and out[-1][0] == "s"
    line.text = "".join(p for _, p in out)
    if carriage_return and line.text:
        line.text += "\r"
    line.pieces = []
    return line


def normalize(text: str, mask: bytearray) -> list[Line]:
    """Remove comments and return the code lines that the comparison uses."""
    lines: list[Line] = []
    number = 1
    current = Line(number)
    pos = 0
    n = len(text)
    while pos < n:
        cls = mask[pos]
        end = pos + 1
        while end < n and mask[end] == cls:
            end += 1
        segment = text[pos:end]
        breaks = segment.count("\n")
        if cls == COMMENT:
            current.pieces.append(("x", ""))
            if breaks:
                # A comment that spans lines keeps one line break.
                lines.append(_finish(current))
                number += breaks
                current = Line(number, pieces=[("x", "")])
        elif cls == STRING:
            current.pieces.append(("s", segment))
            number += breaks
        else:
            parts = segment.split("\n")
            for k, part in enumerate(parts):
                if k:
                    lines.append(_finish(current))
                    number += 1
                    current = Line(number)
                if part:
                    current.pieces.append(("c", part))
        pos = end
    lines.append(_finish(current))

    # A group is a run of lines that are blank or held only a comment. The
    # check deletes the comment lines of a group and keeps at most one blank
    # line. A group without a comment line stays as it is, because a blank line
    # can be data (for example inside a multi-line YAML plain scalar). Blank
    # lines at the start and end of the file are dropped.
    result: list[Line] = []
    group: list[Line] = []
    keep_next = False

    def flush(at_end: bool) -> None:
        if not result or at_end:
            pass  # the start or the end of the file
        elif any(line.had_comment for line in group):
            blanks = [line for line in group if not line.had_comment]
            result.extend(blanks[:1])
        else:
            result.extend(group)
        group.clear()

    for line in lines:
        if line.text == "" and not keep_next:
            group.append(line)
        else:
            flush(at_end=False)
            result.append(line)
        keep_next = line.text.rstrip("\r").endswith("\\") and not line.ends_in_string
    flush(at_end=True)
    return result


def compare(path: str, base: str, head: str) -> str | None:
    """Return None if base and head differ only in comments, else the reason."""
    try:
        base_mask = classify(path, base)
    except ScanError as error:
        return f"cannot tokenize the base version: {error}"
    try:
        head_mask = classify(path, head)
    except ScanError as error:
        return f"cannot tokenize the head version: {error}"
    base_lines = normalize(base, base_mask)
    head_lines = normalize(head, head_mask)
    for k in range(max(len(base_lines), len(head_lines))):
        b = base_lines[k] if k < len(base_lines) else None
        h = head_lines[k] if k < len(head_lines) else None
        if b is not None and h is not None and b.text == h.text:
            continue
        # A line can hold a multi-line string, so find the first differing
        # character and report the source line that holds it.
        bt = b.text if b else ""
        ht = h.text if h else ""
        at = next((i for i in range(min(len(bt), len(ht))) if bt[i] != ht[i]), min(len(bt), len(ht)))
        where_b = f"base line {b.number + bt.count(chr(10), 0, at)}" if b else "end of base"
        where_h = f"head line {h.number + ht.count(chr(10), 0, at)}" if h else "end of head"
        return (
            f"code differs at {where_b} / {where_h}:\n"
            f"      base: {_show(b, at)}\n"
            f"      head: {_show(h, at)}"
        )
    return None


def _show(line: Line | None, at: int) -> str:
    """Show the part of the line around index at."""
    if line is None:
        return "(no line)"
    text = line.text
    first = max(text.rfind("\n", 0, at) + 1, at - 60)
    shown = repr(text[first : first + 120])
    return ("..." if first else "") + shown


