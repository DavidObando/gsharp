#!/usr/bin/env python3
"""Check that a Git diff changes only comments in G# files.

For each changed .gs file, the check reads the base version and the head
version with the compiler's own lexer (SyntaxTree.ParseTokens, through
build/gstokens) and compares the tokens that are not whitespace or comments.
The file passes only if they are identical. A change inside a string literal
is a code change, so it fails.

For each kept token, the check also compares what separates it from the
previous kept token: nothing, spaces, or a line break. The parser reads this:
it requires `a?(x)` to touch (a null-conditional call) and it ends some
constructs at a line break. The first token of a file has no separator, so a
header comment can be added or removed.

Comments that the toolchain reads are compared too, and a change to one fails
with "directive comment changed: review manually":

  - a `///` doc comment, through the compiler's own code (build/gstokens
    calls DocumentationAttacher, GSharpDocumentationParser and
    DocumentationXmlWriter). The check compares the XML that the compiler
    writes for each block with the text removed (element names, attributes
    such as `name` and `cref`, and nesting), the declaration that the
    compiler attaches the block to (or the place of a floating block), and
    the diagnostics that DocumentationValidator reports from the syntax tree
    (floating doc comments and unknown tags). The prose may change.
  - a `//` comment that starts with `<auto-generated`. No G# tool reads it
    (analyzers detect generated code by the .g.gs file name), but other tools
    and readers do, and the files that carry it are generated.

The G# lexer has no other comment that changes behavior: no shebang, no
pragma, and no formatter on/off marker.

Every other file type fails with "unsupported: review manually", .py, .yml,
.sh and .cs included. The check also fails for an added, deleted, renamed or
copied file, for a mode change, for a file that is not UTF-8 text, for a
change to a byte-order mark, and for source that the lexer rejects.

Usage: check-comment-only-diff.py --base REV [--head REV] [--repo DIR]
                                  [--gstokens DLL | --no-build] [PATH ...]

The base is compared through its merge base with the head, like
`git diff BASE...HEAD`. PATH limits the check to those paths. The check builds
build/gstokens/GsTokens.gsproj (Release) before it reads a .gs file, unless
--gstokens names a built gstokens.dll or --no-build is given.

Exit status: 0 if every changed file changes only comments, 1 if a file fails,
2 for a usage or Git error.
"""

from __future__ import annotations

import argparse
import bisect
import json
import re
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from xml.etree import ElementTree

REPO = Path(__file__).resolve().parent.parent
GSTOKENS_PROJECT = REPO / "build" / "gstokens" / "GsTokens.gsproj"
GSTOKENS_DLL = REPO / "out" / "bin" / "Release" / "GsTokens" / "gstokens.dll"

UNSUPPORTED = "unsupported: review manually"
DIRECTIVE_CHANGED = "directive comment changed: review manually"

GENERATED_MARKER = re.compile(r"^//\s*<auto-generated")


class CheckError(Exception):
    """The check cannot compare the file, so the file fails."""


@dataclass(frozen=True)
class Token:
    """A token that the comparison keeps.

    `before` is what separates the token from the previous kept token:
    "start" for the first one, then "none", "space" or "line break".
    """

    kind: str
    text: str
    line: int
    before: str
    position: int = 0

    def key(self) -> tuple[str, str, str]:
        return (self.kind, self.text, self.before)

    def show(self) -> str:
        text = self.text if len(self.text) <= 80 else self.text[:77] + "..."
        return f"{self.kind} {text!r} (after: {self.before})"


def first_difference(base: list[Token], head: list[Token]) -> int | None:
    """Return the index of the first token that differs, or None."""
    for k in range(max(len(base), len(head))):
        if k >= len(base) or k >= len(head) or base[k].key() != head[k].key():
            return k
    return None


def describe(base: list[Token], head: list[Token], k: int) -> str:
    b = base[k] if k < len(base) else None
    h = head[k] if k < len(head) else None
    if (b and b.kind == "CommentToken") or (h and h.kind == "CommentToken"):
        where = f"base line {b.line}" if b else f"head line {h.line}" if h else "?"
        return f"{DIRECTIVE_CHANGED} (an `<auto-generated` comment at {where})"
    shown_b = b.show() if b else "(no token)"
    shown_h = h.show() if h else "(no token)"
    line_b = b.line if b else None
    line_h = h.line if h else None
    if b and h and b.kind == h.kind and b.text != h.text:
        # A token can be long and span lines (a raw string), so show the part
        # around the first character that differs, and the line that holds it.
        at = next((i for i in range(min(len(b.text), len(h.text))) if b.text[i] != h.text[i]), min(len(b.text), len(h.text)))
        first = max(0, at - 40)
        prefix = "..." if first else ""
        shown_b = f"{b.kind} {prefix}{b.text[first : at + 40]!r}"
        shown_h = f"{h.kind} {prefix}{h.text[first : at + 40]!r}"
        line_b = b.line + b.text.count("\n", 0, at)
        line_h = h.line + h.text.count("\n", 0, at)
    where_b = f"base line {line_b}" if b else "end of base"
    where_h = f"head line {line_h}" if h else "end of head"
    return f"code differs at {where_b} / {where_h}:\n      base: {shown_b}\n      head: {shown_h}"


# --------------------------------------------------------------------------
# The G# lexer.
# --------------------------------------------------------------------------

GS_TRIVIA = {"WhitespaceToken", "CommentToken", "DocumentationCommentToken"}


class GsLexer:
    """Runs build/gstokens, which prints the tokens that the G# lexer reads."""

    def __init__(self, dll: Path) -> None:
        self.dll = dll

    @staticmethod
    def build() -> GsLexer:
        result = subprocess.run(
            ["dotnet", "build", str(GSTOKENS_PROJECT), "--configuration", "Release", "--nologo", "-v:q"],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )
        if result.returncode != 0:
            tail = "\n".join(result.stdout.strip().splitlines()[-5:])
            raise CheckError(f"cannot build {GSTOKENS_PROJECT.relative_to(REPO)}:\n{tail}")
        return GsLexer(GSTOKENS_DLL)

    def lex(self, texts: list[str]) -> list[tuple[list[Token], list[Doc], list[str]]]:
        """Return the kept tokens, the doc comments and the doc diagnostics of each text."""
        if not self.dll.is_file():
            raise CheckError(f"{self.dll} does not exist; build {GSTOKENS_PROJECT.relative_to(REPO)}")
        with tempfile.TemporaryDirectory(prefix="comment-only-") as scratch:
            paths = []
            for k, text in enumerate(texts):
                path = Path(scratch) / f"{k}.gs"
                path.write_bytes(text.encode("utf-8"))
                paths.append(str(path))
            try:
                result = subprocess.run(
                    ["dotnet", str(self.dll), *paths], stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True
                )
            except OSError as error:
                raise CheckError(f"cannot run dotnet: {error}") from error
        if result.returncode != 0:
            detail = (result.stderr.strip() or result.stdout.strip())[-500:]
            raise CheckError(f"the G# token tool failed with exit code {result.returncode}: {detail}")
        out = []
        for entry in json.loads(result.stdout):
            if entry["errors"]:
                raise CheckError(f"the G# lexer reports: {entry['errors'][0]}")
            tokens = gs_significant(entry["tokens"])
            out.append((tokens, gs_docs(entry["docs"], tokens), entry["docDiagnostics"]))
        return out


def gs_significant(raw: list[list]) -> list[Token]:
    """Drop whitespace and comments, and record what came between kept tokens."""
    tokens: list[Token] = []
    separator = "none"
    for kind, line, text, position in raw:
        kept_comment = kind == "CommentToken" and GENERATED_MARKER.match(text) is not None
        if kind in GS_TRIVIA and not kept_comment:
            if "\n" in text or "\r" in text:
                separator = "line break"
            elif separator == "none":
                separator = "space"
            continue
        tokens.append(Token(kind, text, line, separator if tokens else "start", position))
        # A `//` comment token holds its own line break.
        separator = "line break" if kept_comment and text.endswith(("\n", "\r")) else "none"
    return tokens


@dataclass(frozen=True)
class Doc:
    """A `///` block as the compiler reads it.

    `target` is the index of the kept token that the block documents, or of
    the first kept token after a floating block. `skeleton` is the XML that
    the compiler writes for the block, with the text removed: element names,
    attributes (`name`, `cref`, `href`, ...) and nesting.
    """

    line: int
    target: int
    attached: bool
    skeleton: str

    def key(self) -> tuple[int, bool, str]:
        return (self.target, self.attached, self.skeleton)


def _skeleton(xml: str) -> str:
    try:
        root = ElementTree.fromstring(f"<doc>{xml}</doc>")
    except ElementTree.ParseError as error:
        raise CheckError(f"cannot read the compiler's doc XML: {error}") from error

    def shape(element: ElementTree.Element) -> str:
        attributes = "".join(f" {k}={v!r}" for k, v in sorted(element.attrib.items()))
        return f"<{element.tag}{attributes}>" + "".join(shape(child) for child in element) + f"</{element.tag}>"

    return "".join(shape(child) for child in root)


def gs_docs(entries: list[dict], tokens: list[Token]) -> list[Doc]:
    positions = [t.position for t in tokens]
    docs = []
    for entry in entries:
        attached = entry["declaration"] >= 0
        anchor = entry["declaration"] if attached else entry["end"]
        docs.append(Doc(entry["line"], bisect.bisect_left(positions, anchor), attached, _skeleton(entry["xml"])))
    return docs


def compare_docs(base: list[Doc], head: list[Doc]) -> str | None:
    for k in range(max(len(base), len(head))):
        b = base[k] if k < len(base) else None
        h = head[k] if k < len(head) else None
        if b is not None and h is not None and b.key() == h.key():
            continue
        def show(d: Doc | None) -> str:
            if d is None:
                return "(no doc comment)"
            where = "documents" if d.attached else "floats before"
            return f"line {d.line}, {where} token {d.target}: {d.skeleton}"
        return f"{DIRECTIVE_CHANGED} (a /// doc comment):\n      base: {show(b)}\n      head: {show(h)}"
    return None


# --------------------------------------------------------------------------
# Comparison.
# --------------------------------------------------------------------------

SUPPORTED = {".gs"}


def compare(path: str, base: str, head: str, lexer: GsLexer | None = None) -> str | None:
    """Return None if base and head differ only in comments, else the reason."""
    if Path(path).suffix.lower() not in SUPPORTED:
        return UNSUPPORTED
    if base.startswith("\ufeff") != head.startswith("\ufeff"):
        return "the byte-order mark changed"
    try:
        if lexer is None:
            raise CheckError("no G# lexer is available")
        (base_tokens, base_docs, base_notes), (head_tokens, head_docs, head_notes) = lexer.lex([base, head])
    except CheckError as error:
        return f"cannot compare: {error}"
    k = first_difference(base_tokens, head_tokens)
    if k is not None:
        return describe(base_tokens, head_tokens, k)
    reason = compare_docs(base_docs, head_docs)
    # The order of the diagnostics carries no meaning; the blocks are compared above.
    if reason is None and sorted(base_notes) != sorted(head_notes):
        reason = (
            f"{DIRECTIVE_CHANGED} (the compiler's doc-comment diagnostics differ):\n"
            f"      base: {base_notes}\n      head: {head_notes}"
        )
    return reason


# --------------------------------------------------------------------------
# Git.
# --------------------------------------------------------------------------


def _git(repo: Path, *args: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(repo), *args], check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE
    ).stdout


@dataclass
class Change:
    status: str
    old_mode: str
    new_mode: str
    old_blob: str
    new_blob: str
    path: str


def changed_files(repo: Path, base: str, head: str, paths: list[str]) -> list[Change]:
    merge_base = _git(repo, "merge-base", base, head).decode().strip()
    raw = _git(repo, "diff", "--raw", "-z", "--no-renames", "--no-abbrev", merge_base, head, "--", *paths)
    fields = raw.decode("utf-8", "surrogateescape").split("\0")
    changes = []
    k = 0
    while k + 1 < len(fields) and fields[k]:
        meta = fields[k].lstrip(":").split()
        changes.append(Change(meta[4], meta[0], meta[1], meta[2], meta[3], fields[k + 1]))
        k += 2
    return changes


def precheck(change: Change) -> str | None:
    """Return the reason that a change cannot be checked, or None."""
    if change.status != "M":
        kind = {"A": "added", "D": "deleted", "T": "type changed"}.get(change.status, change.status)
        return f"file is {kind}; only modified files can be checked"
    if change.old_mode != change.new_mode:
        return f"mode changed from {change.old_mode} to {change.new_mode}"
    if change.new_mode not in ("100644", "100755"):
        return f"not a regular file (mode {change.new_mode})"
    if Path(change.path).suffix.lower() not in SUPPORTED:
        return UNSUPPORTED
    return None


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--base", required=True, help="base revision, for example origin/main")
    parser.add_argument("--head", default="HEAD", help="head revision (default: HEAD)")
    parser.add_argument("--repo", type=Path, default=Path.cwd(), help="Git repository (default: current directory)")
    parser.add_argument("--gstokens", type=Path, help="a built gstokens.dll (default: build it)")
    parser.add_argument("--no-build", action="store_true", help="use the built gstokens.dll without building it")
    parser.add_argument("paths", nargs="*", help="limit the check to these paths")
    args = parser.parse_args(argv)
    try:
        changes = changed_files(args.repo, args.base, args.head, args.paths)
    except (OSError, subprocess.CalledProcessError) as error:
        detail = getattr(error, "stderr", b"") or b""
        print(f"git failed: {error} {detail.decode(errors='replace').strip()}")
        return 2
    if not changes:
        print("No changed files.")
        return 0

    lexer: GsLexer | None = None
    lexer_error: str | None = None
    if any(Path(c.path).suffix.lower() == ".gs" and precheck(c) is None for c in changes):
        if args.gstokens:
            lexer = GsLexer(args.gstokens)
        elif args.no_build:
            lexer = GsLexer(GSTOKENS_DLL)
        else:
            try:
                lexer = GsLexer.build()
            except (OSError, CheckError) as error:
                lexer_error = f"cannot compare: {error}"

    failed = 0
    for change in changes:
        reason = precheck(change)
        if reason is None:
            try:
                base = _git(args.repo, "cat-file", "blob", change.old_blob).decode("utf-8")
                head = _git(args.repo, "cat-file", "blob", change.new_blob).decode("utf-8")
            except UnicodeDecodeError:
                reason = "not UTF-8 text"
            except subprocess.CalledProcessError as error:
                reason = f"git failed: {error}"
            else:
                is_gs = Path(change.path).suffix.lower() == ".gs"
                reason = lexer_error if is_gs and lexer_error else compare(change.path, base, head, lexer)
        if reason is None:
            print(f"PASS {change.path}")
        else:
            failed += 1
            print(f"FAIL {change.path}: {reason}")
    passed = len(changes) - failed
    print(f"{passed} of {len(changes)} changed files change only comments; {failed} failed.")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
