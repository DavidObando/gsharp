#!/usr/bin/env python3
"""Generate the bounded, typed ADR-0210 CLR-copy bridge helpers."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "src/Sdk/Gsharp.Runtime.Values/FixedArrays.ClrArrayCopies.g.gs"


def carrier(length: int) -> str:
    if length < 2:
        return f'{"Empty" if length == 0 else "Leaf"}[T]'
    left = length // 2
    return f"Branch[T, {carrier(left)}, {carrier(length - left)}]"


def slot(length: int, index: int) -> str:
    if length == 1:
        return ".Item"
    left = length // 2
    return (
        ".Left" + slot(left, index)
        if index < left
        else ".Right" + slot(length - left, index - left)
    )


def render() -> str:
    lines = [
        "// Copyright (C) GSharp Authors. All rights reserved.",
        "// Generated by build/generate-fixed-array-copies.py.",
        "",
        "package Gsharp.Values.FixedArrays.V1",
        "",
        "import System",
        "",
        "/// Checked copying bridges for the bounded ADR-0210 canonical carriers.",
        "shared class ClrArrayCopies {",
        "    private func RequireLength[T](array []T, length int32) {",
        '        ArgumentNullException.ThrowIfNull(array, paramName: "array")',
        "        if array.Length != length {",
        '            throw ArgumentException("The array length must equal the fixed-array length.", "array")',
        "        }",
        "    }",
    ]
    for length in range(33):
        shape = carrier(length)
        lines += [
            "",
            f"    /// Copies exactly {length} array elements into an independent canonical value.",
            f"    func FromArray{length}[T](array []T) {shape} {{",
            f"        RequireLength(array, {length})",
            f"        var result {shape} = default",
        ]
        lines += [
            f"        result{slot(length, index)} = array[{index}]"
            for index in range(length)
        ]
        lines += [
            "        return result",
            "    }",
            "",
            f"    /// Copies the {length} canonical elements into a fresh CLR array.",
            f"    func ToArray{length}[T](value {shape}) []T {{",
            "        return []T{",
        ]
        lines += [
            f"            value{slot(length, index)},"
            for index in range(length)
        ]
        lines += ["        }", "    }"]
    return "\n".join([*lines, "}", ""])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print(f"{OUTPUT.relative_to(ROOT)} is out of date")
            return 1
    else:
        OUTPUT.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
