    [Fact]
    public void GeneratedImplementationThisRunTranslates_IsNotReported()
    {
        // A repository-layout migration also TRANSLATES a git-tracked
        // `<auto-generated>` file. When it is in the run's translated set,
        // its implementation reaches the G# output, so the definition's
        // omission is the ordinary partial rule, not a gap.
        const string source = @"
public static partial class Registry
{
    public static partial int Count();

    public static partial string Name { get; }

    public static string Show() => (Count() * 2).ToString() + Name;
}";
        const string generated = @"// <auto-generated/>
public static partial class Registry
{
    public static partial int Count() => 21;

    public static partial string Name => ""x"";
}";

        LoadedCSharpProject project = CSharpProjectLoader.LoadInMemory(new[]
        {
            ("Registry.cs", source),
            ("Registry.Generated.cs", generated),
        });
        Assert.True(project.BoundWithoutErrors, string.Join(Environment.NewLine, project.ErrorDiagnostics));
        var documents = project.Compilation.SyntaxTrees
            .Select(tree => new LoadedDocument(tree.FilePath, tree, project.Compilation.GetSemanticModel(tree)))
            .ToList();
        var translator = new CSharpToGSharpTranslator(
            translatedFilePaths: documents.Select(document => document.FilePath).ToList());

        var diagnostics = new List<TranslationDiagnostic>();
        var printed = new List<string>();
        foreach (LoadedDocument document in documents)
        {
            var context = new TranslationContext(project.Compilation, document.SemanticModel, document.FilePath);
            printed.Add(GSharpPrinter.Print(translator.TranslateDocument(document, context)));
            diagnostics.AddRange(context.Diagnostics);
        }

        Assert.DoesNotContain(diagnostics, diagnostic => diagnostic.Severity == TranslationSeverity.Unsupported);
        Assert.Contains("func Count() int32 -> 21", printed[1], StringComparison.Ordinal);
        TranslationTestValidation.AssertBinds(printed.ToArray());
    }

