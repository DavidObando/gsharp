    private static (string Printed, IReadOnlyList<TranslationDiagnostic> Diagnostics) Translate(
        params (string FileName, string Source)[] files)
    {
        LoadedCSharpProject project = CSharpProjectLoader.LoadInMemory(files);
        Assert.True(
            project.BoundWithoutErrors,
            "Snippet should bind with no C# errors: " +
                string.Join(Environment.NewLine, project.ErrorDiagnostics));

        // The loader drops the `<auto-generated>` generator output, as a real
        // build's loader does; only the hand-authored document translates.
        LoadedDocument document = Assert.Single(project.Documents);
        var context = new TranslationContext(project.Compilation, document.SemanticModel, document.FilePath);
        CompilationUnit unit = new CSharpToGSharpTranslator().TranslateDocument(document, context);
        return (GSharpPrinter.Print(unit), context.Diagnostics);
    }

    private static Assembly CompileInProcess(string source)
    {
        var compilation = new GSharpCompilation(GSharpSyntaxTree.Parse(GSharpSourceText.From(source)))
        {
            IsLibrary = true,
        };
        using var peStream = new MemoryStream();
        var result = compilation.Emit(peStream);
        Assert.True(
            result.Success,
            "Emit failed:\n" + string.Join("\n", result.Diagnostics.Select(d => d.ToString())) + "\n\n" + source);

        peStream.Position = 0;
        var loadContext = new AssemblyLoadContext("Issue4370-" + Guid.NewGuid().ToString("N"), isCollectible: true);
        return loadContext.LoadFromStream(peStream);
    }
