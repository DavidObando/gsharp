/// <summary>
/// Issue #4370: a C# <c>[LibraryImport]</c> partial method translates to the
/// native body-less G# <c>@LibraryImport</c> declaration (gsc builds the
/// marshalling wrapper itself, ADR-0092) instead of disappearing because its
/// implementation is LibraryImportGenerator output; marshalling surface gsc
/// does not honour is reported; and any other partial member implemented by
/// untranslated generated code is reported rather than silently dropped.
/// </summary>
/// <remarks>
/// The fixtures model the generator output as a second
/// <c>// &lt;auto-generated/&gt;</c> document holding the implementation part —
/// the shape a real build hands cs2gs (the loader drops that document, the
/// compilation still sees it).
/// </remarks>
public class Issue4370LibraryImportTranslationTests
{
    private const string IssueRepro = @"
using System.Runtime.InteropServices;

public static partial class Native
{
    [LibraryImport(""libc"", EntryPoint = ""getpid"")]
    public static partial int GetPid();

    public static int Call() => GetPid();
}";

    private const string IssueReproGenerated = @"// <auto-generated/>
public static partial class Native
{
    public static partial int GetPid() => 0;
}";

    [Fact]
    public void IssueRepro_TranslatesToNativeLibraryImport_BindsCompilesAndRuns()
    {
        (string printed, IReadOnlyList<TranslationDiagnostic> diagnostics) = Translate(
            ("Native.cs", IssueRepro),
            ("Native.g.cs", IssueReproGenerated));

        Assert.DoesNotContain(diagnostics, diagnostic => diagnostic.Severity == TranslationSeverity.Unsupported);
        Assert.Contains("@LibraryImport(\"libc\", EntryPoint: \"getpid\")", printed, StringComparison.Ordinal);
        Assert.Contains("func GetPid() int32;", printed, StringComparison.Ordinal);
        Assert.DoesNotContain("partial func", printed, StringComparison.Ordinal);
        Assert.Contains("func Call() int32 -> GetPid()", printed, StringComparison.Ordinal);

        // The import is a static member of the type (inside `shared`), not a
        // top-level function: C# callers reach it as Native.GetPid.
        int shared = printed.IndexOf("shared {", StringComparison.Ordinal);
        Assert.True(shared >= 0 && shared < printed.IndexOf("func GetPid", StringComparison.Ordinal), printed);

        TranslationTestValidation.AssertBinds(printed);
        Assembly assembly = CompileInProcess(printed);
        if (RuntimeInformation.IsOSPlatform(OSPlatform.Linux) || RuntimeInformation.IsOSPlatform(OSPlatform.OSX))
        {
            Type native = assembly.GetTypes().Single(type => type.Name == "Native");
            object pid = native.GetMethod("Call", BindingFlags.Public | BindingFlags.Static).Invoke(null, null);
            Assert.Equal(Environment.ProcessId, (int)pid);
        }
    }

    [Fact]
    public void AttributeArguments_AreMappedFromTheirConstantValues()
    {
        const string source = @"
using System.Runtime.InteropServices;

namespace Demo
{
    internal static partial class Libc
    {
        private const string LibName = ""libc"";

        [LibraryImport(LibName, EntryPoint = ""strlen"", StringMarshalling = StringMarshalling.Utf8, SetLastError = true)]
        internal static partial nint StrLen(string text);

        [LibraryImport(LibName, EntryPoint = ""time"")]
        private static partial long Time(ref long t);

        [LibraryImport(LibName, EntryPoint = ""time"")]
        private static partial long TimeOut(out long t);

        [LibraryImport(LibName)]
        [return: MarshalAs(UnmanagedType.Bool)]
        private static partial bool isatty([MarshalAs(UnmanagedType.I4)] int fd);

        public static long Now()
        {
            long t = 0;
            Time(ref t);
            TimeOut(out long u);
            return isatty(0) ? t : u + StrLen(""x"");
        }
    }
}";
        const string generated = @"// <auto-generated/>
namespace Demo
{
    internal static partial class Libc
    {
        internal static partial nint StrLen(string text) => 0;
        private static partial long Time(ref long t) => t = 0;
        private static partial long TimeOut(out long t) => t = 0;
        private static partial bool isatty(int fd) => false;
    }
}";

        (string printed, IReadOnlyList<TranslationDiagnostic> diagnostics) = Translate(
            ("Libc.cs", source),
            ("Libc.g.cs", generated));

        Assert.DoesNotContain(diagnostics, diagnostic => diagnostic.Severity == TranslationSeverity.Unsupported);

        // The const library name reaches gsc as the string literal its
        // P/Invoke binder requires; the enum argument keeps its member name.
        Assert.Contains(
            "@LibraryImport(\"libc\", EntryPoint: \"strlen\", StringMarshalling: StringMarshalling.Utf8, SetLastError: true)",
            printed,
            StringComparison.Ordinal);
        Assert.Contains("internal func StrLen(text string) nint;", printed, StringComparison.Ordinal);
        Assert.Contains("private func Time(ref t int64) int64;", printed, StringComparison.Ordinal);
        Assert.Contains("private func TimeOut(out t int64) int64;", printed, StringComparison.Ordinal);
        Assert.Contains("@return:MarshalAs(UnmanagedType.Bool)", printed, StringComparison.Ordinal);
        Assert.Contains("isatty(@MarshalAs(UnmanagedType.I4) fd int32) bool;", printed, StringComparison.Ordinal);
        Assert.DoesNotContain("@LibraryImport(LibName", printed, StringComparison.Ordinal);

        TranslationTestValidation.AssertBinds(printed);
        CompileInProcess(printed);
    }

