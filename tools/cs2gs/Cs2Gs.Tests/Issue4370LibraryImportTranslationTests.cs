        "[LibraryImport(\"libc\")] public static partial int F([MarshalUsing(typeof(Marshaller))] int x);",
        "[MarshalUsing]")]
    [InlineData(
        "[LibraryImport(\"libc\")] [UnmanagedCallConv(CallConvs = new[] { typeof(System.Runtime.CompilerServices.CallConvStdcall) })] public static partial int F(int x);",
        "[UnmanagedCallConv]")]
    [InlineData(
        "[LibraryImport(\"libc\")] [return: MarshalAs(UnmanagedType.U1)] public static partial bool F(int x);",
        "[return: MarshalAs]")]
    [InlineData(
        "[LibraryImport(\"libc\")] public static partial int F(Handle x);",
        "[NativeMarshalling]")]
    public void UnsupportedMarshallingSurface_IsReported(string declaration, string expectedFragment)
    {
        string source = @"
using System.Runtime.InteropServices;
using System.Runtime.InteropServices.Marshalling;

public sealed class Marshaller
{
}

[NativeMarshalling(typeof(Marshaller))]
public struct Handle
{
    public int Value;
}

public static partial class Native
{
    " + declaration + @"
}";
        string implementationParameter = declaration.Contains("Handle x", StringComparison.Ordinal) ? "Handle x" : "int x";
        string implementationReturn = declaration.Contains("partial bool", StringComparison.Ordinal) ? "bool" : "int";
        string generated = "// <auto-generated/>\npublic static partial class Native\n{\n    public static partial "
            + implementationReturn + " F(" + implementationParameter + ") => default;\n}";

        (string printed, IReadOnlyList<TranslationDiagnostic> diagnostics) = Translate(
            ("Native.cs", source),
            ("Native.g.cs", generated));

        TranslationDiagnostic unsupported = Assert.Single(
            diagnostics,
            diagnostic => diagnostic.Severity == TranslationSeverity.Unsupported);
        Assert.Contains(expectedFragment, unsupported.Message, StringComparison.Ordinal);
        Assert.Contains("'F'", unsupported.Message, StringComparison.Ordinal);

        // The import is still emitted so the rest of the type translates.
        Assert.Contains("func F(", printed, StringComparison.Ordinal);
    }

    [Fact]
    public void CdeclUnmanagedCallConv_TranslatesWithWarning()
    {
        // The Raylib-cs shape: a const library name plus CallConvCdecl, which
        // is gsc's platform default everywhere but 32-bit Windows.
        const string source = @"
using System.Runtime.CompilerServices;
using System.Runtime.InteropServices;

public static unsafe partial class Raylib
{
    public const string NativeLibName = ""libc"";

    [LibraryImport(NativeLibName, EntryPoint = ""getpid"")]
    [UnmanagedCallConv(CallConvs = new[] { typeof(CallConvCdecl) })]
    public static partial int GetPid();

    [LibraryImport(NativeLibName, EntryPoint = ""strlen"")]
    [UnmanagedCallConv(CallConvs = new[] { typeof(CallConvCdecl) })]
    public static partial nint StrLen(sbyte* text);
}";
        const string generated = @"// <auto-generated/>
public static unsafe partial class Raylib
{
    public static partial int GetPid() => 0;
    public static partial nint StrLen(sbyte* text) => 0;
}";

        (string printed, IReadOnlyList<TranslationDiagnostic> diagnostics) = Translate(
            ("Raylib.cs", source),
            ("Raylib.g.cs", generated));

        Assert.DoesNotContain(diagnostics, diagnostic => diagnostic.Severity == TranslationSeverity.Unsupported);
        Assert.Equal(
            2,
            diagnostics.Count(diagnostic =>
                diagnostic.Severity == TranslationSeverity.Warning
                && diagnostic.Message.Contains("CallConvCdecl", StringComparison.Ordinal)));
        Assert.Contains("@LibraryImport(\"libc\", EntryPoint: \"strlen\")", printed, StringComparison.Ordinal);
        Assert.Contains("func StrLen(text *int8) nint;", printed, StringComparison.Ordinal);

        TranslationTestValidation.AssertBinds(printed);
        Assembly assembly = CompileInProcess(printed);
        if (RuntimeInformation.IsOSPlatform(OSPlatform.Linux) || RuntimeInformation.IsOSPlatform(OSPlatform.OSX))
        {
            Type raylib = assembly.GetTypes().Single(type => type.Name == "Raylib");
            object pid = raylib.GetMethod("GetPid", BindingFlags.Public | BindingFlags.Static).Invoke(null, null);
            Assert.Equal(Environment.ProcessId, (int)pid);
        }
    }

