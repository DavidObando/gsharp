namespace Cs2Gs.Translator;

/// <summary>
/// Issue #2113: a whole-program, symbol-keyed null-TAINT analysis for a
/// nullable-<em>oblivious</em> compilation (one whose
/// <see cref="CSharpCompilationOptions.NullableContextOptions"/> is
/// <see cref="NullableContextOptions.Disable"/>).
///
/// <para>
/// In oblivious C# Roslyn reports every reference type as
/// <c>NullableAnnotation.None</c> with no flow state, so the translator
/// cannot tell a "definitely non-null" declaration apart from a "maybe null"
/// one (<c>NullableAnnotation.None</c> with no flow state). Mapping every
/// oblivious reference `T` to a non-null G# `T` then collides
/// with the `T?` values cs2gs legitimately introduces (`?.`, `= null` defaults,
/// nullable-returning BCL members), producing a cluster of GS0154/0155/0156
/// "T? vs T" errors. Mapping every oblivious reference to `T?` instead over-
/// promotes and forces a use-site explosion of `!!` assertions and idiomatic
/// non-null decls become nullable.
/// </para>
///
/// <para>
/// This analyzer instead decides, per reference-type declaration symbol S
/// (field / auto-property / parameter / method-return / local), whether S is
/// null-TAINTED. A tainted S is rendered `T?`; an untainted S stays non-null
/// `T` (the idiomatic default). Taint is seeded from direct null evidence
/// (== null, = null, ??=, is null, `?.`, `= null|default` initializers,
/// nullable-returning BCL members, and `return null` paths) and then propagated
/// to a fixpoint along assignment / initializer / return edges: if S is
/// assigned/initialized/returned a value that reads a tainted symbol or calls a
/// tainted method's return, S becomes tainted too.
/// </para>
///
/// <para>
/// The whole result is keyed on the declaration's <see cref="ISymbol"/> and is
/// consulted ONLY at declaration sites (see
/// <c>CSharpToGSharpTranslator.DeclarationVisitor.IsPromotedToNullableReference</c>
/// and the method-return path), so name positions (typeof/construction/base
/// list) and — because the analyzer never runs for a nullable-enabled
/// compilation — enabled projects are provably untouched.
/// </para>
/// </summary>
internal static class ObliviousNullabilityAnalyzer
{
    // Keyed by Compilation identity so an edited/new compilation naturally gets
    // a fresh entry and stale ones are collectible — same pattern as the
    // subclassed-base-types / partial-type-parts caches in the translator.
    private static readonly ConditionalWeakTable<Compilation, TaintResult> Cache = new();
    private static readonly ConditionalWeakTable<Compilation, SourceAssemblySet> SourceAssemblies = new();

    // Issue #3676: `<auto-generated/>`-ness is a property of a whole syntax tree
    // and is asked once per declaration query, so the (root-materializing) trivia
    // scan is memoized per tree. Keyed on tree identity so a reparsed tree gets a
    // fresh entry and stale ones stay collectible, exactly like `Cache` above.
    private static readonly ConditionalWeakTable<SyntaxTree, StrongBox<bool>> GeneratedTrees = new();

    // Issue #3676: per-compilation set of members some source directly writes
    // `null` into, keyed like `Cache` above so it is computed at most once.
    private static readonly ConditionalWeakTable<Compilation, HashSet<string>> NullTargets = new();

    // Which source expressions a transitive return/forwarding edge follows.
    private enum SourceScope
    {
        // Follow method-call returns AND every value declaration the value
        // reads (fields, properties, locals, parameters). Default for method /
        // local-function / lambda return seeding.
        AllSources,

        // Follow ONLY method-call returns (`m(args)`); plain identifier/member
        // forwarding is skipped. Property-getter contract guardrail path where
        // no forwarding may be followed.
        CallsOnly,

        // Follow method-call returns AND field/local/parameter forwarding, but
        // NOT property forwarding. Used for a NON-CONTRACT property getter
        // (issue #914 oblivious sink): `TextWriter Writer => logStreamWriter;`
        // over a promoted `StreamWriter?` backing FIELD must itself be `T?`,
        // yet `string Forward => Work;` forwarding another PROPERTY must keep
        // its declared type and rely on the null-forgiveness `!!` pass, so the
        // property contract with #1354 / #2167 is preserved.
        CallsAndNonPropertyDeclarations,
    }

    /// <summary>
    /// Whether <paramref name="symbol"/> (a declaration symbol: field / property
    /// / parameter / local, or a method whose RETURN is under test) is
    /// null-tainted in <paramref name="compilation"/>. Always returns
    /// <see langword="false"/> for a non-oblivious (nullable-enabled) compilation
    /// — the analysis never runs there, so enabled projects are untouched.
    /// </summary>
    /// <param name="compilation">The C# compilation being translated.</param>
    /// <param name="symbol">The declaration symbol to test.</param>
    /// <returns><see langword="true"/> when the symbol is null-tainted.</returns>
    public static bool IsTainted(CSharpCompilation compilation, ISymbol symbol)
    {
        if (symbol == null ||
            compilation == null ||
            compilation.Options.NullableContextOptions != NullableContextOptions.Disable)
        {
            return false;
        }

        RegisterSourceAssemblies(compilation, null);
        return Cache.GetValue(compilation, Compute).Tainted.Contains(Canonical(symbol));
    }

    /// <summary>
    /// Issue #3676: whether <paramref name="symbol"/>'s declaring source is
    /// marked <c>&lt;auto-generated/&gt;</c>. The C# compiler SUPPRESSES its
    /// nullable diagnostics (CS8600-CS8655) inside such a file — verified
    /// empirically: an identical <c>public string Get() =&gt; null;</c> reports
    /// CS8603 in a hand-authored file and reports NOTHING in one carrying the
    /// header — so a generated file's reference annotations are unenforced and
    /// routinely contradicted by the very code that declares them. gsc has no
    /// matching suppression, so translating those annotations at face value
    /// emits G# the C# compiler never had to justify.
    /// </summary>
    /// <param name="symbol">The declaration symbol to test.</param>
    /// <returns><see langword="true"/> when any declaring tree carries the header.</returns>
    public static bool IsDeclaredInGeneratedCode(ISymbol symbol)
    {
        if (symbol == null)
        {
            return false;
        }

        foreach (SyntaxReference reference in symbol.DeclaringSyntaxReferences)
        {
            if (HasAutoGeneratedHeader(reference.SyntaxTree))
            {
                return true;
            }
        }

        return false;
    }

    /// <summary>
    /// Issue #3676: whether <paramref name="symbol"/> is a generated-code
    /// declaration whose G# type this translator may decide from taint evidence
    /// instead of from its (compiler-unenforced) C# annotation.
    ///
    /// <para>
    /// Being declared in generated code is necessary but not sufficient: a
    /// member that OVERRIDES or IMPLEMENTS another declaration does not own its
    /// own signature. Its parameter and return types are fixed by the base, and
    /// repainting one of them nullable produces a signature that no longer
    /// matches what it overrides — gsc's GS0185/GS0386/GS0387, which is how the
    /// `<auto-generated/>` LSP <c>JsonConverter&lt;T&gt;</c> subclasses
    /// (<c>Read</c>/<c>Write</c>/<c>ReadAsPropertyName</c>) first failed. Those
    /// members keep their declared types and rely on the ordinary use-site
    /// forgiveness pass, exactly as they do today.
    /// </para>
    /// </summary>
    /// <param name="symbol">The declaration symbol to test.</param>
    /// <returns><see langword="true"/> when evidence, not the annotation, decides the symbol.</returns>
    public static bool IsEvidenceDecidedGeneratedDeclaration(ISymbol symbol) =>
        IsDeclaredInGeneratedCode(symbol) && !IsSignatureFixedByAnotherDeclaration(symbol);

    /// <summary>
    /// Issue #3676: whether <paramref name="symbol"/> is an evidence-decided
    /// generated-code declaration (see
    /// <see cref="IsEvidenceDecidedGeneratedDeclaration"/>) that some source in
    /// <paramref name="compilation"/> or <paramref name="siblingCompilations"/>
    /// DIRECTLY writes <c>null</c> (or <c>default</c>) into — an assignment, an
    /// object-initializer member, a field/property initializer, or a
    /// <c>return</c>.
    ///
    /// <para>
    /// Deliberately DIRECT evidence rather than #2113's transitive taint
    /// fixpoint. That fixpoint reasons about a compilation where every
    /// annotation is oblivious and it therefore has nothing else to go on;
    /// applied to a nullable-ENABLED compilation, whose
    /// graph is mostly annotated, its forwarding edges over-promote — it marked
    /// the LSP <c>LspJson.Options</c> chain nullable although
    /// <c>Create()</c> only ever returns a fresh <c>new
    /// JsonSerializerOptions</c>, which then failed to bind at the non-null
    /// StreamJsonRpc formatter property. The narrow rule states exactly what
    /// the suppression licenses and nothing more: where the compiler stopped
    /// checking, believe the code that writes <c>null</c>, not the annotation
    /// it silently contradicts.
    /// </para>
    /// </summary>
    /// <param name="compilation">The compilation being translated.</param>
    /// <param name="symbol">The declaration symbol to test.</param>
    /// <param name="siblingCompilations">Other projects loaded in the same run, or <see langword="null"/>.</param>
    /// <returns><see langword="true"/> when null is written into the declaration.</returns>
    public static bool IsGeneratedDeclarationAssignedNull(
        CSharpCompilation compilation,
        ISymbol symbol,
        IReadOnlyList<CSharpCompilation> siblingCompilations)
    {
        if (compilation == null
            || !IsEvidenceDecidedGeneratedDeclaration(symbol)
            || symbol.OriginalDefinition.GetDocumentationCommentId() is not { } id)
        {
            return false;
        }

        // A declaration must translate identically no matter which project is
        // being emitted, so the evidence is the union over every compilation
        // known to the run — an existential OR, order-independent, each side
        // computed and cached once.
        if (NullAssignmentTargets(compilation).Contains(id))
        {
            return true;
        }

        if (siblingCompilations != null)
        {
            foreach (CSharpCompilation sibling in siblingCompilations)
            {
                if (sibling != null && NullAssignmentTargets(sibling).Contains(id))
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Whether <paramref name="tree"/> opens with an <c>&lt;auto-generated&gt;</c>
    /// marker, matching the leading-trivia test the C# compiler itself uses to
    /// decide a tree is generated code. Memoized per tree.
    /// </summary>
    /// <param name="tree">The syntax tree to test.</param>
    /// <returns><see langword="true"/> when the tree is marked generated.</returns>
    public static bool HasAutoGeneratedHeader(SyntaxTree tree)
    {
        if (tree == null)
        {
            return false;
        }

        return GeneratedTrees.GetValue(
            tree,
            scanned => new StrongBox<bool>(
                scanned.GetRoot().GetLeadingTrivia().Any(trivia =>
                    trivia.ToString().Contains("<auto-generated", System.StringComparison.OrdinalIgnoreCase))))
            .Value;
    }

    /// <summary>
    /// Issue #2412: cross-project overload of <see cref="IsTainted(CSharpCompilation, ISymbol)"/>.
    /// <paramref name="compilation"/>'s own whole-program taint fixpoint only
    /// walks ITS OWN syntax trees, so it never sees a referenced sibling
    /// project's tainting evidence — even for a symbol DECLARED in
    /// <paramref name="compilation"/> itself, when that evidence is an
    /// interface-implementation edge (issue #2285) recorded only inside a
    /// sibling project's own fixpoint (the sibling's own source types are the
    /// ones implementing the interface). This tries <paramref name="compilation"/>
    /// first (byte-identical to the two-argument overload for every existing,
    /// single-compilation caller — an empty or <see langword="null"/>
    /// <paramref name="siblingCompilations"/> reduces to exactly that), then
    /// each of <paramref name="siblingCompilations"/> in the supplied
    /// (deterministic) order, returning <see langword="true"/> on the first
    /// compilation whose OWN cached <see cref="Compute"/> result proves the
    /// symbol tainted. A symbol declared in — or seeded/propagated from — ANY
    /// ONE known project's own source is a single global fact once true, so
    /// this is a plain existential OR: each candidate's result is computed
    /// (and cached, same <see cref="Cache"/>) independently and exactly once
    /// regardless of how many times this overload is called, keeping repeated
    /// per-document queries within one run, and across a project translated
    /// both standalone and as a sibling, consistent and cheap.
    /// <para>
    /// Deliberately scoped to <paramref name="symbol"/> ITSELF (plus its
    /// remapped counterpart in each sibling) — never a same-compilation
    /// backward walk through ordinary assignment edges to some OTHER,
    /// indirectly-connected declaration. The sole exception is issue #2504's
    /// explicitly tracked named-delegate return-contract edge, whose source
    /// callable may be declared in a referenced sibling. Issue #2412's
    /// own worked example is explicit that the fix must insert `!!`
    /// forgiveness AT THE CONSUMPTION SITE while leaving the consuming
    /// project's OWN declarations (e.g. an object-initializer target
    /// property) untouched — confirmed empirically: even a fully MERGED
    /// single-compilation version of the exact LibA/LibB repro promotes the
    /// object-initializer TARGET property's own declared type too (the
    /// existing, pre-#2412 edge-based fixpoint already treats "declaration
    /// type is the join of every direct assignment" uniformly for locals,
    /// fields, AND properties alike) — a broader, transitively-propagating
    /// design here would branch further from that minimal, explicitly-scoped
    /// request than necessary, and would let ONE cross-project call site's
    /// taint silently repaint an unrelated declaration's own type everywhere
    /// else it is used in the consuming project.
    /// </para>
    /// </summary>
    /// <param name="compilation">The compilation of the translation unit asking about <paramref name="symbol"/>.</param>
    /// <param name="symbol">The declaration symbol to test.</param>
    /// <param name="siblingCompilations">
    /// Every other project's own compilation loaded in the same migration run
    /// (<see cref="TranslationContext.SiblingCompilations"/>), or
    /// <see langword="null"/> when none is known.
    /// </param>
    /// <returns><see langword="true"/> when any known compilation's own analysis proves the symbol null-tainted.</returns>
    public static bool IsTainted(
        CSharpCompilation compilation,
        ISymbol symbol,
        IReadOnlyList<CSharpCompilation> siblingCompilations)
    {
        if (symbol == null
            || compilation == null
            || compilation.Options.NullableContextOptions != NullableContextOptions.Disable)
        {
            return false;
        }

        RegisterSourceAssemblies(compilation, siblingCompilations);
        return IsTaintedCore(
            compilation,
            Canonical(symbol),
            siblingCompilations,
            new HashSet<ScalarQuery>(ScalarQueryComparer.Instance),
            new HashSet<TupleElementQuery>(TupleElementQueryComparer.Instance));
    }

    /// <summary>
    /// Whether one reference-typed leaf inside a tuple-valued declaration is
    /// null-tainted. Tuple leaves are tracked independently so evidence for
    /// one element never widens its siblings.
    /// </summary>
    /// <param name="compilation">The compilation containing the query.</param>
    /// <param name="symbol">The tuple-valued declaration symbol.</param>
    /// <param name="elementPath">Zero-based indexes from the outer tuple to the leaf.</param>
    /// <param name="siblingCompilations">Other compilations loaded in the same translation run.</param>
    /// <returns><see langword="true"/> when the selected tuple leaf is null-tainted.</returns>
    public static bool IsTupleElementTainted(
        CSharpCompilation compilation,
        ISymbol symbol,
        IReadOnlyList<int> elementPath,
        IReadOnlyList<CSharpCompilation> siblingCompilations)
    {
        if (symbol == null
            || elementPath == null
            || elementPath.Count == 0
            || compilation == null
            || compilation.Options.NullableContextOptions != NullableContextOptions.Disable)
        {
            return false;
        }

        RegisterSourceAssemblies(compilation, siblingCompilations);
        return IsTupleElementTaintedCore(
            compilation,
            Canonical(symbol),
            EncodeTuplePath(elementPath),
            siblingCompilations,
            new HashSet<ScalarQuery>(ScalarQueryComparer.Instance),
            new HashSet<TupleElementQuery>(TupleElementQueryComparer.Instance));
    }

    /// <summary>
    /// Whether <paramref name="expression"/> reads a null-tainted tuple leaf.
    /// </summary>
    /// <param name="compilation">The compilation containing the expression.</param>
    /// <param name="expression">A named or positional tuple-member expression.</param>
    /// <param name="model">The semantic model for the expression.</param>
    /// <param name="siblingCompilations">Other compilations loaded in the same translation run.</param>
    /// <returns><see langword="true"/> when the selected tuple leaf is null-tainted.</returns>
    public static bool IsTupleElementTainted(
        CSharpCompilation compilation,
        ExpressionSyntax expression,
        SemanticModel model,
        IReadOnlyList<CSharpCompilation> siblingCompilations)
    {
        if (compilation == null
            || expression == null
            || model == null
            || compilation.Options.NullableContextOptions != NullableContextOptions.Disable
            || !TryResolveTupleElementSource(expression, model, out TupleElementKey source))
        {
            return false;
        }

        RegisterSourceAssemblies(compilation, siblingCompilations);
        return IsTupleElementTaintedCore(
            compilation,
            source.Symbol,
            source.Path,
            siblingCompilations,
            new HashSet<ScalarQuery>(ScalarQueryComparer.Instance),
            new HashSet<TupleElementQuery>(TupleElementQueryComparer.Instance));
    }

    /// <summary>
    /// Issue #3663: whether <paramref name="expression"/> reads a variable bound
    /// by a DECONSTRUCTING <c>foreach</c> header
    /// (<c>foreach ((A a, B b) in items)</c>) whose corresponding tuple leaf is
    /// null-tainted. Such a variable has no declared type of its own on the G#
    /// side — <c>for (a, b) in items</c> infers each name from the sequence's
    /// element tuple — so when #3641's nested-tuple promotion renders that
    /// element <c>A?</c>, every read of the variable is a nullable value the
    /// translator must bridge with <c>!!</c> at its non-null sinks. The sibling
    /// <see cref="IsTupleElementTainted(CSharpCompilation, ExpressionSyntax, SemanticModel, IReadOnlyList{CSharpCompilation})"/>
    /// only recognizes an explicit member read (<c>pair.Item1</c>), which a
    /// deconstruction never writes.
    /// </summary>
    /// <param name="compilation">The compilation containing the expression.</param>
    /// <param name="expression">A read of a deconstruction-bound variable.</param>
    /// <param name="model">The semantic model for the expression.</param>
    /// <param name="siblingCompilations">Other compilations loaded in the same translation run.</param>
    /// <returns><see langword="true"/> when the bound tuple leaf is null-tainted.</returns>
    public static bool IsDeconstructedForEachElementTainted(
        CSharpCompilation compilation,
        ExpressionSyntax expression,
        SemanticModel model,
        IReadOnlyList<CSharpCompilation> siblingCompilations)
    {
        if (compilation == null
            || expression == null
            || model == null
            || compilation.Options.NullableContextOptions != NullableContextOptions.Disable
            || !TryResolveForEachDeconstructionSource(expression, model, out TupleElementKey source))
        {
            return false;
        }

        RegisterSourceAssemblies(compilation, siblingCompilations);
        return IsTupleElementTaintedCore(
            compilation,
            source.Symbol,
            source.Path,
            siblingCompilations,
            new HashSet<ScalarQuery>(ScalarQueryComparer.Instance),
            new HashSet<TupleElementQuery>(TupleElementQueryComparer.Instance));
    }

    public static HashSet<INamedTypeSymbol> CollectEfEntityTypes(Compilation compilation)
    {
        var entities = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel model = compilation.GetSemanticModel(tree);
            foreach (PropertyDeclarationSyntax property in tree.GetRoot().DescendantNodes().OfType<PropertyDeclarationSyntax>())
            {
                var dbSet = model.GetDeclaredSymbol(property)?.Type as INamedTypeSymbol;
                if (dbSet?.Name != "DbSet"
                    || dbSet.Arity != 1
                    || dbSet.ContainingNamespace?.ToDisplayString() != "Microsoft.EntityFrameworkCore"
                    || dbSet.TypeArguments[0] is not INamedTypeSymbol entity)
                {
                    continue;
                }

                entities.Add(entity.OriginalDefinition);
            }
        }

        return entities;
    }

    internal static bool TryGetGenericReceiverTuplePath(
        INamedTypeSymbol receiverType,
        IParameterSymbol parameter,
        out INamedTypeSymbol tupleType,
        out IReadOnlyList<int> tuplePath)
    {
        tupleType = null;
        tuplePath = null;
        if (receiverType == null
            || parameter?.OriginalDefinition.Type
                is not ITypeParameterSymbol { TypeParameterKind: TypeParameterKind.Type } typeParameter
            || typeParameter.ContainingType is not INamedTypeSymbol declaringType)
        {
            return false;
        }

        if (!TryResolveReceiverTypeParameterPath(
                receiverType,
                declaringType.OriginalDefinition,
                typeParameter.Ordinal,
                out INamedTypeSymbol actualTuple,
                out IReadOnlyList<int> path))
        {
            return false;
        }

        tupleType = actualTuple;
        tuplePath = path;
        return true;
    }

    private static bool IsTaintedCore(
        CSharpCompilation compilation,
        ISymbol symbol,
        IReadOnlyList<CSharpCompilation> siblingCompilations,
        HashSet<ScalarQuery> scalarVisited,
        HashSet<TupleElementQuery> tupleVisited)
    {
        var query = new ScalarQuery(compilation, Canonical(symbol));
        if (!scalarVisited.Add(query))
        {
            return false;
        }

        TaintResult result = Cache.GetValue(compilation, Compute);
        if (result.Tainted.Contains(query.Symbol))
        {
            return true;
        }

        foreach ((ISymbol target, TupleElementKey source) in result.ScalarTupleEdges)
        {
            if (SymbolEqualityComparer.Default.Equals(target, query.Symbol)
                && IsTupleElementTaintedCore(
                    compilation,
                    source.Symbol,
                    source.Path,
                    siblingCompilations,
                    scalarVisited,
                    tupleVisited))
            {
                return true;
            }
        }

        foreach ((ISymbol target, ISymbol source) in result.DelegateReturnEdges)
        {
            if (SymbolEqualityComparer.Default.Equals(target, query.Symbol)
                && IsTaintedCore(
                    compilation,
                    source,
                    siblingCompilations,
                    scalarVisited,
                    tupleVisited))
            {
                return true;
            }
        }

        if (siblingCompilations != null)
        {
            foreach (CSharpCompilation sibling in siblingCompilations)
            {
                if (sibling == null
                    || ReferenceEquals(sibling, compilation)
                    || sibling.Options.NullableContextOptions != NullableContextOptions.Disable)
                {
                    continue;
                }

                // Remap independently-bound symbols by stable metadata identity
                // before testing the sibling compilation's own cached graph.
                ISymbol remapped = RemapToCompilation(sibling, query.Symbol);
                if (remapped != null
                    && IsTaintedCore(
                        sibling,
                        Canonical(remapped),
                        siblingCompilations,
                        scalarVisited,
                        tupleVisited))
                {
                    return true;
                }
            }
        }

        return false;
    }

    private static bool IsTupleElementTaintedCore(
        CSharpCompilation compilation,
        ISymbol symbol,
        string path,
        IReadOnlyList<CSharpCompilation> siblingCompilations,
        HashSet<ScalarQuery> scalarVisited,
        HashSet<TupleElementQuery> tupleVisited)
    {
        var key = new TupleElementKey(symbol, path);
        if (!tupleVisited.Add(new TupleElementQuery(compilation, key)))
        {
            return false;
        }

        TaintResult result = Cache.GetValue(compilation, Compute);
        if (result.TupleTainted.Contains(key))
        {
            return true;
        }

        foreach ((TupleElementKey target, ISymbol source) in result.TupleScalarEdges)
        {
            if (TupleElementKeyComparer.Instance.Equals(target, key)
                && IsTaintedCore(
                    compilation,
                    source,
                    siblingCompilations,
                    scalarVisited,
                    tupleVisited))
            {
                return true;
            }
        }

        foreach ((TupleElementKey target, TupleElementKey source) in result.TupleEdges)
        {
            if (TupleElementKeyComparer.Instance.Equals(target, key)
                && IsTupleElementTaintedCore(
                    compilation,
                    source.Symbol,
                    source.Path,
                    siblingCompilations,
                    scalarVisited,
                    tupleVisited))
            {
                return true;
            }
        }

        if (siblingCompilations != null)
        {
            foreach (CSharpCompilation sibling in siblingCompilations)
            {
                if (sibling == null
                    || ReferenceEquals(sibling, compilation)
                    || sibling.Options.NullableContextOptions != NullableContextOptions.Disable)
                {
                    continue;
                }

                ISymbol remapped = RemapToCompilation(sibling, symbol);
                if (remapped != null
                    && IsTupleElementTaintedCore(
                        sibling,
                        Canonical(remapped),
                        path,
                        siblingCompilations,
                        scalarVisited,
                        tupleVisited))
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Finds the symbol in <paramref name="targetCompilation"/>'s own symbol
    /// table that is the "same" declaration as <paramref name="symbol"/>,
    /// which may have been resolved through an entirely different
    /// <see cref="CSharpCompilation"/>. Matching is by stable metadata
    /// identity (containing type's fully qualified metadata name plus member
    /// name/kind/arity), never by <see cref="SymbolEqualityComparer"/> or CLR
    /// object identity, since those do not hold across independently bound
    /// compilations (see the long comment on the calling overload). Returns
    /// <see langword="null"/> when no matching declaration exists in
    /// <paramref name="targetCompilation"/> (e.g. `symbol` is unrelated to it).
    /// </summary>
    private static ISymbol RemapToCompilation(Compilation targetCompilation, ISymbol symbol)
    {
        if (symbol is IParameterSymbol parameter)
        {
            ISymbol remappedOwner = RemapMemberOwner(targetCompilation, parameter.ContainingSymbol);
            return remappedOwner switch
            {
                IMethodSymbol method when parameter.Ordinal < method.Parameters.Length =>
                    method.Parameters[parameter.Ordinal],
                IPropertySymbol indexer when parameter.Ordinal < indexer.Parameters.Length =>
                    indexer.Parameters[parameter.Ordinal],
                _ => null,
            };
        }

        return RemapMemberOwner(targetCompilation, symbol);
    }

    /// <summary>
    /// Remaps a field/property/method/local-owning member symbol (everything
    /// <see cref="RemapToCompilation"/> handles other than parameters
    /// themselves) into <paramref name="targetCompilation"/>'s own symbol
    /// table by metadata name. Locals have no stable cross-compilation
    /// identity (they only ever make sense within the one method body/one
    /// compilation that declares them), so they intentionally fall through to
    /// <see langword="null"/> here.
    /// </summary>
    private static ISymbol RemapMemberOwner(Compilation targetCompilation, ISymbol symbol)
    {
        if (symbol == null)
        {
            return null;
        }

        INamedTypeSymbol containingType = symbol.ContainingType;
        if (containingType == null)
        {
            return null;
        }

        INamedTypeSymbol remappedType = targetCompilation.GetTypeByMetadataName(MetadataTypeName(containingType));
        if (remappedType == null)
        {
            return null;
        }

        if (symbol is IMethodSymbol method)
        {
            return remappedType.GetMembers(method.Name)
                .OfType<IMethodSymbol>()
                .FirstOrDefault(candidate =>
                    candidate.IsStatic == method.IsStatic &&
                    candidate.Parameters.Length == method.Parameters.Length &&
                    candidate.TypeParameters.Length == method.TypeParameters.Length);
        }

        return remappedType.GetMembers(symbol.Name).FirstOrDefault(candidate => candidate.Kind == symbol.Kind);
    }

    /// <summary>
    /// Builds the CLR metadata name (e.g. <c>Outer+Inner`1</c> within its
    /// namespace) that <see cref="Compilation.GetTypeByMetadataName"/> expects,
    /// walking outward through nested-type containment so nested types (which
    /// <c>MetadataName</c> alone does not capture) are found too.
    /// </summary>
    private static string MetadataTypeName(INamedTypeSymbol type)
    {
        var parts = new List<string>();
        for (INamedTypeSymbol current = type; current != null; current = current.ContainingType)
        {
            parts.Insert(0, current.MetadataName);
        }

        string nested = string.Join("+", parts);
        return type.ContainingNamespace is { IsGlobalNamespace: false } ns
            ? ns.ToDisplayString() + "." + nested
            : nested;
    }

    // Every member of `compilation` that some source in it directly writes
    // `null`/`default` into, keyed by documentation-comment id so the answer is
    // comparable across the separate compilations one migration run loads.
    // Computed once per compilation.
    private static HashSet<string> NullAssignmentTargets(CSharpCompilation compilation) =>
        NullTargets.GetValue(compilation, ComputeNullAssignmentTargets);

    private static HashSet<string> ComputeNullAssignmentTargets(Compilation compilation)
    {
        var targets = new HashSet<string>(System.StringComparer.Ordinal);
        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel model = null;
            foreach (SyntaxNode node in tree.GetRoot().DescendantNodes())
            {
                ISymbol target = node switch
                {
                    // `x.Member = null` and the object-initializer member
                    // `new T { Member = null }`, which share this node shape.
                    AssignmentExpressionSyntax assignment
                        when assignment.IsKind(SyntaxKind.SimpleAssignmentExpression)
                            && WritesNull(assignment.Right) =>
                        Model().GetSymbolInfo(assignment.Left).Symbol,

                    // `string Member { get; set; } = null;` / `string field = null;`
                    EqualsValueClauseSyntax initializer
                        when WritesNull(initializer.Value)
                            && initializer.Parent is VariableDeclaratorSyntax or PropertyDeclarationSyntax =>
                        Model().GetDeclaredSymbol(initializer.Parent),

                    // `return null;` anywhere in the member's body.
                    ReturnStatementSyntax returned when WritesNull(returned.Expression) =>
                        OwningMember(Model().GetEnclosingSymbol(returned.SpanStart)),

                    // An expression-bodied member whose whole body is null.
                    ArrowExpressionClauseSyntax arrow when WritesNull(arrow.Expression) =>
                        OwningMember(Model().GetDeclaredSymbol(arrow.Parent)),

                    _ => null,
                };

                if (target?.OriginalDefinition.GetDocumentationCommentId() is { } id)
                {
                    targets.Add(id);
                }

                SemanticModel Model() => model ??= compilation.GetSemanticModel(tree);
            }
        }

        return targets;
    }

    // `null`, `default`, or either reachable through parentheses or a branch of
    // a conditional / switch expression — all of which make null one of the
    // values the C# actually writes into the target.
    private static bool WritesNull(ExpressionSyntax expression) =>
        expression switch
        {
            null => false,
            ParenthesizedExpressionSyntax parenthesized => WritesNull(parenthesized.Expression),
            ConditionalExpressionSyntax conditional =>
                WritesNull(conditional.WhenTrue) || WritesNull(conditional.WhenFalse),
            SwitchExpressionSyntax switched => switched.Arms.Any(arm => WritesNull(arm.Expression)),
            DefaultExpressionSyntax => true,
            LiteralExpressionSyntax literal =>
                literal.IsKind(SyntaxKind.NullLiteralExpression)
                || literal.IsKind(SyntaxKind.DefaultLiteralExpression),
            _ => false,
        };

    // The declaration a `return`/arrow body belongs to: the method itself, or
    // the property behind a getter rather than the synthesized accessor.
    private static ISymbol OwningMember(ISymbol symbol) =>
        symbol is IMethodSymbol { MethodKind: MethodKind.PropertyGet, AssociatedSymbol: { } property }
            ? property
            : symbol;

    // Whether the member owning `symbol`'s type position inherits that position
    // from a base class or interface declaration, so its nullability is not the
    // member's own to restate. Covers the member itself and — since a parameter
    // list is matched as a whole — every parameter of such a member.
    private static bool IsSignatureFixedByAnotherDeclaration(ISymbol symbol)
    {
        ISymbol member = symbol is IParameterSymbol parameter
            ? parameter.ContainingSymbol
            : symbol;

        return member switch
        {
            IMethodSymbol method =>
                method.IsOverride
                || method.ExplicitInterfaceImplementations.Length > 0
                || ImplementsInterfaceMember(method),
            IPropertySymbol property =>
                property.IsOverride
                || property.ExplicitInterfaceImplementations.Length > 0
                || ImplementsInterfaceMember(property),
            _ => false,
        };
    }

    // Whether `member` implicitly implements an interface member of its
    // containing type (the explicit form is tested directly by the caller).
    private static bool ImplementsInterfaceMember(ISymbol member)
    {
        INamedTypeSymbol containing = member.ContainingType;
        if (containing == null)
        {
            return false;
        }

        foreach (INamedTypeSymbol contract in containing.AllInterfaces)
        {
            foreach (ISymbol candidate in contract.GetMembers(member.Name))
            {
                if (SymbolEqualityComparer.Default.Equals(
                        containing.FindImplementationForInterfaceMember(candidate),
                        member))
                {
                    return true;
                }
            }
        }

        return false;
    }

    private static TaintResult Compute(Compilation compilation)
    {
        var tainted = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
        var tupleTainted = new HashSet<TupleElementKey>(TupleElementKeyComparer.Instance);

        // Transitive edges: (target <- source). If `source` is tainted then
        // `target` becomes tainted. Both are canonicalized declaration symbols
        // (field/property/parameter/local for a value target; method for a
        // return target; field/property/parameter/local/method for a source).
        var edges = new List<(ISymbol Target, ISymbol Source)>();
        var tupleEdges = new List<(TupleElementKey Target, TupleElementKey Source)>();
        var tupleScalarEdges = new List<(TupleElementKey Target, ISymbol Source)>();
        var scalarTupleEdges = new List<(ISymbol Target, TupleElementKey Source)>();
        var delegateReturnEdges = new List<(ISymbol Target, ISymbol Source)>();

        foreach (SyntaxTree tree in compilation.SyntaxTrees)
        {
            SemanticModel model = compilation.GetSemanticModel(tree);
            SyntaxNode root = tree.GetRoot();

            foreach (SyntaxNode node in root.DescendantNodes())
            {
                SeedDirectTaint(node, model, tainted);
                CollectEdges(node, model, tainted, edges, scalarTupleEdges);
            }

            // Method / accessor / local-function RETURN taint: a `return null`,
            // `return default`, or `return <nullable-expr>` path taints the
            // enclosing member's return symbol; a non-directly-null `return`
            // records a transitive edge from the return symbol to the returned
            // value's source.
            SeedReturnTaint(root, model, tainted, edges, scalarTupleEdges);
            CollectTupleFlows(
                root,
                model,
                tainted,
                edges,
                tupleTainted,
                tupleEdges,
                tupleScalarEdges,
                scalarTupleEdges);
            CollectDelegateReturnContractEdges(
                compilation,
                root,
                model,
                tainted,
                edges,
                delegateReturnEdges,
                tupleTainted,
                tupleEdges);
        }

        // Issue #3060: EF entity properties are promoted by policy rather than
        // syntax evidence, so seed them before contract edges synchronize
        // interface and implementation nullability.
        SeedEfEntityPropertyTaint(compilation, tainted);

        // Issue #2285: an interface member and every member that implements it
        // (across the whole compilation) must reach the SAME tainted-ness, so
        // cs2gs never promotes one endpoint (e.g. a record's primary-ctor
        // parameter) to `T?` while leaving the other (the interface property it
        // satisfies) non-null `T` — see <see cref="CollectInterfaceImplementationEdges"/>.
        CollectInterfaceImplementationEdges(compilation, edges);
        CollectOverrideContractEdges(compilation, edges);
        CollectTupleContractEdges(compilation, tupleTainted, tupleEdges);

        // Fixpoint: propagate taint along the edge set until it stabilizes.
        bool changed = true;
        while (changed)
        {
            changed = false;
            foreach ((ISymbol target, ISymbol source) in edges)
            {
                if (!tainted.Contains(target) && tainted.Contains(source))
                {
                    tainted.Add(target);
                    changed = true;
                }
            }

            foreach ((TupleElementKey target, ISymbol source) in tupleScalarEdges)
            {
                if (!tupleTainted.Contains(target) && tainted.Contains(source))
                {
                    tupleTainted.Add(target);
                    changed = true;
                }
            }

            foreach ((ISymbol target, TupleElementKey source) in scalarTupleEdges)
            {
                if (!tainted.Contains(target) && tupleTainted.Contains(source))
                {
                    tainted.Add(target);
                    changed = true;
                }
            }

            foreach ((TupleElementKey target, TupleElementKey source) in tupleEdges)
            {
                if (!tupleTainted.Contains(target) && tupleTainted.Contains(source))
                {
                    tupleTainted.Add(target);
                    changed = true;
                }
            }
        }

        return new TaintResult(
            tainted,
            tupleTainted,
            tupleEdges,
            tupleScalarEdges,
            scalarTupleEdges,
            delegateReturnEdges);
    }

    private static void SeedEfEntityPropertyTaint(
        Compilation compilation,
        HashSet<ISymbol> tainted)
    {
        foreach (INamedTypeSymbol entity in CollectEfEntityTypes(compilation))
        {
            foreach (IPropertySymbol property in entity.GetMembers().OfType<IPropertySymbol>())
            {
                if (IsEligibleScalarTarget(property))
                {
                    tainted.Add(Canonical(property));
                }
            }
        }
    }

    // Seeds direct null evidence for a value declaration symbol (field /
    // property / parameter / local): the exact forms the translator's local
    // ComputeIsUsedAsNullable / IsNullableInitializer already recognize, applied
    // whole-program.
    private static void SeedDirectTaint(
        SyntaxNode node,
        SemanticModel model,
        HashSet<ISymbol> tainted)
    {
        switch (node)
        {
            // `x == null` / `null == x` / `x != null` / `null != x`.
            case BinaryExpressionSyntax binary
                when binary.IsKind(SyntaxKind.EqualsExpression)
                    || binary.IsKind(SyntaxKind.NotEqualsExpression):
                if (IsNullLiteral(binary.Right))
                {
                    TaintTarget(binary.Left, model, tainted);
                }
                else if (IsNullLiteral(binary.Left))
                {
                    TaintTarget(binary.Right, model, tainted);
                }

                break;

            // `x = null` / `x = null!`.
            case AssignmentExpressionSyntax assign
                when assign.IsKind(SyntaxKind.SimpleAssignmentExpression)
                    && IsNullOrSuppressedNull(assign.Right):
                TaintTarget(assign.Left, model, tainted);
                break;

            // `x ??= y`: `x` is a legal `??=` target only if it is nullable.
            case AssignmentExpressionSyntax coalesceAssign
                when coalesceAssign.IsKind(SyntaxKind.CoalesceAssignmentExpression):
                TaintTarget(coalesceAssign.Left, model, tainted);
                break;

            // `x is null` / `x is not null`.
            case IsPatternExpressionSyntax isPattern
                when IsNullConstantPattern(isPattern.Pattern):
                TaintTarget(isPattern.Expression, model, tainted);
                break;

            // `x?.M` / `x?[i]`: the receiver before the `?` is nullable.
            case ConditionalAccessExpressionSyntax conditionalAccess:
                TaintTarget(conditionalAccess.Expression, model, tainted);
                break;

            // `T x = null|default`, `field = null|default`, parameter `= null`.
            case VariableDeclaratorSyntax declarator
                when declarator.Initializer != null:
                if (model.GetDeclaredSymbol(declarator) is ISymbol declared
                    && IsValueDeclarationSymbol(declared)
                    && IsDirectlyNullable(declarator.Initializer.Value, model))
                {
                    tainted.Add(Canonical(declared));
                }

                break;

            case PropertyDeclarationSyntax property
                when property.Initializer != null:
                if (model.GetDeclaredSymbol(property) is IPropertySymbol propertySymbol
                    && IsDirectlyNullable(property.Initializer.Value, model))
                {
                    tainted.Add(Canonical(propertySymbol));
                }

                break;

            case ParameterSyntax parameter
                when parameter.Default != null:
                if (model.GetDeclaredSymbol(parameter) is IParameterSymbol parameterSymbol
                    && IsDirectlyNullable(parameter.Default.Value, model))
                {
                    tainted.Add(Canonical(parameterSymbol));
                }

                break;
        }
    }

    // Records transitive taint edges for the assignment / initializer forms
    // whose RHS is not itself directly-null but reads another declaration.
    private static void CollectEdges(
        SyntaxNode node,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        // Interprocedural parameter taint: an argument that is directly null or
        // reads a (possibly tainted) declaration flows to the bound parameter, so
        // a parameter that ever receives null becomes `T?` too. This keeps a
        // pass-through call `Callee(maybeNull)` from demanding a non-null
        // parameter (GS0154) once `maybeNull` is promoted.
        //
        // Issue #914 (oblivious sink): a constructor initializer delegation
        // (`: this(...)` / `: base(...)`) is an argument-passing call site too.
        // A convenience initializer that forwards its own (possibly promoted)
        // parameters to the designated initializer — e.g. `LogMessage(string
        // context, string message) : this(DateTime.Now, threadId, context,
        // message)` where `context`/`message` are themselves promoted `string?`
        // — must promote the designated initializer's matching parameters, else
        // the delegating call demands a non-null value (GS0154). Roslyn models a
        // constructor initializer as an `IInvocationOperation`, so it flows
        // through the same argument→parameter edge collection.
        // Issue #3501: BaseObjectCreationExpressionSyntax covers BOTH explicit
        // `new Entry(null, …)` and target-typed `new(null, …)` creations — the
        // implicit form (C# 9) is a sibling syntax type, not an
        // ObjectCreationExpressionSyntax, so the RoslynAnalyzerApiMap-style
        // `[key] = new(null, "…")` initializer never flowed its null argument
        // into the record's positional parameter (GS0155 nil → string).
        if (node is InvocationExpressionSyntax
            or BaseObjectCreationExpressionSyntax
            or ConstructorInitializerSyntax
            or ElementAccessExpressionSyntax
            or ElementBindingExpressionSyntax)
        {
            CollectArgumentEdges(node, model, tainted, edges, scalarTupleEdges);
        }

        switch (node)
        {
            case AssignmentExpressionSyntax assign
                when assign.IsKind(SyntaxKind.SimpleAssignmentExpression):
                ISymbol assignTarget = ResolveAssignable(assign.Left, model);
                if (assignTarget != null)
                {
                    // A declaration's emitted type is the JOIN over its
                    // initializer AND every assignment to it. A later `lhs =
                    // <nullable>` (e.g. `id = mo["ProcessorID"]!!.ToString()`,
                    // where `object.ToString()` is declared `string?`) therefore
                    // promotes `lhs` even when the declaration's initializer was
                    // non-null (issue #2167, the `var` local-join case). A
                    // directly-nullable RHS taints immediately; any other RHS
                    // records a transitive edge so a nullable source propagates.
                    CollectScalarValueFlow(
                        assignTarget,
                        assign.Right,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                }

                break;

            case VariableDeclaratorSyntax declarator
                when declarator.Initializer != null:
                if (model.GetDeclaredSymbol(declarator) is ISymbol declared
                    && IsValueDeclarationSymbol(declared))
                {
                    CollectScalarValueFlow(
                        Canonical(declared),
                        declarator.Initializer.Value,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                }

                break;

            case PropertyDeclarationSyntax property
                when property.Initializer != null:
                if (model.GetDeclaredSymbol(property) is IPropertySymbol propertySymbol)
                {
                    CollectScalarValueFlow(
                        Canonical(propertySymbol),
                        property.Initializer.Value,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                }

                break;
        }
    }

    // Interprocedural: map each call argument to its bound parameter and add a
    // taint edge (or a direct taint for a directly-null argument), so a parameter
    // that ever receives a nullable value is itself promoted to `T?`.
    private static void CollectArgumentEdges(
        SyntaxNode call,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        ImmutableArray<IArgumentOperation> arguments = GetCallArguments(call, model);

        if (arguments.IsDefaultOrEmpty)
        {
            return;
        }

        foreach (IArgumentOperation argument in arguments)
        {
            if (argument.Parameter is not IParameterSymbol parameter
                || argument.Value?.Syntax is not ExpressionSyntax value)
            {
                continue;
            }

            ISymbol parameterSymbol = Canonical(parameter);

            // Issue #3501: a local/parameter read that a syntactic null-check
            // guard proves non-null at a CONSTRUCTOR argument does not carry
            // its declaration's taint into the parameter. The canonical shape
            // is Oahu's `if (prod is null) { continue; } pairs.Add(new(prod,
            // comp))` — `prod` is declared nullable (its producer can return
            // null) but is provably non-null at the creation, and tainting the
            // record's positional parameter widened the DATA SHAPE (`Product`
            // → `Product?` on the positional property) for every consumer,
            // including deconstruction locals whose dereferences are not
            // receiver-bridged. gsc's own smart-cast narrows the same guarded
            // read on the G# side, so the suppressed edge never reintroduces a
            // `T? -> T` mismatch. Ordinary METHOD arguments keep the
            // promotion-consolidation behavior (a tainted value symmetrically
            // widens every sink it touches — see PromotionConsolidationTests):
            // a method parameter is a local contract the forgiveness passes
            // already manage, not a data shape.
            bool guardedCreationArgument = call is BaseObjectCreationExpressionSyntax
                && IsNullGuardDominatedRead(value, model);
            if (!guardedCreationArgument)
            {
                CollectScalarValueFlow(
                    parameterSymbol,
                    value,
                    model,
                    tainted,
                    edges,
                    scalarTupleEdges);
            }

            // A parameter forwarded unchanged into another parameter inherits
            // that downstream nullable contract. This lets a null-check at the
            // end of a pass-through chain widen every upstream declaration even
            // when the original null-producing caller lives in another project.
            foreach (ISymbol source in ResolveSources(value, model))
            {
                if (source is IParameterSymbol { Type.TypeKind: TypeKind.Delegate }
                    && parameter.Type.TypeKind == TypeKind.Delegate)
                {
                    edges.Add((Canonical(source), parameterSymbol));
                }
            }

            // Issue #3501: an `out` argument flows the OPPOSITE way — the
            // callee writes the parameter's value into the caller's variable, so
            // a tainted out parameter (`bool TryGetTupleType(..., out
            // INamedTypeSymbol tupleType)` assigning an `as`-cast) makes the
            // receiving out-var local `T?` too. Without this edge the local's
            // symbol stayed untainted while gsc independently inferred the
            // out-var's type from the promoted parameter (`T?`), so downstream
            // reads passed a `T?` where the translator believed a `T` flowed
            // (GS0154) and never bridged with `!!`.
            //
            // `Deconstruct` is excluded: its out parameters feed positional
            // deconstruction locals (`for (item, comp) in pairs`) whose G#
            // types come from the tuple element rendering, not the parameter,
            // and whose oblivious dereferences are not receiver-bridged —
            // tainting them regressed the Oahu gate (member reads on a
            // now-`T?` deconstructed local). `ref` stays excluded too: the
            // caller's variable was initialized before the call, so its own
            // initializer/assignment edges already model its nullability.
            if (parameter.RefKind is RefKind.Out
                && parameter.ContainingSymbol is not IMethodSymbol { Name: "Deconstruct" })
            {
                ISymbol receiver =
                    value is DeclarationExpressionSyntax { Designation: SingleVariableDesignationSyntax designation }
                        ? model.GetDeclaredSymbol(designation)
                        : ResolveAssignable(value, model);
                if (receiver != null && IsValueDeclarationSymbol(receiver))
                {
                    edges.Add((Canonical(receiver), parameterSymbol));
                }
            }
        }
    }

    private static ImmutableArray<IArgumentOperation> GetCallArguments(
        SyntaxNode call,
        SemanticModel model) =>
        model.GetOperation(call) switch
        {
            IInvocationOperation invocation => invocation.Arguments,
            IObjectCreationOperation creation => creation.Arguments,
            IPropertyReferenceOperation property => property.Arguments,
            _ => default,
        };

    // Issue #2469: tuple-valued declarations need the same direct/transitive
    // evidence graph as scalar declarations, but keyed by an element path.
    // This pass covers tuple literals, nested tuples, conditionals/switches,
    // tuple locals/parameters/properties, calls, and deconstruction.
    private static void CollectTupleFlows(
        SyntaxNode root,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
        List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        foreach (SyntaxNode node in root.DescendantNodes())
        {
            switch (node)
            {
                case MethodDeclarationSyntax method:
                    CollectTupleReturnFlows(
                        model.GetDeclaredSymbol(method),
                        method.ExpressionBody?.Expression,
                        method.Body,
                        model,
                        tupleTainted,
                        tupleEdges,
                        tupleScalarEdges);
                    break;

                case LocalFunctionStatementSyntax localFunction:
                    CollectTupleReturnFlows(
                        model.GetDeclaredSymbol(localFunction),
                        localFunction.ExpressionBody?.Expression,
                        localFunction.Body,
                        model,
                        tupleTainted,
                        tupleEdges,
                        tupleScalarEdges);
                    break;

                case AnonymousFunctionExpressionSyntax lambda:
                    CollectTupleReturnFlows(
                        model.GetSymbolInfo(lambda).Symbol as IMethodSymbol,
                        lambda.Body as ExpressionSyntax,
                        lambda.Body as BlockSyntax,
                        model,
                        tupleTainted,
                        tupleEdges,
                        tupleScalarEdges);
                    break;

                case PropertyDeclarationSyntax property:
                    IPropertySymbol propertySymbol = model.GetDeclaredSymbol(property);
                    if (TryGetTupleType(propertySymbol, out INamedTypeSymbol propertyTuple))
                    {
                        if (property.Initializer?.Value is ExpressionSyntax initializer)
                        {
                            CollectTupleValueFlow(
                                Canonical(propertySymbol),
                                propertyTuple,
                                initializer,
                                model,
                                string.Empty,
                                tupleTainted,
                                tupleEdges,
                                tupleScalarEdges);
                        }

                        CollectTupleGetterFlows(
                            propertySymbol,
                            propertyTuple,
                            property.ExpressionBody?.Expression,
                            property.AccessorList,
                            model,
                            tupleTainted,
                            tupleEdges,
                            tupleScalarEdges);
                    }

                    break;

                case IndexerDeclarationSyntax indexer:
                    IPropertySymbol indexerSymbol = model.GetDeclaredSymbol(indexer);
                    if (TryGetTupleType(indexerSymbol, out INamedTypeSymbol indexerTuple))
                    {
                        CollectTupleGetterFlows(
                            indexerSymbol,
                            indexerTuple,
                            indexer.ExpressionBody?.Expression,
                            indexer.AccessorList,
                            model,
                            tupleTainted,
                            tupleEdges,
                            tupleScalarEdges);
                    }

                    break;

                case VariableDeclaratorSyntax declarator
                    when declarator.Initializer?.Value is ExpressionSyntax initializer:
                    ISymbol declared = model.GetDeclaredSymbol(declarator);
                    if (declared != null && SymbolValueType(declared) is ITypeSymbol declaredType)
                    {
                        CollectDeclarationTupleFlow(
                            Canonical(declared),
                            declaredType,
                            initializer,
                            model,
                            tupleTainted,
                            tupleEdges,
                            tupleScalarEdges);
                    }

                    break;

                case AssignmentExpressionSyntax assignment
                    when assignment.IsKind(SyntaxKind.SimpleAssignmentExpression):
                    ISymbol target = ResolveAssignable(assignment.Left, model);
                    if (target != null && SymbolValueType(target) is ITypeSymbol assignedType)
                    {
                        CollectDeclarationTupleFlow(
                            target,
                            assignedType,
                            assignment.Right,
                            model,
                            tupleTainted,
                            tupleEdges,
                            tupleScalarEdges);
                    }
                    else if (assignment.Left is TupleExpressionSyntax or DeclarationExpressionSyntax)
                    {
                        CollectDeconstructionFlow(
                            assignment.Left,
                            assignment.Right,
                            model,
                            tainted,
                            edges,
                            scalarTupleEdges);
                    }

                    break;

                case InvocationExpressionSyntax
                    or ObjectCreationExpressionSyntax
                    or ConstructorInitializerSyntax
                    or ElementAccessExpressionSyntax
                    or ElementBindingExpressionSyntax:
                    CollectTupleArgumentFlows(
                        node,
                        model,
                        tupleTainted,
                        tupleEdges,
                        tupleScalarEdges);
                    break;
            }
        }
    }

    private static void CollectTupleReturnFlows(
        IMethodSymbol method,
        ExpressionSyntax arrowBody,
        BlockSyntax body,
        SemanticModel model,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
        List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges)
    {
        ITypeSymbol returnType = SymbolValueType(method);
        if (returnType is not INamedTypeSymbol { IsTupleType: true }
            && NestedTupleSlots(returnType).Count == 0)
        {
            return;
        }

        ISymbol target = Canonical(method);
        if (arrowBody != null)
        {
            CollectDeclarationTupleFlow(
                target,
                returnType,
                arrowBody,
                model,
                tupleTainted,
                tupleEdges,
                tupleScalarEdges);
        }

        foreach (ReturnStatementSyntax statement in EnumerateOwnReturns(body))
        {
            if (statement.Expression != null)
            {
                CollectDeclarationTupleFlow(
                    target,
                    returnType,
                    statement.Expression,
                    model,
                    tupleTainted,
                    tupleEdges,
                    tupleScalarEdges);
            }
        }
    }

    private static void CollectTupleGetterFlows(
        IPropertySymbol property,
        INamedTypeSymbol tupleType,
        ExpressionSyntax arrowBody,
        AccessorListSyntax accessorList,
        SemanticModel model,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
        List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges)
    {
        ISymbol target = Canonical(property);
        if (arrowBody != null)
        {
            CollectTupleValueFlow(
                target,
                tupleType,
                arrowBody,
                model,
                string.Empty,
                tupleTainted,
                tupleEdges,
                tupleScalarEdges);
        }

        AccessorDeclarationSyntax getter = accessorList?.Accessors
            .FirstOrDefault(a => a.IsKind(SyntaxKind.GetAccessorDeclaration));
        if (getter?.ExpressionBody?.Expression is ExpressionSyntax getterArrow)
        {
            CollectTupleValueFlow(
                target,
                tupleType,
                getterArrow,
                model,
                string.Empty,
                tupleTainted,
                tupleEdges,
                tupleScalarEdges);
        }

        foreach (ReturnStatementSyntax statement in EnumerateOwnReturns(getter?.Body))
        {
            if (statement.Expression != null)
            {
                CollectTupleValueFlow(
                    target,
                    tupleType,
                    statement.Expression,
                    model,
                    string.Empty,
                    tupleTainted,
                    tupleEdges,
                    tupleScalarEdges);
            }
        }
    }

    private static void CollectTupleArgumentFlows(
        SyntaxNode call,
        SemanticModel model,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
        List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges)
    {
        ImmutableArray<IArgumentOperation> arguments = GetCallArguments(call, model);

        if (arguments.IsDefaultOrEmpty)
        {
            return;
        }

        foreach (IArgumentOperation argument in arguments)
        {
            if (argument.Parameter is IParameterSymbol parameter
                && argument.Value?.Syntax is ExpressionSyntax value
                && parameter.Type is ITypeSymbol parameterType)
            {
                CollectDeclarationTupleFlow(
                    Canonical(parameter),
                    parameterType,
                    value,
                    model,
                    tupleTainted,
                    tupleEdges,
                    tupleScalarEdges);
            }

            CollectGenericReceiverTupleArgumentFlow(
                call,
                argument,
                model,
                tupleTainted,
                tupleEdges,
                tupleScalarEdges);
        }
    }

    // Issue #3564: Dictionary<TKey, TValue> indexer/method parameters use the
    // receiver's generic TKey slot. When a promoted tuple flows into that slot,
    // carry its per-element taint back to the source field/property type so all
    // uses share Dictionary[(T?, U), TValue] instead of asserting at each use.
    private static void CollectGenericReceiverTupleArgumentFlow(
        SyntaxNode call,
        IArgumentOperation argument,
        SemanticModel model,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
        List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges)
    {
        ExpressionSyntax receiver = call switch
        {
            InvocationExpressionSyntax { Expression: MemberAccessExpressionSyntax member } =>
                member.Expression,
            ElementAccessExpressionSyntax elementAccess => elementAccess.Expression,
            _ => null,
        };

        ISymbol target = receiver == null ? null : model.GetSymbolInfo(receiver).Symbol;

        // Issue #3641: a LOCAL collection is just as much a declaration sink as
        // a field/property — `var prepared = new List<(string, byte[])>();
        // prepared.Add((path, original))` is where the null-bearing element
        // enters the tuple that the enclosing method then returns.
        ITypeSymbol targetType = target switch
        {
            IFieldSymbol field => field.Type,
            IPropertySymbol property => property.Type,
            ILocalSymbol local => local.Type,
            IParameterSymbol receiverParameter => receiverParameter.Type,
            _ => null,
        };

        // Scalar flow already treats out as callee-to-caller and deliberately
        // excludes ref, so neither is receiver-directed here.
        if (target is not (IFieldSymbol or IPropertySymbol or ILocalSymbol or IParameterSymbol)
            || targetType is not INamedTypeSymbol receiverType
            || argument.Parameter is not IParameterSymbol parameter
            || parameter.RefKind is RefKind.Out or RefKind.Ref
            || !TryGetGenericReceiverTuplePath(
                receiverType,
                parameter,
                out INamedTypeSymbol tupleType,
                out IReadOnlyList<int> tuplePath)
            || argument.Value?.Syntax is not ExpressionSyntax value)
        {
            return;
        }

        CollectTupleValueFlow(
            Canonical(target),
            tupleType,
            value,
            model,
            EncodeTuplePath(tuplePath),
            tupleTainted,
            tupleEdges,
            tupleScalarEdges);
    }

    /// <summary>
    /// Issue #3641: routes a value flowing into a declaration to the bare-tuple
    /// collector or to the nested (generic type argument) one, so a tuple that
    /// lives under `List&lt;T&gt;` / `IReadOnlyList&lt;T&gt;` / `IEnumerable&lt;T&gt;` is the same
    /// declaration sink as a bare tuple. G# tuple types agree structurally, so a
    /// producer's return, the intermediate locals and the consumer's parameter
    /// must all render an element identically or none of them may.
    /// </summary>
    /// <param name="target">The declaration receiving the value.</param>
    /// <param name="targetType">The declaration's declared (or awaited) type.</param>
    /// <param name="value">The flowing value expression.</param>
    /// <param name="model">The semantic model for <paramref name="value"/>.</param>
    /// <param name="tupleTainted">Directly tainted tuple leaves.</param>
    /// <param name="tupleEdges">Tuple-leaf to tuple-leaf edges.</param>
    /// <param name="tupleScalarEdges">Tuple-leaf to scalar-declaration edges.</param>
    private static void CollectDeclarationTupleFlow(
        ISymbol target,
        ITypeSymbol targetType,
        ExpressionSyntax value,
        SemanticModel model,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
        List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges)
    {
        if (target == null)
        {
            return;
        }

        if (targetType is INamedTypeSymbol { IsTupleType: true } tuple)
        {
            CollectTupleValueFlow(
                target,
                tuple,
                value,
                model,
                string.Empty,
                tupleTainted,
                tupleEdges,
                tupleScalarEdges);
            return;
        }

        CollectNestedTupleValueFlow(target, targetType, value, model, tupleTainted, tupleEdges);
    }

    // Issue #3641: pairs the nested tuple slots of the target's declared type
    // with those of the source's, positionally and only when both sides expose
    // the same number of slots with the same element arity. That keeps the
    // pairing sound across the covariant hand-offs the shape actually uses
    // (`List<T>` returned as `IReadOnlyList<T>`, passed as `IEnumerable<T>`)
    // without inventing a second cross-signature keying model: each side keeps
    // the element path of ITS OWN rendered type.
    private static void CollectNestedTupleValueFlow(
        ISymbol target,
        ITypeSymbol targetType,
        ExpressionSyntax value,
        SemanticModel model,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges)
    {
        List<(string Path, INamedTypeSymbol Tuple)> targetSlots = NestedTupleSlots(targetType);
        if (targetSlots.Count == 0)
        {
            return;
        }

        value = UnwrapTupleValue(value);
        switch (value)
        {
            case null:
                return;

            case ConditionalExpressionSyntax conditional:
                CollectNestedTupleValueFlow(
                    target, targetType, conditional.WhenTrue, model, tupleTainted, tupleEdges);
                CollectNestedTupleValueFlow(
                    target, targetType, conditional.WhenFalse, model, tupleTainted, tupleEdges);
                return;

            case SwitchExpressionSyntax switchExpression:
                foreach (SwitchExpressionArmSyntax arm in switchExpression.Arms)
                {
                    CollectNestedTupleValueFlow(
                        target, targetType, arm.Expression, model, tupleTainted, tupleEdges);
                }

                return;
        }

        ISymbol source = value switch
        {
            InvocationExpressionSyntax or IdentifierNameSyntax or MemberAccessExpressionSyntax =>
                model.GetSymbolInfo(value).Symbol,
            _ => null,
        };

        if (source == null)
        {
            return;
        }

        List<(string Path, INamedTypeSymbol Tuple)> sourceSlots = NestedTupleSlots(SymbolValueType(source));
        if (sourceSlots.Count != targetSlots.Count)
        {
            return;
        }

        for (int i = 0; i < targetSlots.Count; i++)
        {
            if (targetSlots[i].Tuple.TupleElements.Length != sourceSlots[i].Tuple.TupleElements.Length)
            {
                return;
            }
        }

        ISymbol canonicalSource = Canonical(source);
        for (int i = 0; i < targetSlots.Count; i++)
        {
            AddTupleShapeEdges(
                target,
                targetSlots[i].Tuple,
                targetSlots[i].Path,
                canonicalSource,
                sourceSlots[i].Tuple,
                sourceSlots[i].Path,
                tupleTainted,
                tupleEdges);
        }
    }

    private static void CollectTupleValueFlow(
        ISymbol target,
        INamedTypeSymbol targetTuple,
        ExpressionSyntax value,
        SemanticModel model,
        string prefix,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
        List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges)
    {
        value = UnwrapTupleValue(value);
        switch (value)
        {
            case null:
                return;

            case ConditionalExpressionSyntax conditional:
                CollectTupleValueFlow(target, targetTuple, conditional.WhenTrue, model, prefix, tupleTainted, tupleEdges, tupleScalarEdges);
                CollectTupleValueFlow(target, targetTuple, conditional.WhenFalse, model, prefix, tupleTainted, tupleEdges, tupleScalarEdges);
                return;

            case SwitchExpressionSyntax switchExpression:
                foreach (SwitchExpressionArmSyntax arm in switchExpression.Arms)
                {
                    CollectTupleValueFlow(target, targetTuple, arm.Expression, model, prefix, tupleTainted, tupleEdges, tupleScalarEdges);
                }

                return;

            case TupleExpressionSyntax tuple
                when tuple.Arguments.Count == targetTuple.TupleElements.Length:
                for (int i = 0; i < targetTuple.TupleElements.Length; i++)
                {
                    ITypeSymbol targetType = targetTuple.TupleElements[i].Type;
                    ExpressionSyntax elementValue = tuple.Arguments[i].Expression;
                    string path = AppendTuplePath(prefix, i);
                    if (targetType is INamedTypeSymbol { IsTupleType: true } nestedTarget)
                    {
                        CollectTupleValueFlow(
                            target,
                            nestedTarget,
                            elementValue,
                            model,
                            path,
                            tupleTainted,
                            tupleEdges,
                            tupleScalarEdges);
                    }
                    else if (IsEligibleTupleLeaf(targetType))
                    {
                        var targetKey = new TupleElementKey(target, path);
                        if (IsDirectlyNullable(elementValue, model))
                        {
                            tupleTainted.Add(targetKey);
                        }
                        else if (TryResolveTupleElementSource(elementValue, model, out TupleElementKey tupleSource))
                        {
                            tupleEdges.Add((targetKey, tupleSource));
                        }
                        else
                        {
                            foreach (ISymbol scalarSource in ResolveSources(elementValue, model))
                            {
                                // Issue #3615 (2026-08-28 nightly, Cs2Gs.Translator
                                // wall): only SOURCE-declared symbols propagate
                                // into a declaration's tuple element. An imported
                                // metadata member can enter the tainted set only
                                // through the defensive-use seeds (`x?.M` /
                                // `x == null` at some OTHER site) — its declared
                                // annotation is the contract for the value
                                // flowing HERE, and an annotated-nullable
                                // imported read is already caught by
                                // IsDirectlyNullable above. Letting the
                                // defensive-use heuristic rewrite a source
                                // field's element type widened
                                // `HashSet[(SyntaxTree, ...)]` to
                                // `(SyntaxTree?, ...)` and broke every
                                // deconstructing reader. Source-declared is
                                // tested via DeclaringSyntaxReferences (an
                                // imported metadata symbol has none); the null
                                // guard also keeps the self-migrated form of
                                // this loop well-typed — ResolveSources'
                                // iterator element is promoted to ISymbol? by
                                // the same analysis this file implements.
                                if (scalarSource == null)
                                {
                                    continue;
                                }

                                if (scalarSource.DeclaringSyntaxReferences.IsDefaultOrEmpty)
                                {
                                    continue;
                                }

                                tupleScalarEdges.Add((targetKey, scalarSource));
                            }
                        }
                    }
                }

                return;
        }

        if (IsDefaultTupleValue(value, model))
        {
            TaintAllTupleLeaves(target, targetTuple, prefix, tupleTainted);
            return;
        }

        if (TryResolveTupleSource(value, model, out ISymbol source, out INamedTypeSymbol sourceTuple))
        {
            AddTupleShapeEdges(
                target,
                targetTuple,
                prefix,
                source,
                sourceTuple,
                string.Empty,
                tupleTainted,
                tupleEdges);
        }
    }

    private static void AddTupleShapeEdges(
        ISymbol target,
        INamedTypeSymbol targetTuple,
        string targetPrefix,
        ISymbol source,
        INamedTypeSymbol sourceTuple,
        string sourcePrefix,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges)
    {
        int count = System.Math.Min(targetTuple.TupleElements.Length, sourceTuple.TupleElements.Length);
        for (int i = 0; i < count; i++)
        {
            ITypeSymbol targetType = targetTuple.TupleElements[i].Type;
            ITypeSymbol sourceType = sourceTuple.TupleElements[i].Type;
            string targetPath = AppendTuplePath(targetPrefix, i);
            string sourcePath = AppendTuplePath(sourcePrefix, i);

            if (targetType is INamedTypeSymbol { IsTupleType: true } nestedTarget
                && sourceType is INamedTypeSymbol { IsTupleType: true } nestedSource)
            {
                AddTupleShapeEdges(
                    target,
                    nestedTarget,
                    targetPath,
                    source,
                    nestedSource,
                    sourcePath,
                    tupleTainted,
                    tupleEdges);
            }
            else if (IsEligibleTupleLeaf(targetType))
            {
                var targetKey = new TupleElementKey(target, targetPath);
                if (sourceType is { IsReferenceType: true, NullableAnnotation: NullableAnnotation.Annotated })
                {
                    tupleTainted.Add(targetKey);
                }
                else
                {
                    tupleEdges.Add((targetKey, new TupleElementKey(source, sourcePath)));
                }
            }
        }
    }

    private static void TaintAllTupleLeaves(
        ISymbol target,
        INamedTypeSymbol tupleType,
        string prefix,
        HashSet<TupleElementKey> tupleTainted)
    {
        for (int i = 0; i < tupleType.TupleElements.Length; i++)
        {
            ITypeSymbol elementType = tupleType.TupleElements[i].Type;
            string path = AppendTuplePath(prefix, i);
            if (elementType is INamedTypeSymbol { IsTupleType: true } nested)
            {
                TaintAllTupleLeaves(target, nested, path, tupleTainted);
            }
            else if (IsEligibleTupleLeaf(elementType))
            {
                tupleTainted.Add(new TupleElementKey(target, path));
            }
        }
    }

    private static void CollectDeconstructionFlow(
        ExpressionSyntax targetPattern,
        ExpressionSyntax value,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        value = UnwrapTupleValue(value);
        if (value is ConditionalExpressionSyntax conditional)
        {
            CollectDeconstructionFlow(targetPattern, conditional.WhenTrue, model, tainted, edges, scalarTupleEdges);
            CollectDeconstructionFlow(targetPattern, conditional.WhenFalse, model, tainted, edges, scalarTupleEdges);
            return;
        }

        if (value is SwitchExpressionSyntax switchExpression)
        {
            foreach (SwitchExpressionArmSyntax arm in switchExpression.Arms)
            {
                CollectDeconstructionFlow(targetPattern, arm.Expression, model, tainted, edges, scalarTupleEdges);
            }

            return;
        }

        if (value is TupleExpressionSyntax tupleValue
            && TryGetDeconstructionElements(targetPattern, out IReadOnlyList<ExpressionSyntax> targets)
            && targets.Count == tupleValue.Arguments.Count)
        {
            for (int i = 0; i < targets.Count; i++)
            {
                CollectDeconstructionFlow(
                    targets[i],
                    tupleValue.Arguments[i].Expression,
                    model,
                    tainted,
                    edges,
                    scalarTupleEdges);
            }

            return;
        }

        if (value is TupleExpressionSyntax declarationTupleValue
            && targetPattern is DeclarationExpressionSyntax
            { Designation: ParenthesizedVariableDesignationSyntax declarationPattern }
            && declarationPattern.Variables.Count == declarationTupleValue.Arguments.Count)
        {
            for (int i = 0; i < declarationPattern.Variables.Count; i++)
            {
                CollectDesignationFlow(
                    declarationPattern.Variables[i],
                    declarationTupleValue.Arguments[i].Expression,
                    model,
                    tainted,
                    edges,
                    scalarTupleEdges);
            }

            return;
        }

        if (TryResolveDeconstructionTarget(targetPattern, model, out ISymbol scalarTarget))
        {
            if (IsDirectlyNullable(value, model))
            {
                tainted.Add(scalarTarget);
            }
            else if (TryResolveTupleElementSource(value, model, out TupleElementKey elementSource))
            {
                scalarTupleEdges.Add((scalarTarget, elementSource));
            }
            else
            {
                AddEdges(scalarTarget, value, model, edges);
            }

            return;
        }

        if (TryResolveTupleSource(value, model, out ISymbol tupleSource, out INamedTypeSymbol sourceTuple))
        {
            if (targetPattern is DeclarationExpressionSyntax
                { Designation: ParenthesizedVariableDesignationSyntax forwardedPattern })
            {
                CollectDesignationPatternFromTupleSource(
                    forwardedPattern,
                    tupleSource,
                    sourceTuple,
                    string.Empty,
                    model,
                    scalarTupleEdges);
                return;
            }

            CollectPatternFromTupleSource(
                targetPattern,
                tupleSource,
                sourceTuple,
                string.Empty,
                model,
                scalarTupleEdges);
        }
    }

    private static void CollectDesignationFlow(
        VariableDesignationSyntax target,
        ExpressionSyntax value,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        if (target is ParenthesizedVariableDesignationSyntax parenthesized
            && value is TupleExpressionSyntax tuple
            && parenthesized.Variables.Count == tuple.Arguments.Count)
        {
            for (int i = 0; i < parenthesized.Variables.Count; i++)
            {
                CollectDesignationFlow(
                    parenthesized.Variables[i],
                    tuple.Arguments[i].Expression,
                    model,
                    tainted,
                    edges,
                    scalarTupleEdges);
            }

            return;
        }

        if (target is not SingleVariableDesignationSyntax single
            || model.GetDeclaredSymbol(single) is not ISymbol declared
            || !IsValueDeclarationSymbol(declared))
        {
            return;
        }

        ISymbol scalarTarget = Canonical(declared);
        if (IsDirectlyNullable(value, model))
        {
            tainted.Add(scalarTarget);
        }
        else if (TryResolveTupleElementSource(value, model, out TupleElementKey elementSource))
        {
            scalarTupleEdges.Add((scalarTarget, elementSource));
        }
        else
        {
            AddEdges(scalarTarget, value, model, edges);
        }
    }

    private static void CollectPatternFromTupleSource(
        ExpressionSyntax pattern,
        ISymbol source,
        INamedTypeSymbol sourceTuple,
        string prefix,
        SemanticModel model,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        if (!TryGetDeconstructionElements(pattern, out IReadOnlyList<ExpressionSyntax> targets))
        {
            return;
        }

        int count = System.Math.Min(targets.Count, sourceTuple.TupleElements.Length);
        for (int i = 0; i < count; i++)
        {
            ITypeSymbol sourceType = sourceTuple.TupleElements[i].Type;
            string path = AppendTuplePath(prefix, i);
            if (sourceType is INamedTypeSymbol { IsTupleType: true } nested)
            {
                CollectPatternFromTupleSource(targets[i], source, nested, path, model, scalarTupleEdges);
            }
            else if (TryResolveDeconstructionTarget(targets[i], model, out ISymbol scalarTarget))
            {
                scalarTupleEdges.Add((scalarTarget, new TupleElementKey(source, path)));
            }
        }
    }

    private static void CollectDesignationPatternFromTupleSource(
        ParenthesizedVariableDesignationSyntax pattern,
        ISymbol source,
        INamedTypeSymbol sourceTuple,
        string prefix,
        SemanticModel model,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        int count = System.Math.Min(pattern.Variables.Count, sourceTuple.TupleElements.Length);
        for (int i = 0; i < count; i++)
        {
            VariableDesignationSyntax target = pattern.Variables[i];
            ITypeSymbol sourceType = sourceTuple.TupleElements[i].Type;
            string path = AppendTuplePath(prefix, i);
            if (target is ParenthesizedVariableDesignationSyntax nestedPattern
                && sourceType is INamedTypeSymbol { IsTupleType: true } nestedTuple)
            {
                CollectDesignationPatternFromTupleSource(
                    nestedPattern,
                    source,
                    nestedTuple,
                    path,
                    model,
                    scalarTupleEdges);
            }
            else if (target is SingleVariableDesignationSyntax single
                && model.GetDeclaredSymbol(single) is ISymbol declared
                && IsValueDeclarationSymbol(declared))
            {
                scalarTupleEdges.Add((Canonical(declared), new TupleElementKey(source, path)));
            }
        }
    }

    private static bool TryGetDeconstructionElements(
        ExpressionSyntax pattern,
        out IReadOnlyList<ExpressionSyntax> elements)
    {
        if (pattern is TupleExpressionSyntax tuple)
        {
            elements = tuple.Arguments.Select(a => a.Expression).ToList();
            return true;
        }

        elements = null;
        return false;
    }

    private static bool TryResolveDeconstructionTarget(
        ExpressionSyntax target,
        SemanticModel model,
        out ISymbol symbol)
    {
        symbol = target switch
        {
            IdentifierNameSyntax identifier => model.GetSymbolInfo(identifier).Symbol,
            DeclarationExpressionSyntax { Designation: SingleVariableDesignationSyntax single } =>
                model.GetDeclaredSymbol(single),
            _ => null,
        };

        if (symbol != null && IsValueDeclarationSymbol(symbol))
        {
            symbol = Canonical(symbol);
            return true;
        }

        symbol = null;
        return false;
    }

    private static bool TryResolveTupleSource(
        ExpressionSyntax expression,
        SemanticModel model,
        out ISymbol symbol,
        out INamedTypeSymbol tupleType)
    {
        expression = UnwrapTupleValue(expression);
        symbol = expression switch
        {
            InvocationExpressionSyntax invocation => model.GetSymbolInfo(invocation).Symbol,
            IdentifierNameSyntax or MemberAccessExpressionSyntax => model.GetSymbolInfo(expression).Symbol,
            _ => null,
        };

        if (TryGetTupleType(symbol, out tupleType))
        {
            symbol = Canonical(symbol);
            return true;
        }

        symbol = null;
        tupleType = null;
        return false;
    }

    private static bool TryResolveTupleElementSource(
        ExpressionSyntax expression,
        SemanticModel model,
        out TupleElementKey source)
    {
        expression = UnwrapTupleValue(expression);
        if (expression is MemberAccessExpressionSyntax member
            && model.GetSymbolInfo(member).Symbol is IFieldSymbol field
            && model.GetTypeInfo(member.Expression).Type is INamedTypeSymbol { IsTupleType: true } receiverTuple)
        {
            int index = TupleElementIndex(receiverTuple, field);
            if (index >= 0)
            {
                if (TryResolveTupleElementSource(member.Expression, model, out TupleElementKey parent))
                {
                    source = new TupleElementKey(parent.Symbol, AppendTuplePath(parent.Path, index));
                    return true;
                }

                if (TryResolveTupleSource(member.Expression, model, out ISymbol symbol, out _))
                {
                    source = new TupleElementKey(symbol, index.ToString(System.Globalization.CultureInfo.InvariantCulture));
                    return true;
                }
            }
        }

        source = default;
        return false;
    }

    // Issue #3663: resolves a read of a variable declared by a DECONSTRUCTING
    // `foreach` header back to the leaf it aliases — the enumerated collection's
    // declaration symbol plus the element path the type mapper walks when it
    // renders that declaration (`PromoteTupleTypeArguments`: type-argument
    // indexes first, tuple element indexes after). Both header spellings climb
    // the same way: `var (a, b)` nests SingleVariableDesignations inside a
    // ParenthesizedVariableDesignation, while the explicitly typed `(A a, B b)`
    // nests DeclarationExpressions inside a TupleExpression.
    private static bool TryResolveForEachDeconstructionSource(
        ExpressionSyntax expression,
        SemanticModel model,
        out TupleElementKey source)
    {
        source = default;
        if (model.GetSymbolInfo(expression).Symbol is not ILocalSymbol local
            || local.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax()
                is not SingleVariableDesignationSyntax designation)
        {
            return false;
        }

        var indexes = new List<int>();
        SyntaxNode current = designation;
        bool climbing = true;
        while (climbing)
        {
            switch (current.Parent)
            {
                case ParenthesizedVariableDesignationSyntax nested
                    when current is VariableDesignationSyntax variable:
                    int nestedIndex = nested.Variables.IndexOf(variable);
                    if (nestedIndex < 0)
                    {
                        return false;
                    }

                    indexes.Insert(0, nestedIndex);
                    current = nested;
                    break;

                case DeclarationExpressionSyntax declaration:
                    current = declaration;
                    break;

                case ArgumentSyntax { Parent: TupleExpressionSyntax tuple } argument:
                    int tupleIndex = tuple.Arguments.IndexOf(argument);
                    if (tupleIndex < 0)
                    {
                        return false;
                    }

                    indexes.Insert(0, tupleIndex);
                    current = tuple;
                    break;

                default:
                    climbing = false;
                    break;
            }
        }

        if (indexes.Count == 0
            || current.Parent is not ForEachVariableStatementSyntax forEach
            || forEach.Variable != current)
        {
            return false;
        }

        if (model.GetForEachStatementInfo(forEach).ElementType
                is not INamedTypeSymbol { IsTupleType: true } elementTuple
            || model.GetSymbolInfo(forEach.Expression).Symbol is not { } collection
            || SymbolValueType(collection) is not { } collectionType)
        {
            return false;
        }

        // The enumerated element tuple has to sit at exactly ONE position of the
        // collection's rendered type; an ambiguous match (two identical tuple
        // slots) would key the leaf arbitrarily, so leave those unbridged.
        List<(string Path, INamedTypeSymbol Tuple)> slots = NestedTupleSlots(collectionType)
            .Where(slot => SymbolEqualityComparer.Default.Equals(slot.Tuple, elementTuple))
            .ToList();
        if (slots.Count != 1)
        {
            return false;
        }

        string path = slots[0].Path;
        foreach (int index in indexes)
        {
            path = AppendTuplePath(path, index);
        }

        source = new TupleElementKey(Canonical(collection), path);
        return true;
    }

    private static int TupleElementIndex(INamedTypeSymbol tupleType, IFieldSymbol field)
    {
        IFieldSymbol canonicalField = field.CorrespondingTupleField ?? field;
        for (int i = 0; i < tupleType.TupleElements.Length; i++)
        {
            IFieldSymbol candidate = tupleType.TupleElements[i].CorrespondingTupleField
                ?? tupleType.TupleElements[i];
            if (SymbolEqualityComparer.Default.Equals(candidate, canonicalField)
                || tupleType.TupleElements[i].Name == field.Name)
            {
                return i;
            }
        }

        return -1;
    }

    private static bool TryGetTupleType(ISymbol symbol, out INamedTypeSymbol tupleType)
    {
        tupleType = SymbolValueType(symbol) as INamedTypeSymbol;
        return tupleType is { IsTupleType: true };
    }

    /// <summary>
    /// The type of the value a declaration symbol denotes — a method's
    /// (awaited) return type, otherwise the declared type. Returns
    /// <see langword="null"/> for symbols that are not value declarations.
    /// </summary>
    /// <param name="symbol">The candidate declaration symbol.</param>
    /// <returns>The denoted value type, or <see langword="null"/>.</returns>
    private static ITypeSymbol SymbolValueType(ISymbol symbol) => symbol switch
    {
        IMethodSymbol method => UnwrapAwaitedType(method.ReturnType),
        IPropertySymbol property => property.Type,
        IFieldSymbol field => field.Type,
        ILocalSymbol local => local.Type,
        IParameterSymbol parameter => parameter.Type,
        _ => null,
    };

    /// <summary>
    /// Issue #3641: the tuple positions reachable from <paramref name="type"/>
    /// through generic type ARGUMENTS (`List&lt;(string, byte[])&gt;`), keyed by the
    /// very path the type mapper walks when it renders the declaration
    /// (<c>PromoteTupleTypeArguments</c>): type-argument indexes first, tuple
    /// element indexes after. Bare tuple types are excluded — those already own
    /// the empty-prefix key — so the two collectors never key the same leaf twice.
    /// </summary>
    /// <param name="type">The declared type to scan.</param>
    /// <returns>The nested tuple slots, outermost type argument first.</returns>
    private static List<(string Path, INamedTypeSymbol Tuple)> NestedTupleSlots(ITypeSymbol type)
    {
        var slots = new List<(string Path, INamedTypeSymbol Tuple)>();
        if (type is INamedTypeSymbol { IsTupleType: false })
        {
            CollectNestedTupleSlots(type, string.Empty, slots);
        }

        return slots;
    }

    private static void CollectNestedTupleSlots(
        ITypeSymbol type,
        string prefix,
        List<(string Path, INamedTypeSymbol Tuple)> slots)
    {
        if (type is not INamedTypeSymbol named)
        {
            return;
        }

        if (named.IsTupleType)
        {
            slots.Add((prefix, named));
            return;
        }

        for (int i = 0; i < named.TypeArguments.Length; i++)
        {
            CollectNestedTupleSlots(named.TypeArguments[i], AppendTuplePath(prefix, i), slots);
        }
    }

    private static bool TryResolveReceiverTypeParameterPath(
        INamedTypeSymbol receiverType,
        INamedTypeSymbol declaringType,
        int ordinal,
        out INamedTypeSymbol tupleType,
        out IReadOnlyList<int> path)
    {
        tupleType = null;
        path = null;
        if (SymbolEqualityComparer.Default.Equals(receiverType.OriginalDefinition, declaringType))
        {
            if (ordinal >= receiverType.TypeArguments.Length
                || receiverType.TypeArguments[ordinal]
                    is not INamedTypeSymbol { IsTupleType: true } directTuple)
            {
                return false;
            }

            tupleType = directTuple;
            path = new[] { ordinal };
            return true;
        }

        foreach ((INamedTypeSymbol constructed, INamedTypeSymbol template) in
            EnumerateDirectReceiverTypes(receiverType))
        {
            if (!TryResolveReceiverTypeParameterPath(
                    constructed,
                    declaringType,
                    ordinal,
                    out INamedTypeSymbol inheritedTuple,
                    out IReadOnlyList<int> inheritedPath)
                || !TryFollowTypeArgumentPath(template, inheritedPath, out ITypeSymbol source)
                || source is not ITypeParameterSymbol sourceParameter
                || sourceParameter.ContainingType is not INamedTypeSymbol sourceOwner
                || !SymbolEqualityComparer.Default.Equals(
                    sourceOwner.OriginalDefinition,
                    receiverType.OriginalDefinition))
            {
                continue;
            }

            tupleType = inheritedTuple;
            path = new[] { sourceParameter.Ordinal };
            return true;
        }

        return false;
    }

    private static IEnumerable<(INamedTypeSymbol Constructed, INamedTypeSymbol Template)>
        EnumerateDirectReceiverTypes(INamedTypeSymbol receiverType)
    {
        INamedTypeSymbol original = receiverType.OriginalDefinition;
        if (receiverType.BaseType is INamedTypeSymbol baseType
            && original.BaseType is INamedTypeSymbol baseTemplate)
        {
            yield return (baseType, baseTemplate);
        }

        foreach (INamedTypeSymbol iface in receiverType.Interfaces)
        {
            INamedTypeSymbol template = original.Interfaces.FirstOrDefault(candidate =>
                SymbolEqualityComparer.Default.Equals(
                    candidate.OriginalDefinition,
                    iface.OriginalDefinition));
            if (template != null)
            {
                yield return (iface, template);
            }
        }
    }

    private static bool TryFollowTypeArgumentPath(
        INamedTypeSymbol type,
        IReadOnlyList<int> path,
        out ITypeSymbol result)
    {
        result = type;
        foreach (int index in path)
        {
            if (result is not INamedTypeSymbol named || index >= named.TypeArguments.Length)
            {
                result = null;
                return false;
            }

            result = named.TypeArguments[index];
        }

        return true;
    }

    private static bool IsEligibleTupleLeaf(ITypeSymbol type) =>
        type is { IsReferenceType: true }
            && type.NullableAnnotation != NullableAnnotation.Annotated;

    private static bool IsEligibleScalarTarget(ISymbol symbol)
    {
        ITypeSymbol type = SymbolValueType(symbol);

        return type is { IsReferenceType: true }
            && type.NullableAnnotation != NullableAnnotation.Annotated;
    }

    private static bool IsDefaultTupleValue(ExpressionSyntax expression, SemanticModel model) =>
        expression is DefaultExpressionSyntax
            || (expression is LiteralExpressionSyntax literal
                && literal.IsKind(SyntaxKind.DefaultLiteralExpression)
                && model.GetTypeInfo(literal).ConvertedType is INamedTypeSymbol { IsTupleType: true });

    private static ExpressionSyntax UnwrapTupleValue(ExpressionSyntax expression)
    {
        while (true)
        {
            switch (expression)
            {
                case ParenthesizedExpressionSyntax parenthesized:
                    expression = parenthesized.Expression;
                    continue;
                case CastExpressionSyntax cast:
                    expression = cast.Expression;
                    continue;
                case AwaitExpressionSyntax awaitExpression:
                    expression = awaitExpression.Expression;
                    continue;
                default:
                    return expression;
            }
        }
    }

    private static string AppendTuplePath(string prefix, int index) =>
        string.IsNullOrEmpty(prefix)
            ? index.ToString(System.Globalization.CultureInfo.InvariantCulture)
            : prefix + "." + index.ToString(System.Globalization.CultureInfo.InvariantCulture);

    private static string EncodeTuplePath(IReadOnlyList<int> path) =>
        string.Join(".", path.Select(i => i.ToString(System.Globalization.CultureInfo.InvariantCulture)));

    // Return taint: for each method / accessor / local function, examine every
    // `return` (or arrow expression body) that belongs to it (not to a nested
    // lambda / local function). A directly-null return taints the member's
    // return symbol immediately; any other return records a transitive edge.
    private static void SeedReturnTaint(
        SyntaxNode root,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        foreach (SyntaxNode node in root.DescendantNodes())
        {
            switch (node)
            {
                case MethodDeclarationSyntax method:
                    SeedMethodLikeReturnTaint(
                        model.GetDeclaredSymbol(method),
                        method.ExpressionBody?.Expression,
                        method.Body,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                    break;

                case LocalFunctionStatementSyntax localFunction:
                    SeedMethodLikeReturnTaint(
                        model.GetDeclaredSymbol(localFunction),
                        localFunction.ExpressionBody?.Expression,
                        localFunction.Body,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                    break;

                case AnonymousFunctionExpressionSyntax lambda:
                    SeedMethodLikeReturnTaint(
                        model.GetSymbolInfo(lambda).Symbol,
                        lambda.Body as ExpressionSyntax,
                        lambda.Body as BlockSyntax,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                    break;

                // Property / indexer getters: the "return type" is the
                // property's own type and the taint TARGET is the property
                // symbol itself. A getter whose expression body / `get` accessor
                // yields a nullable (`?.` / `??` / ternary / `return null`)
                // value must be emitted as `T?` (issue #2157).
                case PropertyDeclarationSyntax property:
                    SeedPropertyLikeReturnTaint(
                        model.GetDeclaredSymbol(property),
                        property.ExpressionBody?.Expression,
                        property.AccessorList,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                    break;

                case IndexerDeclarationSyntax indexer:
                    SeedPropertyLikeReturnTaint(
                        model.GetDeclaredSymbol(indexer),
                        indexer.ExpressionBody?.Expression,
                        indexer.AccessorList,
                        model,
                        tainted,
                        edges,
                        scalarTupleEdges);
                    break;
            }
        }
    }

    private static void SeedMethodLikeReturnTaint(
        ISymbol returnSymbol,
        ExpressionSyntax arrowBody,
        BlockSyntax body,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        if (returnSymbol is not IMethodSymbol { ReturnsVoid: false })
        {
            return;
        }

        ISymbol canonicalReturn = Canonical(returnSymbol);

        if (arrowBody != null)
        {
            ApplyReturnValue(
                canonicalReturn,
                arrowBody,
                model,
                tainted,
                edges,
                scalarTupleEdges,
                transitive: true);
        }

        foreach (ReturnStatementSyntax statement in EnumerateOwnReturns(body))
        {
            if (statement.Expression != null)
            {
                ApplyReturnValue(
                    canonicalReturn,
                    statement.Expression,
                    model,
                    tainted,
                    edges,
                    scalarTupleEdges,
                    transitive: true);
            }
        }

        // Issue #3501: an ITERATOR'S yields are its returns for element-taint
        // purposes — `yield return null` (or yielding a promoted-nullable
        // value) makes the iterator's ELEMENT nullable, which the translator
        // renders as `sequence[T?]`. Without this, the signature stayed
        // `sequence[T]` while the yield-seam bridge stood down (the method
        // looked promoted), leaving a bare `T? -> T` at every guarded yield.
        foreach (SyntaxNode descendant in body?.DescendantNodes(
            n => n is not (LocalFunctionStatementSyntax or AnonymousFunctionExpressionSyntax))
            ?? System.Linq.Enumerable.Empty<SyntaxNode>())
        {
            if (descendant is YieldStatementSyntax { Expression: { } yielded }
                && descendant.IsKind(SyntaxKind.YieldReturnStatement))
            {
                // Issue #3700: a yield that a syntactic null-check guard proves
                // non-null yields no evidence about the ELEMENT. The canonical
                // shape is `var child = (T)p.GetValue(o); if (child != null) {
                // yield return child; }` — the local is nullable because the
                // reflective read lowers to `as`, but the element never is.
                // Promoting it anyway widens the iterator's element to `T?`,
                // and that `T?` then escapes through every `foreach` variable
                // and recursive call the sequence feeds (gsc GS0154). The
                // repair belongs at the DECLARATION, exactly as it does for a
                // guarded constructor argument above: gsc's own smart-cast
                // narrows the same guarded read at the yield seam, so standing
                // the promotion down reintroduces no `T? -> T`.
                if (IsNullGuardDominatedRead(yielded, model))
                {
                    continue;
                }

                ApplyReturnValue(
                    canonicalReturn,
                    yielded,
                    model,
                    tainted,
                    edges,
                    scalarTupleEdges,
                    transitive: true);
            }
        }
    }

    private static void SeedPropertyLikeReturnTaint(
        IPropertySymbol propertySymbol,
        ExpressionSyntax propertyArrowBody,
        AccessorListSyntax accessorList,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges)
    {
        // Only reference-typed, not-already-nullable property/indexer types are
        // governed by this analysis; value types and `T?` declarations are left
        // untouched.
        if (propertySymbol is not { Type.IsReferenceType: true } ||
            propertySymbol.Type.NullableAnnotation == NullableAnnotation.Annotated)
        {
            return;
        }

        ISymbol canonicalReturn = Canonical(propertySymbol);

        // A property/indexer getter is direct-taint always: a syntactically
        // nullable body (`?.` / `??`-with-nullable-fallback / ternary /
        // `return null`) promotes the property to `T?` (issue #2157).
        //
        // Issue #2167: it is ALSO transitive for a property that neither
        // overrides a base member nor implements an interface member — a getter
        // that returns a nullable-returning method / forwards a tainted
        // declaration (e.g. `MotherboardInfo.InstallDate` returning
        // `ConvertToDateTime(...)` whose own return is `string?`) must itself be
        // `T?`, otherwise gsc rejects the `T? -> T` return (GS0156). For an
        // OVERRIDE / interface implementation we keep the direct-taint-only
        // behavior and rely on the translator's null-forgiveness pass (issue
        // #1354) to assert the forwarded value non-null, preserving the property
        // contract with the base / interface declaration.
        //
        // Issue #914 (oblivious sink): a NON-CONTRACT getter that merely FORWARDS
        // a promoted-nullable field/local/parameter (e.g. `TextWriter Writer =>
        // logStreamWriter;` where the backing field is a promoted `StreamWriter?`
        // — null-assigned in `CloseWriter`) must itself be `T?`, otherwise the
        // `StreamWriter? -> TextWriter` getter return is rejected (GS0155). Such
        // a property genuinely can be null, so field/local/param forwarding is
        // followed (`SourceScope.CallsAndNonPropertyDeclarations`); every
        // downstream member use (`Writer.WriteLine(...)`) then gets its `!!`
        // assertion from the translator's null-forgiveness pass, which keys off
        // the same promotion. Forwarding ANOTHER PROPERTY is deliberately NOT
        // followed, so `string Forward => Work;` keeps its declared type and the
        // #1354 / #2167 property-contract guardrail is preserved. A contract
        // member stays direct-taint-only (transitive is false below, so the
        // forwarding edges are not recorded for it regardless).
        bool transitive = !ImplementsBaseOrInterfaceMember(propertySymbol);

        // `Prop => expr;`
        if (propertyArrowBody != null)
        {
            ApplyReturnValue(
                canonicalReturn,
                propertyArrowBody,
                model,
                tainted,
                edges,
                scalarTupleEdges,
                transitive,
                SourceScope.CallsAndNonPropertyDeclarations);
        }

        // Only the `get` accessor produces the property value; `set`/`init`
        // return void and are ignored.
        AccessorDeclarationSyntax getter = accessorList?.Accessors
            .FirstOrDefault(a => a.IsKind(SyntaxKind.GetAccessorDeclaration));
        if (getter == null)
        {
            return;
        }

        // `get => expr;`
        if (getter.ExpressionBody?.Expression is ExpressionSyntax getterArrow)
        {
            ApplyReturnValue(
                canonicalReturn,
                getterArrow,
                model,
                tainted,
                edges,
                scalarTupleEdges,
                transitive,
                SourceScope.CallsAndNonPropertyDeclarations);
        }

        // `get { ... return x; }`
        foreach (ReturnStatementSyntax statement in EnumerateOwnReturns(getter.Body))
        {
            if (statement.Expression != null)
            {
                ApplyReturnValue(
                    canonicalReturn,
                    statement.Expression,
                    model,
                    tainted,
                    edges,
                    scalarTupleEdges,
                    transitive,
                    SourceScope.CallsAndNonPropertyDeclarations);
            }
        }
    }

    // Whether the property/indexer overrides a base member or implements an
    // interface member (explicitly or implicitly). Such a member's emitted G#
    // return type must stay in lock-step with the base / interface declaration,
    // so it is excluded from TRANSITIVE return promotion (issue #2167 guardrail;
    // preserves issue #2157 / #1354 behavior for contract members).
    private static bool ImplementsBaseOrInterfaceMember(IPropertySymbol property)
    {
        if (property.IsOverride || !property.ExplicitInterfaceImplementations.IsDefaultOrEmpty)
        {
            return true;
        }

        INamedTypeSymbol containingType = property.ContainingType;
        if (containingType == null)
        {
            return false;
        }

        foreach (INamedTypeSymbol iface in containingType.AllInterfaces)
        {
            foreach (ISymbol member in iface.GetMembers())
            {
                if (member is IPropertySymbol
                    && SymbolEqualityComparer.Default.Equals(
                        containingType.FindImplementationForInterfaceMember(member),
                        property))
                {
                    return true;
                }
            }
        }

        return false;
    }

    /// <summary>
    /// Issue #2285: for every source-declared type in <paramref name="compilation"/>
    /// that implements an interface, records BIDIRECTIONAL taint edges between
    /// each reference-typed interface property and the member that implements
    /// it, so the two endpoints of the same logical contract always reach the
    /// SAME tainted-ness in the fixpoint below — cs2gs must never promote only
    /// one side (the interface property's `T` vs. the implementation's `T?`),
    /// since gsc's Kotlin-style get-only-property variance rejects a non-null
    /// interface contract satisfied by a nullable member (GS0187, tightened by
    /// the #2150/#2284 follow-up). Both directions are recorded (not just the
    /// sound "impl nullable -> widen the interface" direction) so the two
    /// endpoints CONVERGE regardless of which side taint was originally seeded
    /// on (e.g. a caller might null-check through the INTERFACE-typed reference
    /// rather than the concrete type).
    /// <para>
    /// A C# record's positional parameter is a distinct <see cref="ISymbol"/>
    /// from its synthesized auto-property (the one
    /// <c>INamedTypeSymbol.FindImplementationForInterfaceMember</c>
    /// reports as the interface-member implementation) — yet cs2gs maps the
    /// PARAMETER's own type, not the property's, to the emitted G# primary-
    /// constructor parameter (<see cref="CSharpToGSharpTranslator.DeclarationVisitor.MapParameter"/>).
    /// The synthesized property's declaring syntax reference IS the parameter
    /// syntax node itself for a positional record member, so the corresponding
    /// <see cref="IParameterSymbol"/> is resolved from it and wired into the
    /// same edge set, generalizing this fix beyond ordinary classes/properties
    /// to record positional parameters.
    /// </para>
    /// </summary>
    /// <param name="compilation">The C# compilation being translated.</param>
    /// <param name="edges">The taint-edge list to append to.</param>
    private static void CollectInterfaceImplementationEdges(
        Compilation compilation,
        List<(ISymbol Target, ISymbol Source)> edges)
    {
        foreach (INamedTypeSymbol type in EnumerateSourceNamedTypes(compilation))
        {
            if (type.TypeKind is not (TypeKind.Class or TypeKind.Struct) || type.AllInterfaces.IsDefaultOrEmpty)
            {
                continue;
            }

            foreach (INamedTypeSymbol iface in type.AllInterfaces)
            {
                foreach (ISymbol member in iface.GetMembers())
                {
                    switch (member)
                    {
                        case IPropertySymbol interfaceProperty:
                            CollectInterfacePropertyEdges(compilation, type, interfaceProperty, edges);
                            break;

                        case IMethodSymbol interfaceMethod:
                            CollectInterfaceMethodEdges(type, interfaceMethod, edges);
                            break;
                    }
                }
            }
        }
    }

    private static void CollectInterfacePropertyEdges(
        Compilation compilation,
        INamedTypeSymbol type,
        IPropertySymbol interfaceProperty,
        List<(ISymbol Target, ISymbol Source)> edges)
    {
        if (type.FindImplementationForInterfaceMember(interfaceProperty) is not IPropertySymbol implementingProperty)
        {
            return;
        }

        if (IsEligibleScalarTarget(interfaceProperty))
        {
            ISymbol interfaceCanonical = Canonical(interfaceProperty);
            ISymbol implCanonical = Canonical(implementingProperty);
            edges.Add((interfaceCanonical, implCanonical));
            edges.Add((implCanonical, interfaceCanonical));

            IParameterSymbol positionalParameter = FindPositionalRecordParameter(compilation, implementingProperty);
            if (positionalParameter != null)
            {
                ISymbol paramCanonical = Canonical(positionalParameter);
                edges.Add((interfaceCanonical, paramCanonical));
                edges.Add((paramCanonical, interfaceCanonical));
            }
        }

        AddParameterContractEdges(interfaceProperty.Parameters, implementingProperty.Parameters, edges);
    }

    // Issue #2423: the method-return analog of
    // <see cref="CollectInterfacePropertyEdges"/>. `CollectInterfaceImplementationEdges`
    // previously handled ONLY properties, so a method that implements an
    // interface member had no synchronization at all: `SeedMethodLikeReturnTaint`
    // (unlike its property counterpart) applies UNCONDITIONAL transitive
    // return-taint promotion to every method, including one that implements an
    // interface — so an implementation whose body forwards a tainted call (e.g.
    // an `async Task&lt;T&gt;` method delegating to a sibling overload that can
    // return null) is correctly promoted to `T?`, but the interface declaration
    // it implements — which has no body of its own to seed taint from — never
    // is, producing an internally-inconsistent translation gsc's Kotlin-style
    // interface-conformance check rejects (GS0187: "does not implement interface
    // method"). Only an ORDINARY method member is considered (interface property
    // accessors surface as <see cref="IMethodSymbol"/> too via
    // <see cref="ITypeSymbol.GetMembers()"/> and are already handled by the
    // property edge above). The eligibility check is keyed off the UNWRAPPED
    // `async Task&lt;T&gt;`/`ValueTask&lt;T&gt;` result type (mirroring
    // <c>CSharpToGSharpTranslator.PromoteAwaitedReturnIfTainted</c>'s own
    // unwrap), since the interface method symbol's own <c>ReturnType</c> is the
    // `Task&lt;T&gt;` envelope regardless of the implementing method's `async`
    // modifier (a signature-level fact, not an implementation detail) — so a
    // value-typed `Task&lt;int&gt;` is correctly left untouched, exactly like the
    // synchronous case. Both directions are recorded (mirroring the property
    // fix) so the two endpoints always converge to the same tainted-ness
    // regardless of which side (interface or implementation) the taint was
    // originally seeded on.
    private static void CollectInterfaceMethodEdges(
        INamedTypeSymbol type,
        IMethodSymbol interfaceMethod,
        List<(ISymbol Target, ISymbol Source)> edges)
    {
        if (interfaceMethod.MethodKind != MethodKind.Ordinary
            || type.FindImplementationForInterfaceMember(interfaceMethod) is not IMethodSymbol implementingMethod)
        {
            return;
        }

        AddReturnContractEdges(interfaceMethod, implementingMethod, edges);

        AddParameterContractEdges(interfaceMethod.Parameters, implementingMethod.Parameters, edges);
    }

    private static void CollectOverrideContractEdges(
        Compilation compilation,
        List<(ISymbol Target, ISymbol Source)> edges)
    {
        foreach (INamedTypeSymbol type in EnumerateSourceNamedTypes(compilation))
        {
            foreach (IMethodSymbol method in type.GetMembers().OfType<IMethodSymbol>())
            {
                if (method.MethodKind == MethodKind.Ordinary
                    && method.OverriddenMethod is IMethodSymbol overridden)
                {
                    AddReturnContractEdges(method, overridden, edges);
                    AddParameterContractEdges(method.Parameters, overridden.Parameters, edges);
                }
            }

            foreach (IPropertySymbol property in type.GetMembers().OfType<IPropertySymbol>())
            {
                if (property.OverriddenProperty is IPropertySymbol overridden)
                {
                    AddParameterContractEdges(property.Parameters, overridden.Parameters, edges);
                }
            }
        }
    }

    private static void AddReturnContractEdges(
        IMethodSymbol first,
        IMethodSymbol second,
        List<(ISymbol Target, ISymbol Source)> edges)
    {
        ITypeSymbol effectiveReturnType = UnwrapAwaitedType(first.ReturnType);
        if (first.ReturnsVoid
            || second.ReturnsVoid
            || effectiveReturnType is not { IsReferenceType: true }
            || effectiveReturnType.NullableAnnotation == NullableAnnotation.Annotated)
        {
            return;
        }

        ISymbol firstCanonical = Canonical(first);
        ISymbol secondCanonical = Canonical(second);
        edges.Add((firstCanonical, secondCanonical));
        edges.Add((secondCanonical, firstCanonical));
    }

    private static void AddParameterContractEdges(
        ImmutableArray<IParameterSymbol> first,
        ImmutableArray<IParameterSymbol> second,
        List<(ISymbol Target, ISymbol Source)> edges)
    {
        int count = System.Math.Min(first.Length, second.Length);
        for (int i = 0; i < count; i++)
        {
            if (!IsEligibleScalarTarget(first[i]) || !IsEligibleScalarTarget(second[i]))
            {
                continue;
            }

            ISymbol firstCanonical = Canonical(first[i]);
            ISymbol secondCanonical = Canonical(second[i]);
            edges.Add((firstCanonical, secondCanonical));
            edges.Add((secondCanonical, firstCanonical));
        }
    }

    private static void CollectTupleContractEdges(
        Compilation compilation,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges)
    {
        foreach (INamedTypeSymbol type in EnumerateSourceNamedTypes(compilation))
        {
            foreach (IMethodSymbol method in type.GetMembers().OfType<IMethodSymbol>())
            {
                if (method.MethodKind != MethodKind.Ordinary
                    || !TryGetTupleType(method, out INamedTypeSymbol methodTuple))
                {
                    continue;
                }

                if (method.OverriddenMethod is IMethodSymbol overridden
                    && TryGetTupleType(overridden, out INamedTypeSymbol overriddenTuple))
                {
                    AddTupleContractPair(
                        method,
                        methodTuple,
                        overridden,
                        overriddenTuple,
                        tupleTainted,
                        tupleEdges);
                }
            }

            foreach (INamedTypeSymbol iface in type.AllInterfaces)
            {
                foreach (IMethodSymbol interfaceMethod in iface.GetMembers().OfType<IMethodSymbol>())
                {
                    if (interfaceMethod.MethodKind != MethodKind.Ordinary
                        || !TryGetTupleType(interfaceMethod, out INamedTypeSymbol interfaceTuple)
                        || type.FindImplementationForInterfaceMember(interfaceMethod) is not IMethodSymbol implementation
                        || !TryGetTupleType(implementation, out INamedTypeSymbol implementationTuple))
                    {
                        continue;
                    }

                    AddTupleContractPair(
                        interfaceMethod,
                        interfaceTuple,
                        implementation,
                        implementationTuple,
                        tupleTainted,
                        tupleEdges);
                }
            }
        }
    }

    private static void AddTupleContractPair(
        IMethodSymbol first,
        INamedTypeSymbol firstTuple,
        IMethodSymbol second,
        INamedTypeSymbol secondTuple,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges)
    {
        ISymbol firstCanonical = Canonical(first);
        ISymbol secondCanonical = Canonical(second);
        AddTupleShapeEdges(
            firstCanonical,
            firstTuple,
            string.Empty,
            secondCanonical,
            secondTuple,
            string.Empty,
            tupleTainted,
            tupleEdges);
        AddTupleShapeEdges(
            secondCanonical,
            secondTuple,
            string.Empty,
            firstCanonical,
            firstTuple,
            string.Empty,
            tupleTainted,
            tupleEdges);
    }

    // Issue #2504: a source named delegate's Invoke return is a declaration
    // contract just like an interface/base method return. Roslyn exposes the
    // selected method group or synthesized lambda method and the converted
    // delegate type at every conversion seam, independent of whether that seam
    // is an initializer, assignment, argument, return, or multicast update.
    private static void CollectDelegateReturnContractEdges(
        Compilation compilation,
        SyntaxNode root,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, ISymbol Source)> delegateReturnEdges,
        HashSet<TupleElementKey> tupleTainted,
        List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges)
    {
        foreach (ExpressionSyntax expression in root.DescendantNodes().OfType<ExpressionSyntax>())
        {
            bool isLambda = expression is AnonymousFunctionExpressionSyntax;
            if (!isLambda && model.GetMemberGroup(expression).IsDefaultOrEmpty)
            {
                continue;
            }

            if (model.GetTypeInfo(expression).ConvertedType is not INamedTypeSymbol delegateType
                || delegateType.TypeKind != TypeKind.Delegate
                || !IsSourceDelegateType(compilation, delegateType)
                || delegateType.DelegateInvokeMethod is not IMethodSymbol invoke
                || invoke.ReturnsVoid)
            {
                continue;
            }

            IMethodSymbol source = model.GetSymbolInfo(expression).Symbol as IMethodSymbol;
            if (source == null || source.ReturnsVoid)
            {
                continue;
            }

            if (TryGetTupleType(invoke, out INamedTypeSymbol invokeTuple)
                && TryGetTupleType(source, out INamedTypeSymbol sourceTuple))
            {
                AddTupleContractPair(
                    invoke,
                    invokeTuple,
                    source,
                    sourceTuple,
                    tupleTainted,
                    tupleEdges);
                continue;
            }

            if (!IsEligibleScalarTarget(invoke))
            {
                continue;
            }

            ISymbol invokeCanonical = Canonical(invoke);
            ISymbol sourceCanonical = Canonical(source);
            edges.Add((invokeCanonical, sourceCanonical));
            edges.Add((sourceCanonical, invokeCanonical));
            delegateReturnEdges.Add((invokeCanonical, sourceCanonical));
            delegateReturnEdges.Add((sourceCanonical, invokeCanonical));

            if (UnwrapAwaitedType(source.ReturnType).NullableAnnotation == NullableAnnotation.Annotated)
            {
                tainted.Add(invokeCanonical);
            }
        }
    }

    private static bool IsSourceDelegateType(Compilation compilation, INamedTypeSymbol delegateType)
    {
        SourceAssemblySet assemblies = SourceAssemblies.GetValue(
            compilation,
            static current => new SourceAssemblySet(current.Assembly.Identity.GetDisplayName()));
        lock (assemblies.Names)
        {
            return assemblies.Names.Contains(delegateType.ContainingAssembly.Identity.GetDisplayName());
        }
    }

    private static void RegisterSourceAssemblies(
        CSharpCompilation compilation,
        IReadOnlyList<CSharpCompilation> siblingCompilations)
    {
        var compilations = new List<CSharpCompilation> { compilation };
        if (siblingCompilations != null)
        {
            compilations.AddRange(siblingCompilations.Where(candidate => candidate != null));
        }

        string[] names = compilations
            .Select(candidate => candidate.Assembly.Identity.GetDisplayName())
            .Distinct(System.StringComparer.Ordinal)
            .ToArray();

        foreach (CSharpCompilation candidate in compilations)
        {
            SourceAssemblySet assemblies = SourceAssemblies.GetValue(
                candidate,
                static current => new SourceAssemblySet(current.Assembly.Identity.GetDisplayName()));
            bool changed = false;
            lock (assemblies.Names)
            {
                foreach (string name in names)
                {
                    changed |= assemblies.Names.Add(name);
                }
            }

            if (changed)
            {
                Cache.Remove(candidate);
            }
        }
    }

    // Unwraps a (non-generic-parameter) `System.Threading.Tasks.Task<T>` or
    // `System.Threading.Tasks.ValueTask<T>` return type to its awaited result
    // `T`, mirroring `CSharpToGSharpTranslator.PromoteAwaitedReturnIfTainted`'s
    // own unwrap so an interface method's `Task<T>`-declared signature is judged
    // on the SAME effective type an `async` implementation's return is. Any
    // other type (including the non-generic `Task`/`ValueTask`, and a
    // value-typed `Task<int>`, whose `T` is filtered out by the reference-type
    // eligibility check at the call site) is returned unchanged.
    private static ITypeSymbol UnwrapAwaitedType(ITypeSymbol returnType)
    {
        if (returnType is INamedTypeSymbol { IsGenericType: true, TypeArguments.Length: 1 } named
            && named.OriginalDefinition.SpecialType != SpecialType.System_Nullable_T
            && (named.Name == "Task" || named.Name == "ValueTask")
            && named.ContainingNamespace?.ToDisplayString() == "System.Threading.Tasks")
        {
            return named.TypeArguments[0];
        }

        return returnType;
    }

    // A record's positional-parameter property has a declaring syntax
    // reference that IS the `ParameterSyntax` node itself (verified against
    // Roslyn's actual behavior), so the corresponding primary-constructor
    // `IParameterSymbol` — the symbol cs2gs's own primary-constructor mapping
    // promotes — is resolved by re-binding that same syntax node. Returns
    // `null` for an ordinary (non-positional) property.
    private static IParameterSymbol FindPositionalRecordParameter(Compilation compilation, IPropertySymbol property)
    {
        foreach (SyntaxReference reference in property.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax() is ParameterSyntax parameterSyntax)
            {
                SemanticModel model = compilation.GetSemanticModel(parameterSyntax.SyntaxTree);
                if (model.GetDeclaredSymbol(parameterSyntax) is IParameterSymbol parameterSymbol)
                {
                    return parameterSymbol;
                }
            }
        }

        return null;
    }

    // Every source-declared named type reachable from the compilation's
    // assembly, walking nested types too (mirrors
    // `CSharpToGSharpTranslator.EnumerateNamedTypes`, duplicated locally so
    // this analyzer stays a self-contained, independently testable unit).
    private static IEnumerable<INamedTypeSymbol> EnumerateSourceNamedTypes(Compilation compilation)
    {
        foreach (INamedTypeSymbol type in EnumerateNamespaceTypes(compilation.Assembly.GlobalNamespace))
        {
            yield return type;
        }
    }

    private static IEnumerable<INamedTypeSymbol> EnumerateNamespaceTypes(INamespaceSymbol ns)
    {
        foreach (INamedTypeSymbol type in ns.GetTypeMembers())
        {
            foreach (INamedTypeSymbol typeOrNested in EnumerateTypeAndNested(type))
            {
                yield return typeOrNested;
            }
        }

        foreach (INamespaceSymbol nested in ns.GetNamespaceMembers())
        {
            foreach (INamedTypeSymbol type in EnumerateNamespaceTypes(nested))
            {
                yield return type;
            }
        }
    }

    private static IEnumerable<INamedTypeSymbol> EnumerateTypeAndNested(INamedTypeSymbol type)
    {
        yield return type;
        foreach (INamedTypeSymbol nested in type.GetTypeMembers())
        {
            foreach (INamedTypeSymbol nestedOrDeeper in EnumerateTypeAndNested(nested))
            {
                yield return nestedOrDeeper;
            }
        }
    }

    private static void ApplyReturnValue(
        ISymbol returnSymbol,
        ExpressionSyntax value,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges,
        bool transitive,
        SourceScope scope = SourceScope.AllSources)
    {
        if (IsDirectlyNullable(value, model))
        {
            tainted.Add(returnSymbol);
        }
        else if (transitive)
        {
            CollectScalarValueFlow(
                returnSymbol,
                value,
                model,
                tainted,
                edges,
                scalarTupleEdges,
                scope);
        }
    }

    // The `return` statements that belong to <paramref name="body"/> itself,
    // excluding those inside a nested lambda / local function (which have their
    // own return contract).
    private static IEnumerable<ReturnStatementSyntax> EnumerateOwnReturns(BlockSyntax body)
    {
        if (body == null)
        {
            yield break;
        }

        foreach (SyntaxNode descendant in body.DescendantNodes(
            n => n is not (LocalFunctionStatementSyntax or AnonymousFunctionExpressionSyntax)))
        {
            if (descendant is ReturnStatementSyntax statement)
            {
                yield return statement;
            }
        }
    }

    // Adds transitive edges `target <- source` for every declaration symbol the
    // value expression reads (identifier/member) or the method it calls
    // (invocation), unwrapping the compositional forms `??`, `?:`, `(cast)`.
    // <paramref name="scope"/> selects which forwarding sources are followed
    // (see <see cref="SourceScope"/>). This is the interprocedural edge used for
    // property/indexer getters (issue #2167 / #914): a getter returning a
    // nullable-returning method call is promoted; a non-contract getter that
    // forwards a tainted field/local/param is promoted; but a getter that merely
    // FORWARDS another PROPERTY keeps its declared type and relies on the
    // translator's null-forgiveness `!!` pass (issue #1354 / #2157), preserving
    // the property contract.
    private static void AddEdges(
        ISymbol target,
        ExpressionSyntax value,
        SemanticModel model,
        List<(ISymbol Target, ISymbol Source)> edges,
        SourceScope scope = SourceScope.AllSources)
    {
        foreach (ISymbol source in ResolveSources(value, model, scope))
        {
            edges.Add((target, source));
        }
    }

    // Issue #2490: a scalar declaration/return/parameter can receive one
    // independently-tainted leaf from the tuple graph introduced for #2469.
    // Preserve the scalar expression-shape rules used by ResolveSources while
    // recording tuple-member reads as element-path edges instead of collapsing
    // them to the synthesized ValueTuple field symbol.
    private static void CollectScalarValueFlow(
        ISymbol target,
        ExpressionSyntax value,
        SemanticModel model,
        HashSet<ISymbol> tainted,
        List<(ISymbol Target, ISymbol Source)> edges,
        List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges,
        SourceScope scope = SourceScope.AllSources)
    {
        if (!IsEligibleScalarTarget(target))
        {
            return;
        }

        // Issue #2504/#2496: assigning or returning a lambda/method group moves
        // the callable object, not the value produced by invoking it. Its result
        // taint is wired separately to the converted named delegate's Invoke
        // contract; it must never make the delegate envelope itself nullable.
        if (IsCallableValueExpression(value, model))
        {
            return;
        }

        if (IsDirectlyNullable(value, model))
        {
            tainted.Add(target);
            return;
        }

        switch (value)
        {
            case ParenthesizedExpressionSyntax parenthesized:
                CollectScalarValueFlow(target, parenthesized.Expression, model, tainted, edges, scalarTupleEdges, scope);
                return;

            case AwaitExpressionSyntax awaitExpression:
                CollectScalarValueFlow(target, awaitExpression.Expression, model, tainted, edges, scalarTupleEdges, scope);
                return;

            case PostfixUnaryExpressionSyntax suppress
                when suppress.IsKind(SyntaxKind.SuppressNullableWarningExpression):
                return;

            case BinaryExpressionSyntax coalesce
                when coalesce.IsKind(SyntaxKind.CoalesceExpression):
                CollectScalarValueFlow(target, coalesce.Right, model, tainted, edges, scalarTupleEdges, scope);
                return;

            case ConditionalExpressionSyntax conditional:
                CollectScalarValueFlow(target, conditional.WhenTrue, model, tainted, edges, scalarTupleEdges, scope);
                CollectScalarValueFlow(target, conditional.WhenFalse, model, tainted, edges, scalarTupleEdges, scope);
                return;

            case SwitchExpressionSyntax switchExpression:
                foreach (SwitchExpressionArmSyntax arm in switchExpression.Arms)
                {
                    CollectScalarValueFlow(target, arm.Expression, model, tainted, edges, scalarTupleEdges, scope);
                }

                return;

            case CastExpressionSyntax cast:
                CollectScalarValueFlow(target, cast.Expression, model, tainted, edges, scalarTupleEdges, scope);
                return;
        }

        if (scope != SourceScope.CallsOnly
            && TryResolveTupleElementSource(value, model, out TupleElementKey tupleSource))
        {
            scalarTupleEdges.Add((target, tupleSource));
            return;
        }

        AddEdges(target, value, model, edges, scope);
    }

    private static bool IsCallableValueExpression(ExpressionSyntax expression, SemanticModel model)
    {
        while (expression is ParenthesizedExpressionSyntax parenthesized)
        {
            expression = parenthesized.Expression;
        }

        return expression is AnonymousFunctionExpressionSyntax
            || !model.GetMemberGroup(expression).IsDefaultOrEmpty;
    }

    private static IEnumerable<ISymbol> ResolveSources(
        ExpressionSyntax expression,
        SemanticModel model,
        SourceScope scope = SourceScope.AllSources)
    {
        switch (expression)
        {
            case null:
                yield break;

            case ParenthesizedExpressionSyntax paren:
                foreach (ISymbol source in ResolveSources(paren.Expression, model, scope))
                {
                    yield return source;
                }

                break;

            // `await expr`: issue #2421 — a `return await TaintedAsyncCall()`
            // must forward the SAME transitive edge a synchronous `return
            // TaintedCall()` already gets, or the enclosing async method never
            // converges to tainted despite forwarding a provably-nullable
            // awaited result (mirrors the identical unwrap in
            // IsDirectlyNullable above).
            case AwaitExpressionSyntax awaitExpression:
                foreach (ISymbol source in ResolveSources(awaitExpression.Expression, model, scope))
                {
                    yield return source;
                }

                break;

            case PostfixUnaryExpressionSyntax suppress
                when suppress.IsKind(SyntaxKind.SuppressNullableWarningExpression):
                yield break;

            // `a ?? b`: the result is `b`'s value when `a` is null.
            case BinaryExpressionSyntax coalesce
                when coalesce.IsKind(SyntaxKind.CoalesceExpression):
                foreach (ISymbol source in ResolveSources(coalesce.Right, model, scope))
                {
                    yield return source;
                }

                break;

            // `cond ? a : b`: either branch may flow through.
            case ConditionalExpressionSyntax ternary:
                foreach (ISymbol source in ResolveSources(ternary.WhenTrue, model, scope)
                    .Concat(ResolveSources(ternary.WhenFalse, model, scope)))
                {
                    yield return source;
                }

                break;

            // `x switch { ... }`: any arm's result value may flow through.
            case SwitchExpressionSyntax switchExpression:
                foreach (SwitchExpressionArmSyntax arm in switchExpression.Arms)
                {
                    foreach (ISymbol source in ResolveSources(arm.Expression, model, scope))
                    {
                        yield return source;
                    }
                }

                break;

            case CastExpressionSyntax cast:
                foreach (ISymbol source in ResolveSources(cast.Expression, model, scope))
                {
                    yield return source;
                }

                break;

            case InvocationExpressionSyntax invocation:
                if (model.GetSymbolInfo(invocation).Symbol is IMethodSymbol called
                    && !called.ReturnsVoid)
                {
                    yield return Canonical(called);
                }

                break;

            case IdentifierNameSyntax:
            case MemberAccessExpressionSyntax:
                if (scope == SourceScope.CallsOnly)
                {
                    yield break;
                }

                ISymbol symbol = model.GetSymbolInfo(expression).Symbol;
                if (symbol == null)
                {
                    break;
                }

                // A NON-CONTRACT getter follows field/local/param forwarding but
                // never PROPERTY forwarding (that would regress the #1354 /
                // #2167 property-contract guardrail).
                if (scope == SourceScope.CallsAndNonPropertyDeclarations
                    && symbol is IPropertySymbol)
                {
                    yield break;
                }

                if (IsValueDeclarationSymbol(symbol) || symbol is IMethodSymbol)
                {
                    yield return Canonical(symbol);
                }

                break;
        }
    }

    // Taints the declaration symbol an lvalue-ish expression binds to (the
    // receiver of a null-check / null-assignment / `?.`).
    private static void TaintTarget(ExpressionSyntax expression, SemanticModel model, HashSet<ISymbol> tainted)
    {
        ISymbol symbol = ResolveAssignable(expression, model);
        if (symbol != null)
        {
            tainted.Add(symbol);
        }
    }

    // Resolves the field/property/parameter/local a reference expression binds
    // to (canonicalized), or null when the expression is not a simple binding to
    // one of those (e.g. an element access, a method group, a `this`).
    // Issue #3501: true when <paramref name="value"/> is a bare local/parameter
    // read that an enclosing syntactic null-check guard proves non-null at this
    // exact use — either a surrounding `if (x != null) { …use… }` /
    // `if (x == null) {…} else { …use… }` branch (and the ternary forms), or a
    // PRECEDING early-exit guard in an enclosing block
    // (`if (x is null) { continue/return/break/throw; } …use…`). Mirrors the
    // translator-side `IsDominatedByNullCheckGuard` walk, extended with the
    // early-exit form, so a guarded read doesn't propagate its declaration's
    // taint through argument edges (gsc's own smart-cast narrows the same
    // guarded read on the G# side).
    private static bool IsNullGuardDominatedRead(ExpressionSyntax value, SemanticModel model)
    {
        ExpressionSyntax stripped = value;
        while (stripped is ParenthesizedExpressionSyntax paren)
        {
            stripped = paren.Expression;
        }

        if (stripped is not IdentifierNameSyntax identifier)
        {
            return false;
        }

        ISymbol symbol = model.GetSymbolInfo(identifier).Symbol;
        if (symbol is not ILocalSymbol && symbol is not IParameterSymbol)
        {
            return false;
        }

        for (SyntaxNode node = identifier; node != null; node = node.Parent)
        {
            switch (node.Parent)
            {
                case ElseClauseSyntax elseClause
                    when elseClause.Parent is IfStatementSyntax elseIf
                        && node == elseClause.Statement
                        && IsNullTestOf(elseIf.Condition, symbol, whenTrueIsNull: true):
                    return true;

                case IfStatementSyntax ifStatement
                    when node == ifStatement.Statement
                        && IsNullTestOf(ifStatement.Condition, symbol, whenTrueIsNull: false):
                    return true;

                case ConditionalExpressionSyntax ternary
                    when (node == ternary.WhenFalse && IsNullTestOf(ternary.Condition, symbol, whenTrueIsNull: true))
                        || (node == ternary.WhenTrue && IsNullTestOf(ternary.Condition, symbol, whenTrueIsNull: false)):
                    return true;
            }

            // A preceding sibling `if (x == null) <always-exits>` in an
            // enclosing block proves non-null for everything after it.
            if (node is StatementSyntax statement && node.Parent is BlockSyntax block)
            {
                int index = block.Statements.IndexOf(statement);
                for (int i = 0; i < index; i++)
                {
                    if (block.Statements[i] is IfStatementSyntax guard
                        && guard.Else is null
                        && IsNullTestOf(guard.Condition, symbol, whenTrueIsNull: true)
                        && AlwaysExits(guard.Statement))
                    {
                        return true;
                    }
                }
            }

            if (node is AccessorDeclarationSyntax
                or BaseMethodDeclarationSyntax
                or LocalFunctionStatementSyntax
                or AnonymousFunctionExpressionSyntax
                or ArrowExpressionClauseSyntax)
            {
                break;
            }
        }

        return false;
    }

    private static bool AlwaysExits(StatementSyntax statement) => statement switch
    {
        ReturnStatementSyntax or ContinueStatementSyntax or BreakStatementSyntax or ThrowStatementSyntax => true,
        BlockSyntax block => block.Statements.Count > 0 && AlwaysExits(block.Statements[^1]),
        _ => false,
    };

    // Matches `x == null` / `x is null` (whenTrueIsNull: true) and
    // `x != null` / `x is not null` (whenTrueIsNull: false) against
    // <paramref name="symbol"/> by identifier name.
    private static bool IsNullTestOf(ExpressionSyntax condition, ISymbol symbol, bool whenTrueIsNull)
    {
        while (condition is ParenthesizedExpressionSyntax paren)
        {
            condition = paren.Expression;
        }

        static bool IsSymbolIdentifier(ExpressionSyntax expression, ISymbol symbol)
        {
            while (expression is ParenthesizedExpressionSyntax inner)
            {
                expression = inner.Expression;
            }

            return expression is IdentifierNameSyntax id
                && string.Equals(id.Identifier.ValueText, symbol.Name, StringComparison.Ordinal);
        }

        static bool IsNullLiteral(ExpressionSyntax expression) =>
            expression is LiteralExpressionSyntax literal && literal.IsKind(SyntaxKind.NullLiteralExpression);

        switch (condition)
        {
            case BinaryExpressionSyntax binary
                when binary.IsKind(whenTrueIsNull ? SyntaxKind.EqualsExpression : SyntaxKind.NotEqualsExpression):
                return (IsSymbolIdentifier(binary.Left, symbol) && IsNullLiteral(binary.Right))
                    || (IsSymbolIdentifier(binary.Right, symbol) && IsNullLiteral(binary.Left));

            case IsPatternExpressionSyntax isPattern when IsSymbolIdentifier(isPattern.Expression, symbol):
                if (whenTrueIsNull)
                {
                    return isPattern.Pattern is ConstantPatternSyntax { Expression: LiteralExpressionSyntax nullPattern }
                        && nullPattern.IsKind(SyntaxKind.NullLiteralExpression);
                }

                return isPattern.Pattern is UnaryPatternSyntax { Pattern: ConstantPatternSyntax { Expression: LiteralExpressionSyntax notNullPattern } }
                    && notNullPattern.IsKind(SyntaxKind.NullLiteralExpression);

            default:
                return false;
        }
    }

    private static ISymbol ResolveAssignable(ExpressionSyntax expression, SemanticModel model)
    {
        switch (expression)
        {
            case ParenthesizedExpressionSyntax paren:
                return ResolveAssignable(paren.Expression, model);

            case IdentifierNameSyntax:
            case MemberAccessExpressionSyntax:
                ISymbol symbol = model.GetSymbolInfo(expression).Symbol;
                return symbol != null && IsValueDeclarationSymbol(symbol) ? Canonical(symbol) : null;

            default:
                return null;
        }
    }

    // Whether a reference expression is directly (syntactically or by declared
    // BCL annotation) nullable, independent of any other declaration's taint.
    // Mirrors the translator's IsNullableInitializer, plus the `null`/`default`
    // literal forms used in initializer/return positions.
    private static bool IsDirectlyNullable(ExpressionSyntax expression, SemanticModel model)
    {
        switch (expression)
        {
            case null:
                return false;

            case ParenthesizedExpressionSyntax paren:
                return IsDirectlyNullable(paren.Expression, model);

            // `await expr`: an awaited `Task<T>`'s own nullability is that of
            // T, which is exactly what the UNWRAPPED awaited expression's own
            // syntactic shape already answers here (mirrors ResolveSources'
            // identical unwrap immediately below, and the translator's
            // symmetric async-return unwrap in
            // CSharpToGSharpTranslator.PromoteAwaitedReturnIfTainted, issue
            // #2421). Without this, `return await x?.M();` inside an async
            // method would be treated as NOT directly nullable at all.
            case AwaitExpressionSyntax awaitExpression:
                return IsDirectlyNullable(awaitExpression.Expression, model);

            case PostfixUnaryExpressionSyntax suppress
                when suppress.IsKind(SyntaxKind.SuppressNullableWarningExpression):
                return false;

            case LiteralExpressionSyntax literal:
                return literal.IsKind(SyntaxKind.NullLiteralExpression)
                    || (literal.IsKind(SyntaxKind.DefaultLiteralExpression)
                        && IsReferenceLike(model.GetTypeInfo(literal).ConvertedType));

            case DefaultExpressionSyntax defaultExpression:
                return IsReferenceLike(model.GetTypeInfo(defaultExpression).Type);

            // `a?.b` / `a?[i]`.
            case ConditionalAccessExpressionSyntax:
                return true;

            // ADR-0160: `x as T` is a TESTING conversion — it yields null when the
            // runtime type does not match — so its value is always maybe-null,
            // whatever the compilation's nullable context says. In an oblivious
            // compilation Roslyn reports `NullableAnnotation.None` for it, so the
            // flow fallback below cannot see this; without the explicit case a
            // declaration whose value is an `as` result is never promoted. That
            // matters because gsc types `as` as `T?`: `string ToString() => … as
            // string;` must promote its return type to `string?` rather than be
            // asserted, since C# genuinely returns null there and `!!` would throw.
            case BinaryExpressionSyntax asExpression
                when asExpression.IsKind(SyntaxKind.AsExpression):
                return true;

            // `a ?? b`: nullable iff the `b` fallback is nullable.
            case BinaryExpressionSyntax coalesce
                when coalesce.IsKind(SyntaxKind.CoalesceExpression):
                return IsDirectlyNullable(coalesce.Right, model);

            // `cond ? a : b`: nullable iff either branch is.
            case ConditionalExpressionSyntax ternary:
                return IsDirectlyNullable(ternary.WhenTrue, model)
                    || IsDirectlyNullable(ternary.WhenFalse, model);

            // `x switch { ... }`: nullable iff any arm's result is (e.g. a
            // `_ => null` / `_ => default` fallback arm, or an arm forwarding
            // an already-nullable value).
            case SwitchExpressionSyntax switchExpression:
                foreach (SwitchExpressionArmSyntax arm in switchExpression.Arms)
                {
                    if (IsDirectlyNullable(arm.Expression, model))
                    {
                        return true;
                    }
                }

                return false;
        }

        // Flow nullability when the context happens to be enabled (inert in a
        // truly oblivious compilation, but harmless).
        TypeInfo info = model.GetTypeInfo(expression);
        if (info.Nullability.Annotation == NullableAnnotation.Annotated)
        {
            return true;
        }

        // Otherwise consult the bound symbol's DECLARED annotation, which
        // survives in BCL/source metadata regardless of the consuming context
        // (e.g. `AssemblyName.Name` and `Path.GetFileNameWithoutExtension(...)`
        // are declared `string?`).
        ISymbol symbol = model.GetSymbolInfo(expression).Symbol;
        ITypeSymbol symbolType = symbol switch
        {
            IMethodSymbol m => m.ReturnType,
            IPropertySymbol p => p.Type,
            IFieldSymbol f => f.Type,
            ILocalSymbol l => l.Type,
            IParameterSymbol pr => pr.Type,
            _ => null,
        };

        return symbolType is { IsReferenceType: true }
            && symbolType.NullableAnnotation == NullableAnnotation.Annotated;
    }

    private static bool IsReferenceLike(ITypeSymbol type) =>
        type is { IsReferenceType: true } || type is ITypeParameterSymbol;

    // The declaration kinds whose emitted reference type this analysis governs.
    private static bool IsValueDeclarationSymbol(ISymbol symbol) =>
        symbol is IFieldSymbol or IPropertySymbol or IParameterSymbol or ILocalSymbol;

    private static ISymbol Canonical(ISymbol symbol)
    {
        // A reduced extension-method invocation (`value.Ext(...)`) binds to the
        // REDUCED method symbol, whereas the extension's own declaration node
        // binds to the UNREDUCED static method; normalize to the unreduced
        // original so a return-taint keyed on the declaration matches a call-site
        // edge that reads it (issue #2113 — otherwise chained extension methods
        // like `values.FirstEtAlImpl(...)` never propagate their nullable return).
        if (symbol is IMethodSymbol method)
        {
            return (method.ReducedFrom ?? method).OriginalDefinition;
        }

        return symbol?.OriginalDefinition ?? symbol;
    }

    // `x is null` / `x is not null` constant pattern.
    private static bool IsNullConstantPattern(PatternSyntax pattern)
    {
        if (pattern is UnaryPatternSyntax unary && unary.IsKind(SyntaxKind.NotPattern))
        {
            pattern = unary.Pattern;
        }

        return pattern is ConstantPatternSyntax constant && IsNullLiteral(constant.Expression);
    }

    private static bool IsNullLiteral(ExpressionSyntax expression) =>
        expression is LiteralExpressionSyntax literal
            && literal.IsKind(SyntaxKind.NullLiteralExpression);

    // `null` or `null!` (a SuppressNullableWarning over a null literal).
    private static bool IsNullOrSuppressedNull(ExpressionSyntax expression)
    {
        if (expression is PostfixUnaryExpressionSyntax suppress
            && suppress.IsKind(SyntaxKind.SuppressNullableWarningExpression))
        {
            expression = suppress.Operand;
        }

        return IsNullLiteral(expression);
    }

    private readonly struct TupleElementKey
    {
        public TupleElementKey(ISymbol symbol, string path)
        {
            this.Symbol = Canonical(symbol);
            this.Path = path;
        }

        public ISymbol Symbol { get; }

        public string Path { get; }
    }

    private readonly struct ScalarQuery
    {
        public ScalarQuery(CSharpCompilation compilation, ISymbol symbol)
        {
            this.Compilation = compilation;
            this.Symbol = Canonical(symbol);
        }

        public CSharpCompilation Compilation { get; }

        public ISymbol Symbol { get; }
    }

    private readonly struct TupleElementQuery
    {
        public TupleElementQuery(CSharpCompilation compilation, TupleElementKey key)
        {
            this.Compilation = compilation;
            this.Key = key;
        }

        public CSharpCompilation Compilation { get; }

        public TupleElementKey Key { get; }
    }

    private sealed class TupleElementKeyComparer : IEqualityComparer<TupleElementKey>
    {
        public static TupleElementKeyComparer Instance { get; } = new();

        public bool Equals(TupleElementKey x, TupleElementKey y) =>
            SymbolEqualityComparer.Default.Equals(x.Symbol, y.Symbol)
                && string.Equals(x.Path, y.Path, System.StringComparison.Ordinal);

        public int GetHashCode(TupleElementKey obj)
        {
            int symbolHash = obj.Symbol == null
                ? 0
                : SymbolEqualityComparer.Default.GetHashCode(obj.Symbol);
            return System.HashCode.Combine(symbolHash, obj.Path);
        }
    }

    private sealed class ScalarQueryComparer : IEqualityComparer<ScalarQuery>
    {
        public static ScalarQueryComparer Instance { get; } = new();

        public bool Equals(ScalarQuery x, ScalarQuery y) =>
            ReferenceEquals(x.Compilation, y.Compilation)
                && SymbolEqualityComparer.Default.Equals(x.Symbol, y.Symbol);

        public int GetHashCode(ScalarQuery obj)
        {
            int symbolHash = obj.Symbol == null
                ? 0
                : SymbolEqualityComparer.Default.GetHashCode(obj.Symbol);
            return System.HashCode.Combine(
                System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode(obj.Compilation),
                symbolHash);
        }
    }

    private sealed class TupleElementQueryComparer : IEqualityComparer<TupleElementQuery>
    {
        public static TupleElementQueryComparer Instance { get; } = new();

        public bool Equals(TupleElementQuery x, TupleElementQuery y) =>
            ReferenceEquals(x.Compilation, y.Compilation)
                && TupleElementKeyComparer.Instance.Equals(x.Key, y.Key);

        public int GetHashCode(TupleElementQuery obj) =>
            System.HashCode.Combine(
                System.Runtime.CompilerServices.RuntimeHelpers.GetHashCode(obj.Compilation),
                TupleElementKeyComparer.Instance.GetHashCode(obj.Key));
    }

    private sealed class TaintResult
    {
        public TaintResult(
            HashSet<ISymbol> tainted,
            HashSet<TupleElementKey> tupleTainted,
            List<(TupleElementKey Target, TupleElementKey Source)> tupleEdges,
            List<(TupleElementKey Target, ISymbol Source)> tupleScalarEdges,
            List<(ISymbol Target, TupleElementKey Source)> scalarTupleEdges,
            List<(ISymbol Target, ISymbol Source)> delegateReturnEdges)
        {
            this.Tainted = tainted;
            this.TupleTainted = tupleTainted;
            this.TupleEdges = tupleEdges;
            this.TupleScalarEdges = tupleScalarEdges;
            this.ScalarTupleEdges = scalarTupleEdges;
            this.DelegateReturnEdges = delegateReturnEdges;
        }

        public HashSet<ISymbol> Tainted { get; }

        public HashSet<TupleElementKey> TupleTainted { get; }

        public List<(TupleElementKey Target, TupleElementKey Source)> TupleEdges { get; }

        public List<(TupleElementKey Target, ISymbol Source)> TupleScalarEdges { get; }

        public List<(ISymbol Target, TupleElementKey Source)> ScalarTupleEdges { get; }

        public List<(ISymbol Target, ISymbol Source)> DelegateReturnEdges { get; }
    }

    private sealed class SourceAssemblySet
    {
        public SourceAssemblySet(string currentAssembly)
        {
            this.Names = new HashSet<string>(System.StringComparer.Ordinal) { currentAssembly };
        }

        public HashSet<string> Names { get; }
    }
